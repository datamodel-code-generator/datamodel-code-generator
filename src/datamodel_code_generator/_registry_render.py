"""Private rendering helpers for registry modules."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from textwrap import fill
from typing import TYPE_CHECKING, Any, Literal

from datamodel_code_generator._json_output import dump_json

if TYPE_CHECKING:
    from collections.abc import Callable, Iterable, Mapping, Sequence


@dataclass(frozen=True)
class _RegistryPage:
    """How a registry lists its entries: the summary columns and cells, the detail bullets and the Markdown page.

    ``table_notes`` also lists the note of each entry after the text table.
    """

    title: str
    script: str
    intro: str
    columns: tuple[str, ...]
    cells: Callable[[Any], Sequence[str]]
    details: Callable[[Any], Iterable[tuple[str, str | None]]]
    table_notes: bool = False


def _render_registry_json(entries: Iterable[Mapping[str, object]]) -> str:
    """Render registry entries as stable JSON."""
    return dump_json(list(entries), "sorted-ascii")


def _render_registry_entries_json(entries: Iterable[Any]) -> str:
    """Render registry entries, each a dataclass of primitive values, as stable JSON."""
    return _render_registry_json(map(asdict, entries))


def _render_registry_table(entries: Sequence[Any], page: _RegistryPage) -> str:
    """Render registry entries as a stable plain text table, then their wrapped notes when the page lists them."""
    rows = [page.columns, *map(page.cells, entries)]
    widths = [max(len(row[index]) for row in rows) for index in range(len(rows[0]))]
    lines = [
        "  ".join(value.ljust(widths[index]) for index, value in enumerate(rows[0])).rstrip(),
        "  ".join("-" * width for width in widths),
    ]
    lines.extend("  ".join(value.ljust(widths[index]) for index, value in enumerate(row)).rstrip() for row in rows[1:])
    if page.table_notes:
        lines += ["", "Notes:"]
        lines.extend(
            f"{entry.id}:\n{fill(note, width=100, initial_indent='  ', subsequent_indent='  ', break_on_hyphens=False)}"
            for entry in entries
            if (note := entry.note) is not None
        )
    return "\n".join(lines) + "\n"


def _render_registry_markdown(entries: Sequence[Any], page: _RegistryPage, *, include_header: bool) -> str:
    """Render registry entries as a Markdown page: a summary table, then the details, message and note of each."""
    lines = (
        [
            f"# {page.title}",
            "",
            f"<!-- Generated by scripts/{page.script}. Do not edit manually. -->",
            "",
            page.intro,
            "",
        ]
        if include_header
        else []
    )
    lines += [f"| {' | '.join(page.columns)} |", f"|{'|'.join('-' * (len(column) + 2) for column in page.columns)}|"]
    lines += (
        "| "
        + " | ".join(
            f"`{cell}`" if column in {"ID", "Target"} else cell
            for column, cell in zip(page.columns, page.cells(entry), strict=True)
        )
        + " |"
        for entry in entries
    )
    lines += ["", "## Details", ""]
    for entry in entries:
        bullets = (f"- **{label}:** {value}" for label, value in page.details(entry) if value is not None)
        lines += [f"### `{entry.id}`", "", *bullets, "", entry.message, ""]
        if entry.note:
            lines += [entry.note, ""]
    return "\n".join(lines).rstrip() + "\n"


def _render_registry(entries: Sequence[Any], page: _RegistryPage, format_: Literal["table", "json", "markdown"]) -> str:
    """Render registry entries in the requested listing format."""
    match format_:
        case "json":
            return _render_registry_entries_json(entries) + "\n"
        case "markdown":
            return _render_registry_markdown(entries, page, include_header=True)
    return _render_registry_table(entries, page)


def _render_release_notes(sections: Iterable[tuple[str, Iterable[str]]]) -> str:
    """Render the release-note sections that have items: the heading, a blank line, a bullet per item, a blank line."""
    lines: list[str] = []
    for heading, items in sections:
        if bullets := [f"- {item}" for item in items]:
            lines += [f"## {heading}", "", *bullets, ""]
    return "\n".join(lines)
