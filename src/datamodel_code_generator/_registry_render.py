"""Private rendering helpers for registry modules."""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from collections.abc import Callable, Iterable, Mapping, Sequence


def _render_registry_json(entries: Iterable[Mapping[str, object]]) -> str:
    """Render registry entries as stable JSON."""
    return json.dumps(list(entries), indent=2, sort_keys=True)


def _render_registry_table(rows: Sequence[Sequence[str]]) -> str:
    """Render registry rows as a stable plain text table."""
    widths = [max(len(row[index]) for row in rows) for index in range(len(rows[0]))]
    lines = [
        "  ".join(value.ljust(widths[index]) for index, value in enumerate(rows[0])).rstrip(),
        "  ".join("-" * width for width in widths),
    ]
    lines.extend("  ".join(value.ljust(widths[index]) for index, value in enumerate(row)).rstrip() for row in rows[1:])
    return "\n".join(lines) + "\n"


def _render_registry_markdown(  # noqa: PLR0913
    entries: Sequence[Any],
    *,
    title: str,
    script: str,
    intro: str,
    columns: Sequence[str],
    cells: Callable[[Any], Sequence[str]],
    details: Callable[[Any], Iterable[tuple[str, str | None]]],
    include_header: bool,
) -> str:
    """Render registry entries as a Markdown page: a summary table, then the details, message and note of each."""
    lines = (
        [f"# {title}", "", f"<!-- Generated by scripts/{script}. Do not edit manually. -->", "", intro, ""]
        if include_header
        else []
    )
    lines += [f"| {' | '.join(columns)} |", f"|{'|'.join('-' * (len(column) + 2) for column in columns)}|"]
    lines += (
        "| "
        + " | ".join(
            f"`{cell}`" if column in {"ID", "Target"} else cell
            for column, cell in zip(columns, cells(entry), strict=True)
        )
        + " |"
        for entry in entries
    )
    lines += ["", "## Details", ""]
    for entry in entries:
        bullets = (f"- **{label}:** {value}" for label, value in details(entry) if value is not None)
        lines += [f"### `{entry.id}`", "", *bullets, "", entry.message, ""]
        if entry.note:
            lines += [entry.note, ""]
    return "\n".join(lines).rstrip() + "\n"
