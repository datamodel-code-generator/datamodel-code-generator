class Module:
    """One generated module: collision-free imports, private aliases of imported types, and package-relative names."""

    def __init__(self, reserved: Iterable[str], symbols: Mapping[int, str], *, level: int) -> None:
        """Reserve the names the module defines, and remember its depth below the package root."""
        self.namespace = Namespace(reserved)
        self.leaves: dict[tuple[str, str], str] = {}
        self.types = TypeSource(self.namespace, symbols, self.leaf)
        self.level = level

    def leaf(self, module: str, name: str) -> str:
        """Return the private alias of an imported type, numbered in the order the module first spells them."""
        if (alias := self.leaves.get((module, name))) is None:
            alias = self.leaves[module, name] = f"_dcg_type_{len(self.leaves)}"
        return alias

    def name(self, module: str, name: str) -> str:
        """Return the local alias of a name imported from an absolute module."""
        return self.namespace.name(module, name)

    def local(self, module: str, name: str) -> str:
        """Return the local alias of a name imported from a module of the generated package."""
        return self.namespace.name(f"{'.' * self.level}{module}", name)

    def root(self, name: str) -> str:
        """Return the local alias of a module at the package root."""
        return self.namespace.name("." * self.level, name)

    def imports(self) -> str:
        """Return the module's import statements."""
        return "\n".join((
            *self.namespace.imports(),
            *(f"from {module} import {name} as {alias}" for (module, name), alias in self.leaves.items()),
        ))


class _Typing:
    """Spell the payload types of a planned client: model types with their projection, or schema-less surfaces."""

    def __init__(self, plan: ClientPlan, codecs: CodecPlan, accessors: dict[TypeUseId, UseAccessors]) -> None:
        """Keep the plan, the use bindings of the codec plan, and the codec accessors of every bound use."""
        self.plan = plan
        self.symbols = dict(codecs.imports)
        self.projections = {use: binding.projection_mode for use, binding in codecs.bindings}
        self.accessors = accessors

    def envelope(self, use: TypeUseBinding) -> bool:
        """Return whether a use's codec projects into an envelope."""
        return self.projections.get(use.id) == "envelope"

    def key(self, kind: str, use: TypeUseBinding | None, *, sent: bool) -> _Key:
        """Return the identity of one payload type: its model type and projection, or a schema-less surface."""
        if kind == "binary":
            return "bytes"
        if use is None or use.type is None:
            return {"text": "str", "form": "form", "multipart": "multipart"}.get(kind, "wire")
        return _Model(use.type, self.envelope(use), sent)

    @staticmethod
    def spell(module: Module, key: _Key) -> str:
        """Return the spelling of one payload type in a module."""
        match key:
            case _Model():
                static = module.types.static(key.type)
                if key.sent:
                    values = module.local("model_codecs", "DecodedValue" if key.envelope else "ModelValue")
                    return f"{static} | {values}[{static}]"
                return f"{module.local('model_codecs', 'DecodedValue')}[{static}]" if key.envelope else static
            case _Parts():
                return f"{module.local('bodies', 'MultipartData')}[{_Typing.values(module, key)}]"
            case str() if (surface := _SURFACES.get(key)) is not None:
                package, name, arguments = surface
                return f"{module.local(package, name)}{arguments}"
            case _:
                pass
        return key

    @staticmethod
    def values(module: Module, key: _Parts) -> str:
        """Return the union of the value types of a response's parts."""
        return _union(_Typing.spell(module, value) for value in key.values)

    def surface(self, module: Module, kind: str, use: TypeUseBinding | None, *, sent: bool) -> str:
        """Return the payload type of one media or parameter: its model type, envelope, or schema-less surface."""
        return self.spell(module, self.key(kind, use, sent=sent))

    def payloads(self, response: ResponseSpec, media_type: str | None = None) -> list[_Key]:
        """Return the value types one response yields, restricted to those a media type or range dispatches to."""
        if response.bodyless or not response.media:
            return ["None"]
        chosen = (
            None if media_type is None else reachable(media_type, tuple(item.media_type for item in response.media))
        )
        return [
            self.key(media.kind, media.use, sent=False) if media.members is None else self.parts(media)
            for media in response.media
            if chosen is None or media.media_type in chosen
        ]

    def parts(self, media: MediaSpec) -> _Parts:
        """Return the payload of a response read as parts: each part's type, bytes for files and untyped extras."""
        return _Parts(
            tuple(
                dict.fromkeys(
                    "bytes" if part.use is None else self.key("json", part.use, sent=False)
                    for part in member_parts(media)
                )
            )
        )

    def successes(self, spec: OperationSpec, media_type: str | None = None) -> tuple[_Key, ...]:
        """Return every success value type without repeats, restricted to one media type when given."""
        keys = (key for response in spec.responses if response.success for key in self.payloads(response, media_type))
        return tuple(dict.fromkeys(keys))

    def union(self, module: Module, keys: Iterable[_Key], empty: str) -> str:
        """Return the union of payload types in a module, or the spelling of an empty union."""
        return _union(self.spell(module, key) for key in keys) or empty

    def body_surfaces(self, module: Module, media: MediaSpec) -> tuple[str, str]:
        """Return the sync and asyncio body types of one request media type."""
        match media.kind, media.use:
            case "binary", _:
                return module.local("bodies", "SyncBinaryBody"), module.local("bodies", "AsyncBinaryBody")
            case "multipart", None:
                values = "str"
            case "multipart", _ if media.members is not None:
                values = self.part_values(module, media)
            case _:
                surface = self.surface(module, media.kind, media.use, sent=True)
                return surface, surface
        return (
            f"{module.local('bodies', 'MultipartBody')}[{values}]",
            f"{module.local('bodies', 'AsyncMultipartBody')}[{values}]",
        )

    def request_selector(self, module: Module, media: MediaSpec) -> str:
        """Return the type of a request media selector of one media type."""
        return f"{module.local('model_codecs', 'RequestMedia')}[{', '.join(self.body_surfaces(module, media))}]"

    def part_values(self, module: Module, media: MediaSpec) -> str:
        """Return the values the field parts of a body sent as parts take: each member's, WireValue for any extra."""
        keys = (self.key("json", part.use, sent=True) for part in member_parts(media) if not part.plan.file)
        return self.union(module, keys, "") or module.name("typing_extensions", "Never")

    def codec(self, module: Module, use: TypeUseBinding, *, facade: bool = False) -> str:
        """Return the model bindings accessor of a use: its codec and context, or its outbound facade."""
        accessor = self.accessors[use.id]
        bindings = module.local("_generated", "model_bindings")
        if facade:
            return f"{bindings}.{accessor.outbound}"
        return f"{bindings}.{accessor.codec}, {bindings}.{accessor.context}"


class _Resources(_Typing):
    """Render the root clients and the resource modules with their typed operation methods."""

    def __init__(
        self, plan: ClientPlan, codecs: CodecPlan, accessors: dict[TypeUseId, UseAccessors], user_agent: str | None
    ) -> None:
        """Keep the typing context and the generated User-Agent."""
        super().__init__(plan, codecs, accessors)
        self.user_agent = user_agent

    def client(self, *, asynchronous: bool) -> str:
        """Return a root client module: its constructor, lazy resource attributes, and close methods."""
        prefix = "Async" if asynchronous else ""
        mode = _mode(asynchronous=asynchronous)
        roots = [
            (resource, f"{prefix}{resource.pascal}Resource", f".resources.{resource.namespace}._{mode}")
            for resource in self.plan.roots
        ]
        names = {f"{prefix}Client", f"{prefix}ClientWithStreamingResponse", "_DEFAULTS"}
        module = Module({*names, *(name for _, name, _ in roots)}, self.symbols, level=1)
        values = {
            "defaults": f"{module.local('_runtime.client.client', 'ClientDefaults')}(user_agent={self.user_agent!r})",
            "options": module.local("options", "ClientOptions"),
            "http_client": f"{module.namespace.module('httpx2')}.{prefix}Client",
            "unset": module.local("_runtime.model_codecs.unset", "Unset"),
            "unset_value": module.local("_runtime.model_codecs.unset", "UNSET"),
            "literal": module.name("typing", "Literal"),
            "core": module.local("_runtime.client.client", f"{prefix}ClientCore"),
            "adapter": module.local("transports", f"{prefix}TransportAdapter"),
            "owned_adapter": module.local("transports", "OwnedTransportAdapter"),
            "request_options": module.local("options", "RequestOptions"),
            "cached_property": module.name("functools", "cached_property"),
            "raw": module.local("responses", f"{prefix}RawResponse"),
            "binary": f"{module.local('bodies', f'{prefix}BodyInput')}[{module.local('model_codecs', 'WireValue')}]",
            "manager": module.name("contextlib", f"Abstract{prefix}ContextManager"),
            "coroutine": "async " if asynchronous else "",
            "wait": "await " if asynchronous else "",
            "lifecycle": (_ASYNC_LIFECYCLE if asynchronous else _SYNC_LIFECYCLE).format(
                result=module.name("typing_extensions", "Self"), traceback=module.name("types", "TracebackType")
            ),
        }
        imports = module.imports()
        if roots:
            checking = module.name("typing", "TYPE_CHECKING")
            lazy = "\n".join(f"    from {path} import {name}" for _, name, path in roots)
            imports = f"{module.imports()}\n\nif {checking}:\n{lazy}"
        return client_template.render(
            docstring=f"The {'asyncio' if asynchronous else 'synchronous'} client of this package.",
            imports=imports,
            name=f"{prefix}Client",
            class_docstring=f"Call the operations of this API{' with asyncio' if asynchronous else ''} through HTTPX2.",
            resources=[
                {"name": resource.parts[0], "namespace": resource.namespace, "class_name": name, "module": path}
                for resource, name, path in roots
            ],
            **values,
        )

    def resource(self, resource: ResourceSpec, *, asynchronous: bool) -> str:
        """Return a resource module: the resource and its metadata, raw, and streaming views of every operation."""
        prefix = "Async" if asynchronous else ""
        main = f"{prefix}{resource.pascal}Resource"
        views: list[tuple[View, str, str, str]] = [
            (view, attribute, f"{prefix}{resource.pascal}{suffix}", doc) for view, attribute, suffix, doc in _VIEWS
        ]
        module = Module({main, *(name for _, _, name, _ in views)}, self.symbols, level=len(resource.parts) + 2)
        cached = module.name("functools", "cached_property")
        members = [
            (
                f"    @{cached}\n    def {attribute}(self) -> {name}:\n"
                f'        """The same operations, {doc}."""\n'
                f"        return {name}(self._core)"
            )
            for _, attribute, name, doc in views
        ]
        for child in resource.children:
            name = child.rpartition(".")[2]
            class_name = f"{prefix}{''.join(pascal(part) for part in child.split('.'))}Resource"
            alias = module.namespace.name(f".{name}._{_mode(asynchronous=asynchronous)}", class_name)
            members.append(
                f"    @{cached}\n    def {name}(self) -> {alias}:\n"
                f'        """The {child} operations."""\n'
                f"        return {alias}(self._core)"
            )
        members.extend(
            self.method(module, spec, asynchronous=asynchronous, view="plain") for spec in resource.operations
        )
        classes = [{"name": main, "docstring": f"The {resource.namespace} operations.", "members": members}]
        classes.extend(
            {
                "name": name,
                "docstring": f"The {resource.namespace} operations, {doc}.",
                "members": [
                    self.method(module, spec, asynchronous=asynchronous, view=view) for spec in resource.operations
                ],
            }
            for view, _, name, doc in views
        )
        core = module.local("_runtime.client.client", f"{prefix}ClientCore")
        kind = "asyncio" if asynchronous else "synchronous"
        return resource_template.render(
            docstring=f"The {kind} operations of the {resource.namespace} resource.",
            imports=module.imports(),
            core=core,
            views=classes,
        )

    def parameter(self, module: Module, parameter: ParameterSpec) -> str:
        """Return one argument of an operation method: optional ones default to UNSET."""
        kind = media_kind(parameter.plan.content_media_type) if parameter.plan.content_media_type else "json"
        surface = self.surface(module, "json" if kind == "form" else kind, parameter.use, sent=True)
        if parameter.required:
            return f"{parameter.python_name}: {surface}"
        unset, value = module.local("options", "Unset"), module.local("options", "UNSET")
        return f"{parameter.python_name}: {surface} | {unset} = {value}"

    def requests(
        self, module: Module, spec: OperationSpec, *, asynchronous: bool
    ) -> tuple[list[_Variant], tuple[str, ...]]:
        """Return the body signatures of an operation and the body keywords of its implementation.

        A binary body takes the bytes, file, stream, and factory inputs of the client's mode.
        """
        if (body := spec.body) is None:
            return [_Variant(())], ()
        literal = module.name("typing", "Literal")
        omitted = f"{module.local('options', 'Unset')} = {module.local('options', 'UNSET')}"
        groups: dict[str, list[tuple[str, str]]] = {}
        for media in body.media:
            surface = self.body_surfaces(module, media)[asynchronous]
            groups.setdefault(surface, []).append((media.media_type, self.request_selector(module, media)))

        def choices(entries: list[tuple[str, str]]) -> str:
            concrete = [media for media, _ in entries if not media_range(media)]
            return _union((*((_literal(literal, concrete),) if concrete else ()), *(kind for _, kind in entries)))

        surfaces = _union(groups)
        implementation = (
            f"body: {surfaces}" if body.required else f"body: {surfaces} | {omitted}",
            f"media_type: {choices([entry for entries in groups.values() for entry in entries])} | None = None",
        )
        if len(groups) == 1 and (body.default is not None or body.required):
            surface, declared = next(iter(groups.items()))
            if body.default is None:
                single = (f"body: {surface}", f"media_type: {choices(declared)}")
                return [_Variant(single)], single
            return [_Variant(implementation)], implementation
        variants = [
            _Variant((
                f"body: {surface}",
                f"media_type: {choices(media)}{' | None = None' if body.default in dict(media) else ''}",
            ))
            for surface, media in groups.items()
        ]
        if not body.required:
            variants.append(_Variant((f"body: {omitted}", "media_type: None = None")))
        return variants, implementation

    def responses(self, module: Module, spec: OperationSpec) -> tuple[list[_Variant], _Variant]:
        """Return the response media signatures of an operation with their results, and its implementation's.

        A result that is every success type is spelled by the operation's Response alias.
        """
        every = self.successes(spec)
        never = "" if every else module.name("typing_extensions", "Never")

        def named(keys: tuple[_Key, ...]) -> str:
            if keys == every:
                return module.local(f"types.{spec.resource}", f"{spec.pascal}Response")
            return self.union(module, keys, never)

        declared = success_media(spec.responses, ranges=True)
        default = self.successes(spec, spec.response_media_type)
        if not declared:
            return [_Variant((), named(default))], _Variant((), named(default))
        literal = module.name("typing", "Literal")
        selector = module.local("model_codecs", "ResponseMedia")
        groups: dict[tuple[_Key, ...], tuple[list[str], list[str]]] = {}
        for media_type in declared:
            keys = self.successes(spec, media_type)
            concrete, selectors = groups.setdefault(keys, ([], []))
            if not media_range(media_type):
                concrete.append(media_type)
            selectors.append(f"{selector}[{named(keys)}]")

        def choices(concrete: list[str], selectors: list[str]) -> str:
            return _union((*((_literal(literal, concrete),) if concrete else ()), *selectors))

        every_choice = choices(
            [media for concrete, _ in groups.values() for media in concrete],
            [kind for _, selectors in groups.values() for kind in selectors],
        )
        parameters = (f"response_media_type: {every_choice} | None = None",)
        if set(groups) == {default}:
            return [_Variant(parameters, named(default))], _Variant(parameters, named(default))
        variants = [_Variant(("response_media_type: None = None",), named(default))]
        variants.extend(
            _Variant((f"response_media_type: {choices(*values)}",), named(keys)) for keys, values in groups.items()
        )
        return variants, _Variant(parameters, named(every))

    def method(self, module: Module, spec: OperationSpec, *, asynchronous: bool, view: View) -> str:
        """Return one operation method of a view: its overloads by body and response media, then its implementation."""
        arguments = [self.parameter(module, parameter) for parameter in spec.parameters]
        options = f"options: {module.local('options', 'RequestOptions')} | None = None"
        bodies, body = self.requests(module, spec, asynchronous=asynchronous)
        results, result = self.results(module, spec, asynchronous=asynchronous, view=view)
        coroutine = asynchronous and view != "streaming"
        lines: list[str] = []
        if len(bodies) * len(results) > 1:
            overload = module.name("typing", "overload")
            lines.extend(
                line
                for variant in bodies
                for choice in results
                for line in (
                    f"    @{overload}",
                    _signature(
                        spec.name,
                        (*arguments, *variant.parameters, *choice.parameters, options),
                        choice.returns,
                        asynchronous=coroutine,
                        stub=True,
                    ),
                )
            )
        head, opening, closing = _VIEW_CALLS[view, coroutine]
        call = Group(opening, _arguments(module, spec, media=bool(result.parameters)), closing)
        lines.extend((
            _signature(
                spec.name,
                (*arguments, *body, *result.parameters, options),
                result.returns,
                asynchronous=coroutine,
                stub=False,
            ),
            f'        """{_summary(spec)}"""',
            f"        {head}{layout(call, 8, len(head), WIDTH)}",
        ))
        return "\n".join(lines)

    def results(
        self, module: Module, spec: OperationSpec, *, asynchronous: bool, view: View
    ) -> tuple[list[_Variant], _Variant]:
        """Return the response media signatures of an operation's method in a view, and its implementation's.

        Raw and streaming views return the raw response whatever media answered, so only the body chooses overloads.
        """
        results, result = self.responses(module, spec)
        prefix = "Async" if asynchronous else ""
        match view:
            case "metadata":
                response = module.local("responses", "Response")
                return (
                    [_Variant(choice.parameters, f"{response}[{choice.returns}]") for choice in results],
                    _Variant(result.parameters, f"{response}[{result.returns}]"),
                )
            case "raw":
                raw = _Variant(result.parameters, module.local("responses", f"{prefix}RawResponse"))
                return [raw], raw
            case "streaming":
                manager = module.name("contextlib", f"Abstract{prefix}ContextManager")
                streaming = _Variant(
                    result.parameters, f"{manager}[{module.local('responses', f'{prefix}RawResponse')}]"
                )
                return [streaming], streaming
            case _:
                pass
        return results, result


class _Types(_Typing):
    """Render each resource's types module: result aliases, HTTP errors, request codecs, and header accessors."""

    def module(self, resource: ResourceSpec) -> str:
        """Return the types module of one resource."""
        reserved = {name for spec in resource.operations for name in exports(spec)}
        reserved.update(f"_{spec.pascal}RequestCodecs" for spec in resource.operations)
        reserved.update(f"_{spec.name.upper()}_HEADERS" for spec in resource.operations)
        module = Module(reserved, self.symbols, level=len(resource.parts) + 2)
        sections = [section for spec in resource.operations for section in self.sections(module, spec)]
        return types_template.render(
            docstring=f"The result types, errors, codecs, and header accessors of the {resource.namespace} operations.",
            imports=module.imports(),
            sections=sections,
        )

    def sections(self, module: Module, spec: OperationSpec) -> list[str]:
        """Return the definitions of one operation's types."""
        alias = module.name("typing", "TypeAlias")
        name = spec.pascal
        successes = self.union(module, self.successes(spec), module.name("typing_extensions", "Never"))
        errors = dict.fromkeys(key for response in spec.responses if response.error for key in self.payloads(response))
        sections = [
            f"{name}Response: {alias} = {successes}\n{name}ErrorData: {alias} = {self.union(module, errors, 'None')}",
            (
                f"class {name}HTTPError({module.local('errors', 'HTTPStatusError')}[{name}ErrorData]):\n"
                f'    """An error response of {spec.name}, with its decoded payload when one is declared."""'
            ),
            self.request_codecs(module, spec),
        ]
        if headers := _header_names(spec):
            sections.append(self.header_accessor(module, spec, headers))
        return sections

    def facade(self, module: Module, use: TypeUseBinding) -> str:
        """Return the type of a use's outbound codec facade."""
        assert use.type is not None
        facade = "EnvelopeOutboundCodec" if self.envelope(use) else "NativeOutboundCodec"
        return f"{module.local('model_codecs', facade)}[{module.types.static(use.type)}]"

    def request_codecs(self, module: Module, spec: OperationSpec) -> str:  # noqa: PLR0914
        """Return one operation's request codec facade: typed overloads over its codecs and media selectors."""
        declared = () if spec.body is None else spec.body.media
        bodies = [
            (
                media.media_type,
                self.facade(module, media.use),
                self.codec(module, media.use, facade=True),
                self.request_selector(module, media),
            )
            for media in declared
            if media.use is not None and media.kind != "binary" and media.use.id in self.accessors
        ]
        requests = [(media.media_type, self.request_selector(module, media)) for media in declared]
        responses = [
            (media_type, f"{module.local('model_codecs', 'ResponseMedia')}[{self.result(module, spec, media_type)}]")
            for media_type in success_media(spec.responses, ranges=True)
        ]
        parameters = [
            (item.location, item.wire_name, self.facade(module, item.use), self.codec(module, item.use, facade=True))
            for item in spec.parameters
            if item.use is not None and item.use.id in self.accessors
        ]
        sent = [media for media in (() if spec.body is None else spec.body.media) if media.members is not None]
        parts = [
            (media.media_type, part.plan.name, *self.part_codec(module, part))
            for media in sent
            for part in media.members or ()
        ]
        extras = [
            (media.media_type, *self.part_codec(module, extra))
            for media in sent
            if (extra := media.extra) is not None and extra.use is not None
        ]
        never = module.name("typing_extensions", "Never")
        body_union = _union(kind for _, kind, _, _ in bodies) or never
        parameter_union = _union(kind for _, _, kind, _ in parameters) or never
        if not (part_union := _union((*(kind for _, _, kind, _ in parts if kind), *(kind for _, kind, _ in extras)))):
            parts, extras = [], []
        request_union, response_union = _union(kind for _, kind in requests), _union(kind for _, kind in responses)
        name = f"_{spec.pascal}RequestCodecs"
        unions = [body_union, parameter_union, part_union or never, request_union or never, response_union or never]
        while len(unions) > _MIN_UNIONS and unions[-1] == never:
            unions.pop()
        base = f"{module.local(_CODECS, 'RequestCodecs')}[{', '.join(unions)}]"
        lines = [
            layout(Group(f"class {name}(", (("", base),), "):"), 0, 0, WIDTH),
            f'    """The outbound codecs of the {spec.name} request."""',
        ]
        arguments: list[tuple[str, Doc]] = []
        default = None if spec.body is None else spec.body.default
        if bodies:
            lines.extend(self.body_methods(module, bodies, default, body_union))
            arguments.append(("bodies=", _tuple(f"({media!r}, {accessor})" for media, _, accessor, _ in bodies)))
        if any(media == default for media, *_ in (*bodies, *parts)):
            arguments.append(("default=", repr(default)))
        if parameters:
            lines.extend(self.parameter_methods(module, parameters, parameter_union))
            arguments.append((
                "parameters=",
                _tuple(f"({location!r}, {name!r}, {accessor})" for location, name, _, accessor in parameters),
            ))
        if parts or extras:
            lines.extend(self.part_methods(module, parts, default, part_union))
        if parts:
            arguments.append((
                "parts=",
                _tuple(f"({media!r}, {part!r}, {accessor or 'None'})" for media, part, _, accessor in parts),
            ))
        if extras:
            arguments.append(("extras=", _tuple(f"({media!r}, {accessor})" for media, _, accessor in extras)))
        for method, choices, union, keyword in (
            ("select_request_media", requests, request_union, "requests"),
            ("select_response_media", responses, response_union, "responses"),
        ):
            if choices:
                lines.extend(self.select_methods(module, method, choices, union))
                arguments.append((f"{keyword}=", _tuple(repr(media) for media, _ in choices)))
        head = f"{spec.pascal}RequestCodecs: {module.name('typing', 'Final')} = "
        return "\n".join(lines) + f"\n\n\n{head}{layout(_call(name, arguments), 0, len(head), WIDTH)}"

    def result(self, module: Module, spec: OperationSpec, media_type: str) -> str:
        """Return the success value types a response media type or range dispatches to: the Response alias for all."""
        keys = self.successes(spec, media_type)
        if keys == self.successes(spec):
            return f"{spec.pascal}Response"
        return self.union(module, keys, module.name("typing_extensions", "Never"))

    @staticmethod
    def body_methods(
        module: Module, bodies: list[tuple[str, str, str, str]], default: str | None, union: str
    ) -> list[str]:
        """Return the body overloads of a request codec facade: default, each media and selector, then any media."""
        literal = module.name("typing", "Literal")
        overload = f"    @{module.name('typing', 'overload')}"
        lines = [""]
        if (kind := next((kind for media, kind, _, _ in bodies if media == default), None)) is not None:
            lines.extend((overload, f"    def body(self) -> {kind}: ..."))
        for media, kind, _, selector in bodies:
            for parameter in (f"media_type: {literal}[{media!r}]", f"media_type: {selector}"):
                lines.extend((overload, _signature("body", (parameter,), kind, asynchronous=False, stub=True)))
        selectors = _union(selector for _, _, _, selector in bodies)
        lines.extend((
            overload,
            _signature("body", ("media_type: str",), union, asynchronous=False, stub=True),
            _signature(
                "body", (f"media_type: str | {selectors} | None = None",), union, asynchronous=False, stub=False
            ),
            '        """Return the outbound codec of one declared request media type, or of a selector\'s."""',
            "        return self._body(media_type)",
        ))
        return lines

    @staticmethod
    def select_methods(module: Module, method: str, choices: list[tuple[str, str]], union: str) -> list[str]:
        """Return a media selector method of a request codec facade: an overload for each type of selector."""
        literal = module.name("typing", "Literal")
        groups: dict[str, list[str]] = {}
        for media_type, kind in choices:
            groups.setdefault(kind, []).append(media_type)
        lines = [""]
        if len(groups) > 1:
            overload = f"    @{module.name('typing', 'overload')}"
            for kind, declared in groups.items():
                parameters = (f"declared_media: {_literal(literal, declared)}", "concrete_media: str")
                lines.extend((overload, _signature(method, parameters, kind, asynchronous=False, stub=True)))
            parameters, returns = ("declared_media: str", "concrete_media: str"), union
        else:
            ((returns, declared),) = groups.items()
            parameters = (f"declared_media: {_literal(literal, declared)}", "concrete_media: str")
        direction = "request" if method == "select_request_media" else "success response"
        lines.extend((
            _signature(method, parameters, returns, asynchronous=False, stub=False),
            f'        """Return the selector of a declared {direction} media type for a concrete one."""',
            f"        return self._{direction.rpartition(' ')[2]}_media(declared_media, concrete_media)",
        ))
        return lines

    def part_codec(self, module: Module, part: PartSpec) -> tuple[str, str]:
        """Return the type and accessor of a part's outbound codec facade, or empty ones for a file part."""
        return (
            ("", "") if part.use is None else (self.facade(module, part.use), self.codec(module, part.use, facade=True))
        )

    @staticmethod
    def part_methods(
        module: Module, parts: Sequence[tuple[str, str, str, str]], default: str | None, union: str
    ) -> list[str]:
        """Return the part method of a request codec facade: an overload for each member with a codec and any name.

        Extras alone take no overloads, only the method for any name.
        """
        literal = module.name("typing", "Literal")
        overload = f"    @{module.name('typing', 'overload')}"
        keywords = ("name: str", "media_type: str | None = None")
        lines = [""]
        for media, name, kind, _ in parts:
            if kind:
                media_type = f"{literal}[{media!r}]{' | None = None' if media == default else ''}"
                named = (f"name: {literal}[{name!r}]", f"media_type: {media_type}")
                lines.extend((overload, _signature("part", named, kind, asynchronous=False, stub=True)))
        if len(lines) > 1:
            lines.extend((overload, _signature("part", keywords, union, asynchronous=False, stub=True)))
        lines.extend((
            _signature("part", keywords, union, asynchronous=False, stub=False),
            '        """Return the outbound codec of one part of a body sent as parts."""',
            "        return self._part(name, media_type)",
        ))
        return lines

    @staticmethod
    def parameter_methods(module: Module, parameters: Sequence[tuple[str, str, str, str]], union: str) -> list[str]:
        """Return the parameter overloads of a request codec facade: each parameter, then any location and name."""
        literal = module.name("typing", "Literal")
        overload = f"    @{module.name('typing', 'overload')}"
        keywords = (f"location: {_literal(literal, _LOCATIONS)}", "name: str")
        lines = [""]
        for location, name, kind, _ in parameters:
            named = (f"location: {literal}[{location!r}]", f"name: {literal}[{name!r}]")
            lines.extend((overload, _signature("parameter", named, kind, asynchronous=False, stub=True)))
        lines.extend((
            overload,
            _signature("parameter", keywords, union, asynchronous=False, stub=True),
            _signature("parameter", keywords, union, asynchronous=False, stub=False),
            '        """Return the outbound codec of one declared parameter."""',
            "        return self._parameter(location, name)",
        ))
        return lines

    def header_accessor(self, module: Module, spec: OperationSpec, headers: _Headers) -> str:
        """Return one operation's header decoders and its typed accessor function."""
        unset = module.local("options", "Unset")
        results, every, entries = self.header_entries(module, headers)
        missing = any(not header.required for _, branches in headers.values() for _, header in branches)
        decoders = module.local(_CODECS, "ResponseHeaders")
        absent = unset if missing else module.name("typing_extensions", "Never")
        annotation = f"{module.name('typing', 'Final')}[{decoders}[{_union(every)}, {absent}]]"
        keys = ", ".join(repr(response.status) for response in spec.responses)
        value = _call(decoders, (("", repr(spec.operation_id)), ("", f"frozenset({{{keys}}})"), ("", _tuple(entries))))
        head = f"_{spec.name.upper()}_HEADERS: {annotation} = "
        returns = _union((*every, *((unset,) if missing else ())))
        return "\n".join((
            head + layout(value, 0, len(head), WIDTH),
            "",
            "",
            *_accessor(module, spec, results, returns),
        ))

    def header_entries(self, module: Module, headers: _Headers) -> tuple[dict[str, str], list[str], list[Doc]]:
        """Return each header's result type, every value type, and each header's declarations by status."""
        unset = module.local("options", "Unset")
        results: dict[str, str] = {}
        every: list[str] = []
        entries: list[Doc] = []
        for spelling, branches in headers.values():
            kinds = [self.surface(module, "json", header.use, sent=False) for _, header in branches]
            optional = not all(header.required for _, header in branches)
            every.extend(kinds)
            results[spelling] = _union((*kinds, *((unset,) if optional else ())))
            declared = _tuple(
                Group("(", (("", repr(response.status)), ("", self.header_branch(module, header))), ")")
                for response, header in branches
            )
            entries.append(Group("(", (("", repr(spelling)), ("", declared)), ")"))
        return results, every, entries

    def header_branch(self, module: Module, header: HeaderSpec) -> Group:
        """Return the HeaderBranch constructor of one status's declaration of a header."""
        assert header.use is not None
        decoder = "envelope_value" if self.envelope(header.use) else "native_value"
        missing = "required_header" if header.required else "optional_header"
        return _call(
            module.local(_CODECS, "HeaderBranch"),
            (
                ("plan=", parameter_plan(module.local, header.plan)),
                ("decode=", f"{module.local(_CODECS, decoder)}({self.codec(module, header.use)})"),
                ("missing=", module.local(_CODECS, missing)),
            ),
        )


class _Registry(_Typing):
    """Render the operation registry: each operation's servers, parameters, body, and response decoder."""

    def module(self) -> str:
        """Return the operation registry module."""
        servers: dict[tuple[ServerSpec, ...], str] = {}
        for spec in self.plan.operations:
            servers.setdefault(spec.servers, f"_SERVERS_{len(servers)}")
        reserved = {*(f"OPERATION_{spec.index}" for spec in self.plan.operations), *servers.values()}
        module = Module(reserved, self.symbols, level=1)
        final = module.name("typing", "Final")
        sections = [
            f"{name}: {final} = {layout(self.servers(module, specs), 0, len(f'{name}: {final} = '), WIDTH)}"
            for specs, name in servers.items()
        ]
        plan = module.local(_RUNTIME, "OperationPlan")
        for spec in self.plan.operations:
            types = f"types.{spec.resource}"
            result = (
                f"{module.local(types, f'{spec.pascal}Response')}, {module.local(types, f'{spec.pascal}ErrorData')}"
            )
            head = f"OPERATION_{spec.index}: {final}[{plan}[{result}]] = "
            sections.append(head + layout(self.operation(module, spec, servers[spec.servers]), 0, len(head), WIDTH))
        return (
            '"""The operation registry of this package; regenerate it instead of editing."""\n\n'
            f"from __future__ import annotations\n\n{module.imports()}\n\n\n" + "\n\n".join(sections) + "\n"
        )

    @staticmethod
    def servers(module: Module, specs: tuple[ServerSpec, ...]) -> Doc:
        """Return the tuple of one operation's servers."""
        variable = module.local(_RUNTIME, "ServerVariable")
        servers: list[Doc] = []
        for server in specs:
            entries: list[tuple[str, Doc]] = [("url=", repr(server.url))]
            if server.variables:
                entries.append((
                    "variables=",
                    _tuple(
                        _call(
                            variable,
                            (
                                ("name=", repr(name)),
                                ("default=", repr(default)),
                                *((("enum=", repr(enum)),) if enum else ()),
                            ),
                        )
                        for name, default, enum in server.variables
                    ),
                ))
            servers.append(_call(module.local(_RUNTIME, "ServerPlan"), entries))
        return _tuple(servers)

    def operation(self, module: Module, spec: OperationSpec, servers: str) -> Group:
        """Return the OperationPlan constructor of one operation."""
        entries: list[tuple[str, Doc]] = [
            ("operation_id=", repr(spec.operation_id)),
            ("method=", repr(spec.contract.method.upper())),
            ("path=", repr(spec.contract.path)),
            ("servers=", servers),
            ("responses=", self.decoder(module, spec)),
        ]
        if spec.parameters:
            entries.append(("parameters=", _tuple(self.parameter(module, item) for item in spec.parameters)))
        if (body := spec.body) is not None:
            fields: list[tuple[str, Doc]] = [("media=", _tuple(self.media(module, item) for item in body.media))]
            if body.default is not None:
                fields.append(("default=", repr(body.default)))
            if body.required:
                fields.append(("required=", "True"))
            entries.append(("body=", _call(module.local(_RUNTIME, "RequestBody"), fields)))
        if spec.request_id_header is not None:
            entries.append(("request_id_header=", repr(spec.request_id_header)))
        if spec.response_media_type is not None:
            entries.append(("response_media_type=", repr(spec.response_media_type)))
        if (spec.body is not None and spec.body.media) or success_media(spec.responses, ranges=True):
            entries.append(("codecs=", module.local(f"types.{spec.resource}", f"{spec.pascal}RequestCodecs")))
        return _call(module.local(_RUNTIME, "OperationPlan"), entries)

    def encoder(self, module: Module, use: TypeUseBinding) -> str:
        """Return the Encoder of a sent use."""
        return f"{module.local(_RUNTIME, 'Encoder')}({self.codec(module, use)})"

    def parameter(self, module: Module, parameter: ParameterSpec) -> Group:
        """Return the ParameterSpec constructor of one parameter."""
        entries: list[tuple[str, Doc]] = [("plan=", parameter_plan(module.local, parameter.plan))]
        if parameter.use is not None and parameter.use.id in self.accessors:
            entries.append(("encoder=", self.encoder(module, parameter.use)))
        return _call(module.local(_RUNTIME, "ParameterSpec"), entries)

    def media(self, module: Module, media: MediaSpec) -> Group:
        """Return the BodyMedia constructor of one request media type."""
        kind = media.kind if media.kind in {"json", "text", "form", "multipart"} else "binary"
        entries: list[tuple[str, Doc]] = [("media_type=", repr(media.media_type)), ("kind=", repr(kind))]
        if media.members is not None:
            entries.append(("parts=", _tuple(self.sent_plan(module, part) for part in media.members)))
            if media.extra is not None:
                entries.append(("additional_part=", self.sent_plan(module, media.extra)))
        elif kind != "binary" and media.use is not None and media.use.id in self.accessors:
            entries.append(("encoder=", self.encoder(module, media.use)))
            entries.extend(self.form(module, media))
        return _call(module.local(_RUNTIME, "BodyMedia"), entries)

    def sent_plan(self, module: Module, part: PartSpec) -> Group:
        """Return the PartPlan constructor of one member of a body sent as parts."""
        plan = part.plan
        flags = (("repeated=", plan.repeated), ("file=", plan.file), ("required=", plan.required))
        return _call(
            module.local("_runtime.client.multipart", "PartPlan"),
            (
                ("", repr(plan.name)),
                *((flag, "True") for flag, value in flags if value),
                *((("encoder=", self.encoder(module, part.use)),) if part.use is not None else ()),
                *((("content_types=", _tuple(map(repr, plan.content_types))),) if plan.content_types else ()),
                *(
                    (("headers=", _tuple(map(partial(self.part_header, module), part.headers))),)
                    if part.headers
                    else ()
                ),
            ),
        )

    def part_header(self, module: Module, header: HeaderSpec) -> Group:
        """Return the PartHeader constructor of one header an encoding declares for a member's parts."""
        assert header.use is not None
        return _call(
            module.local("_runtime.client.multipart", "PartHeader"),
            (
                ("", parameter_plan(module.local, header.plan)),
                ("", self.codec(module, header.use, facade=True)),
            ),
        )

    @staticmethod
    def form(module: Module, media: MediaSpec) -> list[tuple[str, Doc]]:
        """Return the member plan keywords of a URL-encoded or form-data media type."""
        entries: list[tuple[str, Doc]] = []
        if media.fields:
            entries.append(("fields=", _tuple(field_plan(module.local, item) for item in media.fields)))
        if media.additional is not None:
            entries.append(("additional=", field_plan(module.local, media.additional)))
        if media.encoded:
            entries.append(("encoded=", _tuple(parameter_plan(module.local, item) for item in media.encoded)))
        if media.content_types:
            entries.append(("content_types=", _tuple(repr(pair) for pair in media.content_types)))
        if media.parts:
            entries.append(("parts=", _tuple(_part_plan(module, item) for item in media.parts)))
        if media.additional_part is not None:
            entries.append(("additional_part=", _part_plan(module, media.additional_part)))
        return entries

    def decoder(self, module: Module, spec: OperationSpec) -> Group:
        """Return the ResponseDecoder constructor of one operation."""
        success = [branch for item in spec.responses if item.success for branch in self.branches(module, item)]
        errors = [branch for item in spec.responses if item.error for branch in self.branches(module, item)]
        entries: list[tuple[str, Doc]] = [
            ("", _tuple(success)),
            ("", _tuple(errors)),
            ("", module.local(f"types.{spec.resource}", f"{spec.pascal}HTTPError")),
        ]
        if spec.success_statuses:
            entries.append(("success_statuses=", f"frozenset({{{', '.join(map(str, spec.success_statuses))}}})"))
        if spec.head:
            entries.append(("head=", "True"))
        return _call(module.local(_RUNTIME, "ResponseDecoder"), entries)

    def branches(self, module: Module, response: ResponseSpec) -> list[Doc]:
        """Return the branches of one declared response: one per media type, or one without a body."""
        status = repr(response.status)
        if response.bodyless or not response.media:
            return [f"{module.local(_RUNTIME, 'empty_branch')}({status})"]
        branches: list[Doc] = []
        for media in response.media:
            media_type = repr(media.media_type)
            if media.kind == "binary":
                branches.append(f"{module.local(_RUNTIME, 'binary_branch')}({status}, {media_type})")
            elif media.members is not None:
                branches.append(self.parts_branch(module, status, media))
            elif media.use is None or media.use.id not in self.accessors:
                name = {"json": "wire_branch", "text": "text_branch", "multipart": "multipart_branch"}.get(
                    media.kind, "form_branch"
                )
                branches.append(f"{module.local(_RUNTIME, name)}({status}, {media_type})")
            else:
                name = "envelope_branch" if self.envelope(media.use) else "model_branch"
                entries: list[tuple[str, Doc]] = [
                    ("", status),
                    ("", media_type),
                    ("", repr(media.kind)),
                    ("", self.codec(module, media.use)),
                    *self.form(module, media),
                ]
                branches.append(_call(module.local(_RUNTIME, name), entries))
        return branches

    def parts_branch(self, module: Module, status: str, media: MediaSpec) -> Group:
        """Return the branch of a form-data response with file parts: its reader of each member's parts."""
        reader = f"{module.local(_RUNTIME, 'PartsReader')}[{self.values(module, self.parts(media))}]"
        entries: list[tuple[str, Doc]] = [("", _tuple(self.read_part(module, part) for part in media.members or ()))]
        if media.extra is not None:
            entries.append(("additional=", self.read_part(module, media.extra)))
        return _call(
            module.local(_RUNTIME, "parts_branch"),
            (("", status), ("", repr(media.media_type)), ("", _call(reader, entries))),
        )

    def read_part(self, module: Module, part: PartSpec) -> Group:
        """Return the PartDecoder of one member of a response read as parts: its bytes, or its codec's value."""
        plan = part.plan
        flags = [
            (flag, "True") for flag, value in (("repeated=", plan.repeated), ("required=", plan.required)) if value
        ]
        multipart = "_runtime.client.multipart"
        if part.use is None:
            return _call(module.local(multipart, "file_part"), (("", repr(plan.name)), *flags))
        decoder = "envelope_value" if self.envelope(part.use) else "native_value"
        value = f"{module.local(_CODECS, decoder)}({self.codec(module, part.use)})"
        return _call(
            module.local(multipart, "value_part"), (("", repr(plan.name)), ("", repr(plan.kind)), ("", value), *flags)
        )


class ClientRenderer:
    """Render every module of one client package from its plan, codec plan, and wire plan."""

    def __init__(  # noqa: PLR0913
        self,
        *,
        config: ClientGenerationConfig,
        package: PurePosixPath,
        plan: ClientPlan,
        batch: GeneratedTypeContractBatch,
        wire: WirePlan,
        codecs: CodecPlan,
    ) -> None:
        """Keep the plans; the model bindings module and its accessors are rendered when first used."""
        self.config = config
        self.package = package
        self.plan = plan
        self.batch = batch
        self.wire = wire
        self.codecs = codecs

    @cached_property
    def bindings(self) -> RenderedBindings:
        """Return the model bindings module of every bound use, rendered once."""
        return render_model_bindings(self.codecs, self.wire, self.batch, surface="client")

    @cached_property
    def accessors(self) -> dict[TypeUseId, UseAccessors]:
        """Return the codec accessors of every bound use."""
        return {item.use: item for item in self.bindings.uses}

    def file(self, path: PurePosixPath, kind: str, text: str, *, verbatim: bool = False) -> RenderedFile:
        """Return one owned file of the package."""
        return RenderedFile(path=self.package / path, kind=kind, text=text, verbatim=verbatim)

    def files(self) -> tuple[RenderedFile, ...]:
        """Return every rendered client file in the fixed artifact order."""
        config = self.config
        user_agent = None
        if config.package_mode == "standalone":
            user_agent = f"{config.distribution_name}/{config.package_version}"
        resources = _Resources(self.plan, self.codecs, self.accessors, user_agent)
        types = _Types(self.plan, self.codecs, self.accessors)
        registry = _Registry(self.plan, self.codecs, self.accessors)
        files = [
            self.file(PurePosixPath("__init__.py"), "package", _PACKAGE),
            self.file(PurePosixPath("_client.py"), "client", resources.client(asynchronous=False)),
            self.file(PurePosixPath("_async_client.py"), "client", resources.client(asynchronous=True)),
            self.file(PurePosixPath("options.py"), "options", _OPTIONS),
            self.file(PurePosixPath("errors.py"), "errors", _ERRORS),
            self.file(PurePosixPath("responses.py"), "responses", _RESPONSES),
            self.file(PurePosixPath("bodies.py"), "bodies", _BODIES),
            self.file(PurePosixPath("model_codecs.py"), "model_codecs", render_model_codecs("client")),
            self.file(PurePosixPath("transports.py"), "transports", _TRANSPORTS),
            self.file(PurePosixPath("resources", "__init__.py"), "package", '"""The resources of the clients."""\n'),
        ]
        for resource in self.plan.resources:
            directory = PurePosixPath("resources", *resource.parts)
            files.extend((
                self.file(directory / "__init__.py", "package", _resource_package(resource)),
                self.file(directory / "_sync.py", "resource", resources.resource(resource, asynchronous=False)),
                self.file(directory / "_async.py", "resource", resources.resource(resource, asynchronous=True)),
            ))
        files.append(self.file(PurePosixPath("types", "__init__.py"), "package", '"""The types of the resources."""\n'))
        for resource in self.plan.resources:
            directory = PurePosixPath("types", *resource.parts)
            files.extend((
                self.file(directory / "__init__.py", "package", _types_package(resource)),
                self.file(directory / "_operations.py", "types", types.module(resource)),
            ))
        files.extend((
            self.file(
                PurePosixPath("_generated", "__init__.py"), "package", '"""Generated plans of this package."""\n'
            ),
            self.file(PurePosixPath("_generated", "model_bindings.py"), "model_bindings", self.bindings.source),
            self.file(PurePosixPath("_operations.py"), "operations", registry.module()),
        ))
        runtime = runtime_sources(file.text for file in files)
        return (*files, *(self.file(path, "runtime", text, verbatim=True) for path, text in runtime))
