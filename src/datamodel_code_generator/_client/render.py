def _signature(name: str, parameters: tuple[str, ...], returns: str, *, asynchronous: bool, stub: bool) -> str:
    head = f"    {'async ' if asynchronous else ''}def {name}("
    return layout(
        Group(head, items(("self", "*", *parameters)), f") -> {returns}:{' ...' if stub else ''}"), 4, 0, WIDTH
    )


def _function(head: str, parameters: tuple[str, ...], returns: str, *, stub: bool) -> str:
    return layout(Group(head, items(parameters), f") -> {returns}:{' ...' if stub else ''}"), 0, 0, WIDTH)


def _accessor(module: Module, spec: OperationSpec, results: dict[str, str], returns: str) -> list[str]:
    """Return the header accessor function of an operation: one overload per header name, then its implementation."""
    function = f"def decode_{spec.name}_header("
    info = f"info: {module.local('responses', 'ResponseInfo')}"
    literal = module.name("typing", "Literal")
    lines: list[str] = []
    if len(results) > 1:
        overload = f"@{module.name('typing', 'overload')}"
        for spelling, result in results.items():
            lines.extend((
                overload,
                _function(function, (info, "*", f"name: {literal}[{spelling!r}]"), result, stub=True),
            ))
    lines.extend((
        _function(function, (info, "*", f"name: {_literal(literal, results)}"), returns, stub=False),
        f'    """Decode one declared response header of {spec.name} from a response\'s metadata."""',
        f"    return _{spec.name.upper()}_HEADERS.decode(info, name)",
    ))
    return lines


def _resource_package(resource: ResourceSpec) -> str:
    sync = sorted((f"{resource.pascal}Resource", *(f"{resource.pascal}{suffix}" for _, _, suffix, _ in _VIEWS)))
    names = [f"Async{name}" for name in sync]
    listing = "".join(f"    {name!r},\n" for name in sorted((*names, *sync)))
    return (
        f'"""The {resource.namespace} resource."""\n\n'
        f"from ._async import (\n{''.join(f'    {name},{chr(10)}' for name in names)})\n"
        f"from ._sync import (\n{''.join(f'    {name},{chr(10)}' for name in sync)})\n\n"
        f"__all__ = [\n{listing}]\n"
    )


