def _summary(spec: OperationSpec) -> str:
    """Return the first line of an operation's docstring: its configured description, its summary, or its route."""
    facts = {name: getattr(value, "value", None) for name, value in spec.contract.facts}
    for text in (spec.description, facts.get("summary"), facts.get("description")):
        if isinstance(text, str) and (line := _docstring(text)):
            return line
    return _docstring(f"Call {spec.contract.method.upper()} {spec.contract.path}.")


