def prepare_target(
    input_: _GenerationInput, model_config: GenerateConfig, generator: TargetGenerator
) -> GenerateConfig:
    """Validate target settings in the contract order and return the effective model settings.

    A setting the target needs that no option, configuration key, `generate()` argument, or preset set takes the value
    the target needs, as `implied_settings` says, so a target writes the models a model-only run writes with those
    settings given; a setting given a value the target cannot use is an `Error` that names the option.
    """
    from datamodel_code_generator import (  # noqa: PLC0415
        Error,
        _prepare_generate_facade_config,  # pyright: ignore[reportPrivateUsage]
    )
    from datamodel_code_generator._target_render import (  # noqa: PLC0415
        PYDANTIC_TARGET_MINIMUM,
        pydantic_target_problem,
    )
    from datamodel_code_generator.enums import DataModelType  # noqa: PLC0415

    if sys.version_info < _PYTHON_MINIMUM:
        raise config_error(
            code="E_PYTHON_UNSUPPORTED",
            option_path=None,
            message=f"The {generator.kind} target needs Python {_PYTHON_MINIMUM_TEXT} or later to run",
        )
    if model_config.output is None:
        raise config_error(
            code="E_CONFIG_VALUE",
            option_path="model_config.output",
            message=f"The {generator.kind} target needs model_config.output",
        )
    if implied := implied_settings(model_config, _given_fields(model_config)):
        model_config = model_config.model_copy(update=implied)
    target = model_config.target_pydantic_version
    if (sentinel := model_config.use_missing_sentinel) and (
        needed := pydantic_target_problem(
            model_config.output_model_type.value, target, sentinel=True, implied="use_missing_sentinel" in implied
        )
    ) is not None:
        raise _target_pydantic_error(generator, needed)
    effective = _prepare_generate_facade_config(model_config)
    if (requirement := model_requirement(effective.openapi_scopes, generator.selector)) is not None:
        raise Error(requirement)
    if (backend := effective.output_model_type) not in generator.backends:
        allowed = " or ".join(repr(item.value) for item in DataModelType if item in generator.backends)
        raise config_error(
            code=generator.unsupported_backend,
            option_path="model_config.output_model_type",
            message=f"The {generator.kind} target does not support {backend.value!r}; use {allowed}",
        )
    if (problem := python_problem(effective, generator.kind)) is not None:
        raise config_error(code="E_CONFIG_VALUE", option_path="model_config.target_python_version", message=problem)
    if backend is DataModelType.PydanticV2Dataclass and not sentinel:
        raise config_error(
            code="E_CONFIG_VALUE",
            option_path="model_config.use_missing_sentinel",
            message=(
                f"The {generator.kind} target needs model_config.use_missing_sentinel with --target-pydantic-version "
                f"{PYDANTIC_TARGET_MINIMUM} for {backend.value!r} models, whose fields cannot tell an unset member "
                "from None"
            ),
        )
    if (needed := pydantic_target_problem(backend.value, target, sentinel=False)) is not None:
        raise _target_pydantic_error(generator, needed)
    if backend is DataModelType.MsgspecStruct and (
        missing := tuple(
            Diagnostic(
                code="E_CONFIG_VALUE",
                severity="error",
                stage="config",
                message=(
                    f"The {generator.kind} target needs model_config.{name} for {backend.value!r} models, so that "
                    f"their {decoded} can be decoded"
                ),
                option_path=f"model_config.{name}",
            )
            for enabled, name, decoded in (
                (model_config.use_msgspec_tagged_unions, "use_msgspec_tagged_unions", "discriminated unions"),
                (
                    model_config.use_msgspec_nullable_enum_alias,
                    "use_msgspec_nullable_enum_alias",
                    "enums that list null",
                ),
            )
            if not enabled
        )
    ):
        raise APIGenerationError(missing)
    if (problem := _root_problem(input_)) is None:
        return effective
    option_path, message = problem
    raise APIGenerationError((
        Diagnostic(code="E_INPUT_ROOT", severity="error", stage="input", message=message, option_path=option_path),
    ))


def implied_conflict(config: Any, implied: dict[str, Any], generator: TargetGenerator) -> None:
    """Refuse a given target pydantic version older than the MISSING sentinel the target implied needs, saying so."""
    from datamodel_code_generator._target_render import pydantic_target_problem  # noqa: PLC0415
    from datamodel_code_generator.enums import DataModelType  # noqa: PLC0415

    backend = DataModelType(config.output_model_type).value
    if "use_missing_sentinel" in implied and (
        needed := pydantic_target_problem(backend, config.target_pydantic_version, sentinel=True, implied=True)
    ):
        raise _target_pydantic_error(generator, needed)


def _given_fields(config: GenerateConfig) -> set[str]:
    """Return the fields a config sets: the ones it was given, and the ones its preset sets, applied later."""
    if config.preset is None:
        return set(config.model_fields_set)
    from datamodel_code_generator.preset import PresetContext, resolve_preset_config_updates  # noqa: PLC0415

    preset = resolve_preset_config_updates(
        config.preset,
        context=PresetContext(
            input_file_type=config.input_file_type,
            output_model_type=config.output_model_type,
            target_python_version=config.target_python_version,
        ),
        use_annotated=config.use_annotated,
        explicit_fields=config.model_fields_set,
    )
    fixed = () if preset.target_python_version is None else ("target_python_version",)
    return {*config.model_fields_set, *fixed, *(item.field_name for item in preset.items)}


def python_problem(config: Any, kind: str) -> str | None:
    """Say why a target cannot use a config's target Python version, naming the preset that set it, or None.

    A preset refuses a target Python version given beside it that differs from its own, so with a preset the version
    is the preset's. The command line drops the preset from the settings it generates with, so it asks before the run.
    """
    if (version := config.target_python_version).version_key >= _PYTHON_MINIMUM:
        return None
    message = f"The {kind} target needs a target Python version of {_PYTHON_MINIMUM_TEXT} or later"
    if config.preset is None:
        return message
    from datamodel_code_generator.preset import _coerce_preset_name  # noqa: PLC0415  # pyright: ignore[reportPrivateUsage]

    name = _coerce_preset_name(config.preset).value
    return f"{message}, which the preset {name} sets to {version.value}: use a preset for Python 3.11 or later"


def _target_pydantic_error(generator: TargetGenerator, needed: str) -> APIGenerationError:
    """Refuse the target pydantic version a target cannot use, before the models are generated with it."""
    return config_error(
        code="E_CONFIG_VALUE",
        option_path="model_config.target_pydantic_version",
        message=f"The {generator.kind} target {needed}",
    )


def model_requirement(scopes: Iterable[OpenAPIScope] | None, selector: str) -> str | None:
    """Return the "X requires Y" message for the api scope a target needs, or None while the scopes include it."""
    from datamodel_code_generator.enums import OpenAPIScope  # noqa: PLC0415

    if scopes is not None and OpenAPIScope.Api in scopes:
        return None
    return f"{selector} requires --openapi-scopes to include api"


def _root_problem(input_: _GenerationInput) -> tuple[str, str] | None:
    match input_:
        case list():
            return "input", "Target generation reads one root document, not a list"
        case Path() if input_.is_dir():
            return "input", "Target generation reads one root document, not a directory"
    return None


def _root_input(input_: _GenerationInput, cwd: Path) -> RootInput:
    match input_:
        case Path():
            path = (cwd / input_.expanduser()).resolve()
            return RootInput(path.as_uri(), path.parent)
        case ParseResult():
            return RootInput(input_.geturl(), cwd)
    return RootInput(ROOT_URN, cwd)


def _remote_lock(
    input_: _GenerationInput, config: GenerateConfig, target: TargetConfig, cwd: Path
) -> tuple[GenerateConfig, RemoteReferenceLock | None]:
    """Resolve the remote lock of the models; an update must not overlap the package, as it must not the models."""
    from datamodel_code_generator import (  # noqa: PLC0415
        _prepare_atomic_generation_remote_lock,  # pyright: ignore[reportPrivateUsage]
        _resolve_generation_remote_lock,  # pyright: ignore[reportPrivateUsage]
    )

    if config.update_lock and not config.remote_lock_resolved:
        config, lockfile, lock = _prepare_atomic_generation_remote_lock(input_, config, cwd)
        package = Path(os.path.abspath(cwd / target.output.expanduser()))  # noqa: PTH100
        if any(lockfile.is_relative_to(root) or root.is_relative_to(lockfile) for root in (package, package.resolve())):
            from datamodel_code_generator import Error  # noqa: PLC0415

            label = (target._option_prefix or "target").capitalize()  # noqa: SLF001  # pyright: ignore[reportPrivateUsage]
            msg = f"{label} output and Remote lock paths must not overlap: {package}"
            raise Error(msg)
        return config, lock
    return _resolve_generation_remote_lock(input_, config, cwd), None


def _staging(stack: ExitStack, destination: Path, cwd: Path, around: Path | None = None) -> Path:
    """Create a private directory beside a destination, or beside the output `around` that contains it.

    Models inside the target package are then staged beside the package, so a render writes nothing into it.
    """
    full = cwd / destination.expanduser()
    location = Path(os.path.abspath(full))  # noqa: PTH100
    if around is not None and (outer := (cwd / around.expanduser()).resolve()) in full.resolve().parents:
        location = outer
    parent = location.parent
    while not parent.exists():
        parent = parent.parent
    return Path(stack.enter_context(tempfile.TemporaryDirectory(prefix=".datamodel-codegen-", dir=parent)))


def _staged_models(staged: Path, output: Path, encoding: str) -> tuple[ModelArtifact, ...]:
    from datamodel_code_generator._target_contract import ModelArtifact  # noqa: PLC0415

    if staged.is_file():
        return (ModelArtifact((output.name,), staged.read_bytes(), encoding),)
    files = sorted((path.relative_to(staged).parts, path) for path in staged.rglob("*") if path.is_file())
    return tuple(ModelArtifact(parts, path.read_bytes(), encoding) for parts, path in files)


def _generate_models(
    input_: _GenerationInput, config: GenerateConfig, target: TargetConfig, cwd: Path, *, use_output_cwd: bool
) -> _Models:
    from datamodel_code_generator import (  # noqa: PLC0415
        _absolute_generation_path,  # pyright: ignore[reportPrivateUsage]
        _default_input_filename,  # pyright: ignore[reportPrivateUsage]
        _output_context_path,  # pyright: ignore[reportPrivateUsage]
        _read_custom_file_header,  # pyright: ignore[reportPrivateUsage]
        _run_generation,  # pyright: ignore[reportPrivateUsage]
        _settings_path_from,  # pyright: ignore[reportPrivateUsage]
    )
    from datamodel_code_generator._openapi_generation import TargetGenerationSession  # noqa: PLC0415
    from datamodel_code_generator._target_binding import MetadataCycleError  # noqa: PLC0415

    source = _root_input(input_, cwd)
    output = config.output
    assert output is not None
    prepared, lock = _remote_lock(input_, config, target, cwd)
    output = prepared.output
    assert output is not None
    formatter_cwd = _output_context_path(_absolute_generation_path(output, cwd), cwd)
    settings_path = _settings_path_from(formatter_cwd, prepared.settings_path)
    with ExitStack() as stack:
        staged_output = _staging(stack, output, cwd, target.output) / (output.name or "output")
        if (cwd / output).is_dir():
            staged_output.mkdir()
        updates: dict[str, Any] = {"output": staged_output}
        if (metadata := config.emit_model_metadata) is not None:
            updates["emit_model_metadata"] = _staging(stack, metadata, cwd) / (metadata.name or "model-metadata.json")
        staged = prepared.model_copy(update=updates)
        staged._logical_output = output  # noqa: SLF001  # pyright: ignore[reportPrivateUsage]
        staged._logical_model_metadata = prepared.emit_model_metadata  # noqa: SLF001  # pyright: ignore[reportPrivateUsage]
        if lock is not None or not staged.remote_lock_resolved:
            staged.resolve_remote_lock(lock)
        session = TargetGenerationSession(
            output=output,
            model_package=target.model_package,
            root_selector_document=source.identity,
            serves_source=target._serves_source,  # noqa: SLF001  # pyright: ignore[reportPrivateUsage]
        )
        try:
            _run_generation(input_, staged, cwd, use_output_cwd=use_output_cwd, capture=session)
            artifacts = _staged_models(staged_output, output, prepared.encoding)
            metadata_file = None if metadata is None else (metadata, updates["emit_model_metadata"].read_bytes())
            product = session.take_product(artifacts, allow_empty_api=True)
        except MetadataCycleError as error:
            from datamodel_code_generator._target_documents import named_document  # noqa: PLC0415

            identity = document_identity(error.document, source.base)
            named = "" if identity == source.identity else named_document(identity, identity)
            raise APIGenerationError((
                Diagnostic(
                    code="E_INPUT_CYCLE",
                    severity="error",
                    stage="input",
                    message=f"{error}{named}",
                    source_pointer=error.pointer,
                ),
            )) from error
        finally:
            session.close()
        return _Models(
            product=product,
            artifacts=artifacts,
            single=staged_output.is_file(),
            metadata=metadata_file,
            lock=lock,
            source=source,
            cwd=cwd,
            filename=prepared.input_filename or _default_input_filename(input_),
            settings_path=settings_path,
            formatter_cwd=formatter_cwd,
            custom_header=_read_custom_file_header(
                prepared.custom_file_header,
                _absolute_generation_path(prepared.custom_file_header_path, cwd),
                prepared.encoding,
            ),
        )


def _is_python(path: PurePosixPath) -> bool:
    return path.suffix in {".py", ".pyi"}


def _normalized(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n").rstrip("\n")
    return f"{text}\n" if text else ""


def _written(text: str, encoding: str) -> bytes:
    """Return the bytes that writing the text to a file opened as text leaves in it, as model files are written.

    The text passes the text layer of such a file, so its lines end as the platform ends them.
    """
    with TextIOWrapper(buffer := BytesIO(), encoding=encoding) as file:
        file.write(text)
        file.flush()
        return buffer.getvalue()


def _root_operations(batch: GeneratedTypeContractBatch) -> tuple[OperationContract, ...]:
    """Return the operations of the root document's `paths`, in document order.

    A component path item that no included path references is walked on its own; it has no URL, so it is left out.
    """
    root = batch.documents[0].id
    return tuple(
        operation
        for operation in batch.operations
        if operation.id.parent is None
        and operation.id.kind == "path"
        and operation.id.use_site.document == root
        and operation.id.use_site.pointer.startswith("/paths/")
    )


def _collision_key(path: Path) -> str:
    return unicodedata.normalize("NFC", str(path)).casefold()


def _present(location: Path) -> bool:
    """Return whether a user module exists, as its file or as a package directory that Python imports instead."""
    return location.exists() or (location.name != "__init__.py" and location.with_suffix("").is_dir())


def _located(steps: NextSteps, package: Path, kept: frozenset[Path], cwd: Path) -> NextSteps:
    """Return a target's next steps with the paths of the files it names, saying which implementations it creates.

    An implementation that is a package names its initializer.
    """
    home = package.parent
    return replace(
        steps,
        readme=package / steps.readme,
        entrypoint=None if steps.entrypoint is None else package / steps.entrypoint,
        implementations=tuple(_implementation(item, home / item.path, kept, cwd) for item in steps.implementations),
    )


def _implementation(item: Implementation, path: Path, kept: frozenset[Path], cwd: Path) -> Implementation:
    """Return a user module at its path, created unless kept: its module file, or a package's initializer instead."""
    if not (cwd / path).exists() and (cwd / (directory := path.with_suffix(""))).is_dir():
        return replace(item, path=directory / "__init__.py", created=False)
    return replace(item, path=path, created=path not in kept)


def _adopted(owner: re.Match[str], server: str) -> str:
    """Return an initializer of implementations whose docstring names another server package as this one's."""
    text = owner.string
    return f"{text[: owner.start(1)]}{server}, which {f'{server}.main' if owner[2] else ''}{text[owner.end() :]}"


class _Planner:
    def __init__(  # noqa: PLR0913
        self,
        models: _Models,
        effective: GenerateConfig,
        config: TargetConfig,
        generator: TargetGenerator,
        *,
        models_module: bool = False,
        shown_root: Path | None = None,
        job: str = "",
    ) -> None:
        self.models = models
        self.job = job
        self.models_module = models_module
        self.effective = effective
        self.config = config
        self.generator = generator
        self.cwd = models.cwd
        self.shown_root = self.cwd if shown_root is None else shown_root
        self.root = (self.cwd / config.output.expanduser()).resolve()
        self.documents = DocumentTable(models.product.batch, models.source)
        self.operations: dict[str, OperationContract] = {}

    def operation(self, reference: OperationRef) -> OperationContract | None:
        document = reference.document
        if document is None or document_identity(document, self.cwd) == self.models.source.identity:
            return self.operations.get(reference.pointer)
        return None

    def model_path(self, artifact: ModelArtifact) -> Path:
        output = self.effective.output
        assert output is not None
        if not self.models.single:
            return output.joinpath(*artifact.path)
        return output.with_name(f"{output.name}.py") if self.models_module else output

    def artifact(self, path: Path, kind: ArtifactKind, content: bytes) -> GeneratedArtifact:
        """Plan one file: written unless the path already holds the same bytes, whoever wrote them."""
        current = location.read_bytes() if (location := self.cwd / path).is_file() else None
        return GeneratedArtifact(
            path=path, kind=kind, action="unchanged" if current == content else "write", content=content
        )

    def lock_artifacts(self) -> tuple[GeneratedArtifact, ...]:
        if (lock := self.models.lock) is None:
            return ()
        with tempfile.TemporaryDirectory(prefix=".datamodel-codegen-") as directory:
            try:
                content = staged.read_bytes() if isinstance(staged := lock.stage(Path(directory)), Path) else b""
            finally:
                lock.discard_stage()
        return (self.artifact(lock.path, "remote_lock", content),)

    def check_collisions(self, artifacts: tuple[GeneratedArtifact, ...]) -> None:
        """Refuse files that cannot be written or imported together.

        Two files resolve to one path, a file takes the path of the directory of another file, or a module has the
        name of a directory that the run generates into beside it, which Python imports instead of the module.
        """
        output = self.effective.output
        assert output is not None
        roots = [self.root, *(() if self.models.single else ((self.cwd / output).resolve(),))]
        parents: dict[Path, Path] = {}
        directories: set[str] = set()
        packages: set[str] = set()
        locations: list[Path] = []
        for artifact in artifacts:
            location = self.cwd / artifact.path
            if (parent := parents.get(location.parent)) is None:
                parent = parents[location.parent] = location.parent.resolve()
                for directory in (parent, *parent.parents):
                    directories.add(key := _collision_key(directory))
                    if any(directory == root or root in directory.parents for root in roots):
                        packages.add(key)
            locations.append(parent / location.name)
        seen: set[str] = set()
        problems: list[Diagnostic] = []
        for artifact, location in zip(artifacts, locations, strict=True):
            message = None
            if (key := _collision_key(location)) in seen or key in directories:
                message = "Two generated files resolve to the same path"
            elif location.suffix == ".py" and _collision_key(location.with_suffix("")) in packages:
                message = "The module has the name of a generated package directory beside it"
            if message is not None:
                problems.append(
                    Diagnostic(
                        code="E_PATH_COLLISION",
                        severity="error",
                        stage="publication",
                        message=message,
                        artifact_path=shown(artifact.path, self.cwd).as_posix(),
                    )
                )
            seen.add(key)
        if problems:
            raise APIGenerationError(tuple(problems))

    def project(self) -> GeneratedProject:
        models, config, generator = self.models, self.config, self.generator
        operations = _root_operations(models.product.batch)
        self.operations = {operation.id.use_site.pointer: operation for operation in operations}
        rendered = generator.render(
            TargetRequest(
                config=config,
                model_config=self.effective,
                batch=models.product.batch,
                lease=models.product.source_lease,
                models=models.artifacts,
                model_imports=models.product.model_imports,
                operations=operations,
                documents=self.documents,
                resolve=self.operation,
                cwd=self.cwd,
                shown_root=self.shown_root,
            )
        )
        home = config.output.parent
        kept = {
            file.path: home.joinpath(*file.path.parts)
            for file in rendered.implementations
            if _present(self.cwd / home.joinpath(*file.path.parts))
        }
        finished, stubs = _Finisher(self).finish(rendered)
        written = [file for file in stubs if file.path not in kept]
        artifacts = (
            *(self.artifact(self.model_path(artifact), "model", artifact.content) for artifact in models.artifacts),
            *(self.artifact(config.output.joinpath(*file.path.parts), "target", file.content) for file in finished),
            *(
                ()
                if models.metadata is None
                else (self.artifact(models.metadata[0], "model_metadata", models.metadata[1]),)
            ),
            *self.lock_artifacts(),
            *(
                GeneratedArtifact(
                    path=home.joinpath(*file.path.parts), kind="implementation", action="write", content=file.content
                )
                for file in written
            ),
            *(
                GeneratedArtifact(path=path, kind="implementation", action="keep", content=b"")
                for path in kept.values()
            ),
        )
        artifacts, taken_over = self.check_services(artifacts)
        self.check_collisions(artifacts)
        steps = _located(rendered.next_steps, config.output, frozenset(kept.values()), self.cwd)
        return GeneratedProject(
            target=generator.kind,
            artifacts=artifacts,
            dependencies=rendered.dependencies,
            next_steps=steps if taken_over is None else replace(steps, taken_over=taken_over),
        )

    def check_services(
        self, artifacts: tuple[GeneratedArtifact, ...]
    ) -> tuple[tuple[GeneratedArtifact, ...], str | None]:
        """Refuse a package of implementations that another server package uses, or that models or a module shadow.

        Python would import one of a module beside the server package and the package instead of the other, and a
        models package would be the package itself. One parent package holds one server package: another server package
        generated beside this one refuses the run, since both would import their implementations from the package,
        whatever the docstring of its initializer says. Without one, the docstring naming another server package, gone,
        renamed or moved, or this one spelled from another import root, leaves the package to this one, whose name the
        docstring then records; the artifacts come back with that initializer and the name of the package it took the
        package over from.
        """
        if not (paths := [artifact.path for artifact in artifacts if artifact.kind == "implementation"]):
            return artifacts, None
        module = (package := paths[0].parent).with_suffix(".py")
        models = [artifact.path for artifact in artifacts if artifact.kind == "model"]
        server = self.config.package
        parent = server.rpartition(".")[0]
        services = f"{parent}.services" if parent else "services"
        job = f" of job '{self.job}'" if self.job else ""
        clash = f"the {services} package, from which {server}.main{job} imports your implementations"
        remedy = "put the server package under a parent package of its own"
        path = package
        if found := next((path for path in models if path in {module, package}), None):
            path, message = found, f"The models module has the name of {clash}: name the models otherwise, or {remedy}"
        elif any(package in path.parents for path in models):
            message = f"The models package would be {clash}: name the models otherwise, or {remedy}"
        elif (self.cwd / module).is_file():
            path, message = module, f"This module of yours has the name of {clash}: rename the module, or {remedy}"
        elif other := self.other_server(package.parent, parent):
            message = (
                f"The server packages {other[0]}, generated before, and {server}{job} would both import their "
                f"implementations from the {services} package: put each server package under a parent package of its "
                f"own, or delete the directory {shown(other[1], self.cwd).as_posix()} of {other[0]} when it is no "
                "longer used"
            )
        elif (owner := self.services_owner(path := package / "__init__.py")) is None or owner[1] == server:
            return artifacts, None
        else:
            adopted = self.artifact(path, "implementation", _adopted(owner, server).encode(*self.codec))
            return tuple(adopted if artifact.path == path else artifact for artifact in artifacts), owner[1]
        raise APIGenerationError((
            Diagnostic(
                code="E_PATH_COLLISION",
                severity="error",
                stage="publication",
                message=message,
                artifact_path=shown(path, self.cwd).as_posix(),
            ),
        ))

    @property
    def codec(self) -> tuple[str, str]:
        """Return the encoding of the user's modules, and the error handler that keeps undecodable bytes as they are."""
        return self.effective.encoding, "surrogateescape"

    def services_owner(self, initializer: Path) -> re.Match[str] | None:
        """Return where the docstring of an existing initializer of implementations names its server package."""
        if not (location := self.cwd / initializer).is_file():
            return None
        return _SERVICES_OWNER.search(location.read_bytes().decode(*self.codec))

    def other_server(self, directory: Path, parent: str) -> tuple[str, Path] | None:
        """Return the name and directory of a server package generated in `directory` other than this one, if any.

        A generated server package is a directory with a `_generated` directory and an initializer whose docstring says
        it is one, whether its `main.py` is there or not. The docstring names the package, whatever its directory's
        name; the docstring of earlier versions does not, so the package takes its directory's name in `parent`.
        """
        if not (home := self.cwd / directory).is_dir():
            return None
        for location in sorted(home.iterdir()):
            if (
                (initializer := location / "__init__.py").is_file()
                and (location / "_generated").is_dir()
                and location.resolve() != self.root
                and (found := _SERVER_PACKAGE.search(initializer.read_bytes().decode(*self.codec))) is not None
            ):
                return found[1] or (f"{parent}.{location.name}" if parent else location.name), directory / location.name
        return None

    def planned(self) -> PlannedTarget:
        models, output = self.models, self.effective.output
        return PlannedTarget(
            project=self.project(),
            cwd=self.cwd,
            name=self.config.package,
            package=self.config.output,
            models=None if models.single else output,
            lock=models.lock,
            timestamp=self.effective._generation_timestamp,  # noqa: SLF001
        )


@dataclass(frozen=True, slots=True, kw_only=True)
class PlannedTarget:
    """A rendered target and where its files go, for a caller that writes it now or later with other files.

    `name` is the package's import name and `package` its directory. `models` is the models directory, or None for a
    models file. `lock` is the remote lock update that the target publishes with its files, None when the caller owns
    the lock the models record into.
    """

    project: GeneratedProject
    cwd: Path
    name: str
    package: Path
    models: Path | None
    lock: RemoteReferenceLock | None
    timestamp: str | None

    def directory(self, artifact: GeneratedArtifact) -> Path | None:
        """Return the output directory an artifact is generated into, or None for a file output names itself."""
        if artifact.kind == "target":
            return self.package
        return self.models if artifact.kind == "model" else None

    @property
    def services(self) -> Path | None:
        """Return the package of the user's implementations a server package imports, or None for other targets."""
        return next((item.path.parent for item in self.project.artifacts if item.kind == "implementation"), None)


def check_shared_services(job: str, target: PlannedTarget, earlier: Iterable[tuple[str, PlannedTarget]]) -> None:
    """Refuse a server package of a batch job whose `services` package a server package of an earlier job imports.

    Both would import their implementations from it, so the batch is refused while it plans, whether it writes or
    checks its files.
    """
    if (services := target.services) is None:
        return
    location = (target.cwd / services).resolve()
    for owner, planned in earlier:
        if planned.services is not None and (planned.cwd / planned.services).resolve() == location:
            parent = target.name.rpartition(".")[0]
            raise APIGenerationError((
                Diagnostic(
                    code="E_PATH_COLLISION",
                    severity="error",
                    stage="publication",
                    message=(
                        f"The server packages {planned.name} of job '{owner}' and {target.name} of job '{job}' would "
                        f"both import their implementations from the {f'{parent}.services' if parent else 'services'} "
                        "package: put each server package under a parent package of its own"
                    ),
                    artifact_path=shown(services, target.cwd).as_posix(),
                ),
            ))


def _stage(target: PlannedTarget, artifacts: Iterable[GeneratedArtifact], stack: ExitStack) -> list[StagedFile]:
    """Stage every changed file for the model journal, in a private directory that the stack removes.

    The directory lies in the deepest existing directory of the output it stages for, so the journal renames each
    file within one filesystem, also into an output directory that is a mount point. A file that already holds its
    bytes is left out, so an unchanged target stages nothing and writes nothing. The journal reports a staged module
    that a package directory shadows, so an unchanged one is reported here: a run warns whether or not it writes.
    The Python files that the target output holds and the run does not generate are reported before any is written.
    """
    from datamodel_code_generator._shadowed_modules import warn_shadowed_modules  # noqa: PLC0415

    planned = tuple(artifacts)
    _warn_leftover(target)
    warn_shadowed_modules(target.cwd / artifact.path for artifact in planned if artifact.action == "unchanged")
    if not (changed := [artifact for artifact in planned if artifact.action == "write"]):
        return []
    from datamodel_code_generator._publication import (  # noqa: PLC0415
        StagedFile,
        StagingDirectory,
        close_anchor,
        publication_anchor,
    )

    cwd = target.cwd
    places: dict[Path, tuple[Path, Path, PublicationAnchor]] = {}
    files: list[StagedFile] = []
    for artifact in changed:
        if artifact.kind == "remote_lock":
            lock = cast("RemoteReferenceLock", target.lock)
            stack.callback(close_anchor, anchor := publication_anchor(lock.path.parent))
            lock_staging = StagingDirectory.create(anchor, prefix=".datamodel-codegen-lock-")
            stack.callback(_quietly, lock_staging.cleanup)
            files.append(cast("StagedFile", lock.stage(lock_staging))._replace(anchor=anchor))
            continue
        destination = (directory := target.directory(artifact)) or artifact.path
        if (place := places.get(destination)) is None:
            location = cwd / destination
            resolved = location.resolve() if directory else location.parent.resolve() / location.name
            stack.callback(close_anchor, anchor := publication_anchor(resolved))
            staging = stack.enter_context(tempfile.TemporaryDirectory(prefix=".datamodel-codegen-", dir=anchor.path))
            place = places[destination] = (Path(staging), resolved, anchor)
        staging, resolved, anchor = place
        (source := staging / str(len(files))).write_bytes(artifact.content)
        files.append(StagedFile(source, cwd / artifact.path, resolved / artifact.path.relative_to(destination), anchor))
    return files


def _warn_leftover(target: PlannedTarget) -> None:
    """Warn about the Python files under the target output that the run does not generate, as `--check` lists them.

    Models generated inside the target output are part of it. A run that plans no target file writes no package.
    """
    artifacts = target.project.artifacts
    package, cwd = target.package, target.cwd
    if not (generated := {artifact.path.relative_to(package) for artifact in artifacts if artifact.kind == "target"}):
        return
    from datamodel_code_generator._leftover_files import warn_leftover_files  # noqa: PLC0415

    root = (cwd / package).resolve()
    paths = [artifact.path for artifact in artifacts if artifact.kind == "model"]
    steps = target.project.next_steps
    home = next((shown(item.path.parent, cwd) for item in steps.implementations), None)
    if (models := target.models) is None:
        generated.update(
            location.relative_to(root) for path in paths if (location := (cwd / path).resolve()).is_relative_to(root)
        )
    elif (location := (cwd / models).resolve()).is_relative_to(root):
        inner = location.relative_to(root)
        generated.update(inner / path.relative_to(models) for path in paths)
    warn_leftover_files(root, generated, shown(package, cwd), home)


def publish_target(target: PlannedTarget) -> None:
    """Publish every changed file of one target together through the model journal."""
    publish_planned((), (("", target),))


def _unshared(
    job: str, target: PlannedTarget, models: dict[Path, tuple[str, GeneratedArtifact]]
) -> Iterator[GeneratedArtifact]:
    """Yield the artifacts of a job's target that no earlier job plans.

    Jobs that share a models output plan each of its files once, and must plan the same content for it. No two jobs
    plan one `services` package, which `check_shared_services` refused while the batch planned.
    """
    for artifact in target.project.artifacts:
        if artifact.kind != "model":
            yield artifact
            continue
        location = target.cwd / artifact.path
        owner, planned = models.setdefault(location.parent.resolve(strict=False) / location.name, (job, artifact))
        if planned is artifact:
            yield artifact
        elif planned.content != artifact.content:
            raise APIGenerationError((
                Diagnostic(
                    code="E_PATH_COLLISION",
                    severity="error",
                    stage="publication",
                    message=f"Jobs '{owner}' and '{job}' generate different models",
                    artifact_path=artifact.path.as_posix(),
                ),
            ))


def publish_planned(files: Iterable[StagedFile], targets: Sequence[tuple[str, PlannedTarget]]) -> None:
    """Publish staged files and the changes the named targets planned through one model journal.

    The journal rolls every file back on an I/O error. The remote lock update of a target that owns one is published
    with the files, and discarded when they are not published.
    """
    locks = [lock for _, target in targets if (lock := target.lock) is not None]
    with ExitStack() as stack:
        try:
            staged = list(files)
            models: dict[Path, tuple[str, GeneratedArtifact]] = {}
            for job, target in targets:
                staged.extend(_stage(target, _unshared(job, target, models), stack))
            if staged:
                from datamodel_code_generator._publication import publish_staged_files  # noqa: PLC0415

                publish_staged_files(staged)
        except BaseException:
            for lock in locks:
                _quietly(lock.discard_stage)
            raise
    for lock in locks:
        lock.mark_committed()


def _quietly(cleanup: Callable[[], None]) -> None:
    with suppress(OSError):
        cleanup()


class _Finisher:
    def __init__(self, planner: _Planner) -> None:
        self.config = planner.config
        self.effective = planner.effective
        self.cwd = planner.cwd
        self.models = planner.models
        self.root = planner.root

    def finish(self, rendered: TargetRender) -> tuple[tuple[PlannedFile, ...], tuple[PlannedFile, ...]]:
        """Format, head, and encode every file like a model file, from the model output settings.

        Imports used only for type checking move into `TYPE_CHECKING` blocks as they do in the models' modules: a target
        package is a multi-module output of the model backend, so the backend decides the default. The implementations
        are formatted the same way, without the generated header, returned second, and put where a text file holds
        their `implementation_text`.
        """
        from datamodel_code_generator import (  # noqa: PLC0415
            _build_file_header_parts,  # pyright: ignore[reportPrivateUsage]
            _build_module_content,  # pyright: ignore[reportPrivateUsage]
            _format_file_header,  # pyright: ignore[reportPrivateUsage]
        )
        from datamodel_code_generator._target_format import TargetCodeFormatter  # noqa: PLC0415
        from datamodel_code_generator.format import resolve_use_type_checking_imports  # noqa: PLC0415
        from datamodel_code_generator.model import get_data_model_types  # noqa: PLC0415

        effective, models = self.effective, self.models
        backend = get_data_model_types(
            effective.output_model_type,
            effective.target_python_version,
            target_pydantic_version=effective.target_pydantic_version,
        ).data_model
        files = (*rendered.files, RenderedFile(path=PurePosixPath("py.typed"), kind="typing", text=""))
        formatter = TargetCodeFormatter(
            effective.target_python_version,
            models.settings_path,
            effective.wrap_string_literal,
            skip_string_normalization=not effective.use_double_quotes,
            model_package=self.config.model_package,
            package=self.config.package,
            custom_formatters=effective.custom_formatters,
            custom_formatters_kwargs=effective.custom_formatters_kwargs,
            encoding=effective.encoding,
            formatters=effective.formatters,
            builtin_format_line_length=effective.builtin_format_line_length,
            use_type_checking_imports=resolve_use_type_checking_imports(
                effective.use_type_checking_imports,
                is_multi_module_output=True,
                formatters=effective.formatters,
                requires_runtime_imports_with_ruff_check=backend.REQUIRES_RUNTIME_IMPORTS_WITH_RUFF_CHECK,
            ),
            defer_formatting=True,
            formatter_cwd=models.formatter_cwd,
        )
        custom_header = models.custom_header
        header = _format_file_header(*_build_file_header_parts(custom_header, effective), models.filename)
        formatted = {file.path for file in files if _is_python(file.path) and not file.verbatim}
        texts: dict[PurePosixPath, str] = {}
        for file in files:
            body = formatter.format_code(file.text) if file.path in formatted else file.text
            texts[file.path] = (
                _build_module_content(body, header, has_custom_file_header=bool(custom_header))
                if _is_python(file.path)
                else body
            )
        own = {file.path: formatter.format_code(file.text) for file in rendered.implementations}
        self.defer(formatter, texts, formatted, own)
        for key, value in list(texts.items()):
            if not _is_python(key):
                for path, text in own.items():
                    value = value.replace(implementation_text(path), text.rstrip("\n"))  # noqa: PLW2901
                texts[key] = value
        return self.planned(texts), self.planned(own)

    def planned(self, texts: dict[PurePosixPath, str]) -> tuple[PlannedFile, ...]:
        """Encode formatted texts as their files hold them: Python files in the model encoding, other text as UTF-8."""
        encoding = self.effective.encoding
        return tuple(
            PlannedFile(path=path, content=_written(_normalized(text), encoding if _is_python(path) else "utf-8"))
            for path, text in texts.items()
        )

    def defer(
        self,
        formatter: TargetCodeFormatter,
        texts: dict[PurePosixPath, str],
        paths: set[PurePosixPath],
        own: dict[PurePosixPath, str],
    ) -> None:
        """Run the Ruff formatters once over the formatted files, staged beside the target like a model directory.

        The staged package keeps the target directory's name, which Ruff reads as the package name, and the user
        modules, `own`, are staged beside it as they lie beside the package.
        """
        from datamodel_code_generator._format_types import Formatter  # noqa: PLC0415

        if not paths or not {Formatter.RUFF_CHECK, Formatter.RUFF_FORMAT}.intersection(formatter.formatters):
            return
        encoding = self.effective.encoding
        with ExitStack() as stack:
            staged = _staging(stack, self.config.output, self.cwd) / self.root.name
            files = [*((staged, path, texts) for path in paths), *((staged.parent, path, own) for path in own)]
            for base, path, held in files:
                (location := base.joinpath(*path.parts)).parent.mkdir(parents=True, exist_ok=True)
                location.write_text(held[path], encoding=encoding)
            for directory in dict.fromkeys((staged, *(staged.parent / path.parts[0] for path in own))):
                formatter.format_directory(directory)
            for base, path, held in files:
                held[path] = base.joinpath(*path.parts).read_text(encoding=encoding)


def _run_models(input_: _GenerationInput, effective: GenerateConfig, config: TargetConfig) -> _Models:
    from datamodel_code_generator import _uses_legacy_process_state  # noqa: PLC0415  # pyright: ignore[reportPrivateUsage]
    from datamodel_code_generator._process_state import PROCESS_STATE_LOCK  # noqa: PLC0415

    if _uses_legacy_process_state(effective):
        with PROCESS_STATE_LOCK:
            return _generate_models(input_, effective, config, Path.cwd(), use_output_cwd=True)
    with PROCESS_STATE_LOCK:
        cwd = Path.cwd()
    return _generate_models(input_, effective, config, cwd, use_output_cwd=False)


def _plan(  # noqa: PLR0913
    input_: _GenerationInput,
    model_config: GenerateConfig,
    config: TargetConfig,
    generator: TargetGenerator,
    *,
    publish: bool,
    timestamp: str | None = None,
    models_module: bool = False,
    shown_root: Path | None = None,
    job: str = "",
) -> PlannedTarget:
    """Render one target; a run that publishes it cannot leave a lock update another caller owns unpublished.

    The files carry `timestamp` as their generation timestamp, or the current time without one. With
    `models_module`, models generated as one file are planned as the module that the suffixless output names.
    Warnings name target paths relative to `shown_root`, or to the working directory without one, and refusals name
    the batch `job` that plans the target.
    """
    effective = prepare_target(input_, model_config, generator)
    if publish and effective.remote_lock_resolved and getattr(effective.remote_lock, "update", False):
        raise config_error(
            code="E_CONFIG_CONFLICT",
            option_path="model_config.update_lock",
            message="A target run cannot publish a remote lock update that another caller owns",
        )
    if not effective.disable_timestamp and effective._generation_timestamp is None:  # noqa: SLF001
        effective = effective.model_copy()
        effective._generation_timestamp = (  # noqa: SLF001
            timestamp or datetime.now(timezone.utc).replace(microsecond=0).isoformat()
        )
    models = _run_models(input_, effective, config)
    try:
        return _Planner(
            models, effective, config, generator, models_module=models_module, shown_root=shown_root, job=job
        ).planned()
    finally:
        models.product.close()


def plan_target(  # noqa: PLR0913
    input_: _GenerationInput,
    *,
    model_config: GenerateConfig,
    config: TargetConfig,
    generator: TargetGenerator,
    publish: bool = False,
    timestamp: str | None = None,
    models_module: bool = False,
    shown_root: Path | None = None,
    job: str = "",
) -> PlannedTarget:
    """Render one target and its models without writing them, for a caller that compares or publishes them later.

    A caller that publishes it with other files owns the remote lock the models record into, so the target leaves
    the lock out. Targets published together pass on the `timestamp` of the first, so the models they share carry
    one generation timestamp. `models_module` plans models generated as one file as the module `<output>.py`,
    warnings name target paths relative to `shown_root`, or to the working directory without one, and refusals name
    the batch `job` that plans the target.
    """
    return _plan(
        input_,
        model_config,
        config,
        generator,
        publish=publish,
        timestamp=timestamp,
        models_module=models_module,
        shown_root=shown_root,
        job=job,
    )


def generate_target(
    input_: _GenerationInput, *, model_config: GenerateConfig, config: TargetConfig, generator: TargetGenerator
) -> GeneratedProject:
    """Render one target and its models once, then write every changed file together, as an atomic model run does."""
    publish_target(planned := _plan(input_, model_config, config, generator, publish=True))
    return planned.project
