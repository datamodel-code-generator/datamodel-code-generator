@dataclass(frozen=True, slots=True, kw_only=True)
class RenderedFile:
    """One text file a target rendered; the coordinator formats, heads, and encodes it.

    A verbatim file copies one of this package's own sources, such as a runtime module, that is valid for every
    supported target Python, so the coordinator heads and encodes it without formatting it.
    """

    path: PurePosixPath
    kind: str
    text: str
    verbatim: bool = False


def implementation_text(path: PurePosixPath) -> str:
    """Return the text a rendered file holds where the finished text of an implementation module goes.

    `path` is the module's path among the implementations of a `TargetRender`, which are finished like the other
    modules first, so a README shows a stub as generation writes it.
    """
    return f"\x1fimplementation:{path.as_posix()}\x1f"


@dataclass(frozen=True, slots=True, kw_only=True)
class PlannedFile:
    """One target file as the bytes a generation writes."""

    path: PurePosixPath
    content: bytes


@dataclass(frozen=True, slots=True, kw_only=True)
class TargetRequest:
    """Everything a target renders from: settings, the accepted models, the root operations, and the cwd.

    `model_imports` holds every module and module member that the import statements of the models name.
    """

    config: TargetConfig
    model_config: GenerateConfig
    batch: GeneratedTypeContractBatch
    lease: SourceLease
    models: tuple[ModelArtifact, ...]
    model_imports: frozenset[str]
    operations: tuple[OperationContract, ...]
    documents: DocumentTable
    resolve: Callable[[OperationRef], OperationContract | None]
    cwd: Path
    shown_root: Path

    @property
    def unresolved(self) -> str:
        """Say why an operation reference resolved to nothing, naming the include filter when one is set."""
        if self.model_config.openapi_include_paths:
            return "selects no root path operation that --openapi-include-paths keeps"
        return "selects no root path operation"


@dataclass(frozen=True, slots=True, kw_only=True)
class TargetRender:
    """A target's rendered files, the runtime dependencies of its package, and what to do with it next.

    `implementations` are the modules of the user's that the package imports, with stubs, under the directory that
    holds the package; generation writes each only while it is missing. The paths of `next_steps` are relative to the
    package, and those of its implementations to the directory that holds it. A target raises `APIGenerationError` for
    its failures instead of returning error diagnostics.
    """

    files: tuple[RenderedFile, ...]
    dependencies: tuple[str, ...] = ()
    implementations: tuple[RenderedFile, ...] = ()
    next_steps: NextSteps


class TargetGenerator(Protocol):
    """Render one target kind from the coordinator's request."""

    @property
    def kind(self) -> TargetKind:
        """Return the target kind that results and messages name."""

    @property
    def backends(self) -> frozenset[DataModelType]:
        """Return the model backends the target accepts."""

    @property
    def unsupported_backend(self) -> str:
        """Return the diagnostic code for a backend the target does not accept."""

    @property
    def selector(self) -> str:
        """Return the command-line option that selects the target, which its requirement errors name."""

    def render(self, request: TargetRequest) -> TargetRender:
        """Render the target's files from one accepted model generation."""


