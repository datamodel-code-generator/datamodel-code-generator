"""The packages a server package lives beside: the `services` package of the user's implementations, and others.

A server package imports the user's implementations from the package `services` in its parent package, or a top-level
`services` for a top-level server package. The renderer writes its stubs there, and the API generation refuses a
`services` package that another server package beside it, or a module or the models, would also be.

The docstrings of the two package initializers are a contract between the renderer, which writes them, and the API
generation, which reads them back from the files of an earlier run: the server package's names the package, so that a
server package is found beside `services` whatever its directory's name, and the `services` package's names the server
package that imports it, so that a server package renamed or moved takes the package over.
"""

from __future__ import annotations

import re
from typing import Final

from datamodel_code_generator._module_paths import dotted_name

__all__ = [
    "SERVICES",
    "adopted",
    "beside",
    "generated_server",
    "implementations_docstring",
    "implementations_owner",
    "server_docstring",
    "services_package",
]

SERVICES: Final = "services"
"""The name of the package of the user's implementations, and of its directory beside the server package."""

_IMPLEMENTATIONS_OWNER = re.compile(r'^\ufeff?"""Your implementations of ([\w.]+), which ((?:\1\.main)?)', re.MULTILINE)
_SERVER_PACKAGE = re.compile(r'^\ufeff?"""FastAPI server (?:package ([\w.]+), )?generated by ', re.MULTILINE)


def beside(package: str, name: str) -> str:
    """Return the dotted name of the package `name` in the parent package of `package`, top level for a top one."""
    return dotted_name(package.rpartition(".")[0], name)


def services_package(server: str) -> str:
    """Return the package of the user's implementations that the server package `server` imports."""
    return beside(server, SERVICES)


def server_docstring(server: str) -> str:
    """Return the docstring of the initializer of the server package `server`, which names the package."""
    return f"FastAPI server package {server}, generated by datamodel-code-generator."


def generated_server(text: str, directory: str, server: str) -> str | None:
    """Return the server package that a package initializer's text says it is, or `None` for another initializer.

    The docstring names the package, whatever its directory's name; the docstring of earlier versions does not, so the
    package takes the name of its `directory` beside `server`.
    """
    return None if (found := _SERVER_PACKAGE.search(text)) is None else found[1] or beside(server, directory)


def _owner(server: str, *, main: bool) -> str:
    """Return the words of the implementations' docstring that name the server package and, with `main`, its entry."""
    return f"{server}, which {f'{server}.main' if main else ''}"


def implementations_docstring(server: str) -> str:
    """Return the docstring of the initializer of the implementations, which names the server package `server`."""
    return (
        f"Your implementations of {_owner(server, main=True)} imports.\n\n"
        "datamodel-code-generator wrote this file once and never overwrites it, or the modules beside it."
    )


def implementations_owner(text: str) -> re.Match[str] | None:
    """Return where the docstring of an initializer of implementations names its server package, if it does."""
    return _IMPLEMENTATIONS_OWNER.search(text)


def adopted(owner: re.Match[str], server: str) -> str:
    """Return an initializer of implementations whose docstring names another server package as this one's."""
    text = owner.string
    return f"{text[: owner.start(1)]}{_owner(server, main=bool(owner[2]))}{text[owner.end() :]}"
