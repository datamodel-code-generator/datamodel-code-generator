def read_surface(src: Path) -> Surface:
    """Return the public surface of the package under `src`: options and choices, `__all__`, config fields, templates.

    It also holds what a release fixes: a digest of the option set of each dated preset by date, the digest of the
    recommender rules (everything but `rules_revision` and the option registry, which no recommendation reads) with
    their revision, and the experimental feature ids with their `since_version`. It runs in a fresh interpreter, so the
    surface of a release tag's tree can be read next to this checkout's.
    """
    env = {**os.environ, "PYTHONPATH": str(src), "PYTHONWARNINGS": "ignore"}
    result = subprocess.run(
        [sys.executable, "-c", SURFACE_SCRIPT], capture_output=True, text=True, env=env, check=True, encoding="utf-8"
    )
    return json.loads(result.stdout)


def surface_items(surface: Surface) -> dict[str, str]:
    """Return every item of a surface by the name an entry's `affects` gives it, with the `affects` key it goes under.

    An option and each of its other spellings are `--name`, a choice `--name value`, a public name of the package its
    name, a `GenerateConfig` field `GenerateConfig.<field>`, a builtin template its path under the template directory.
    """
    items: dict[str, str] = {}
    for name, option in surface["options"].items():
        items |= dict.fromkeys([name, *option["aliases"]], "options")
        items |= {f"{name} {choice}": "options" for choice in option["choices"] or []}
    items |= dict.fromkeys(surface["python_api"], "python_api")
    items |= {f"GenerateConfig.{name}": "python_api" for name in surface["generate_config"]}
    return items | dict.fromkeys(surface["templates"], "templates")


def _option_additions(current: Surface, released: Surface) -> list[str]:
    """Return the options and choices of `current` that `released` lacks, as `--name` and `--name=value` keys.

    New `--preset` names are left out: the entry of their preset date lists what they add.
    """
    added = []
    for name, option in current["options"].items():
        if name not in released["options"]:
            added.append(name)
            continue
        if name == PRESET_OPTION:
            continue
        old = set(released["options"][name]["choices"] or [])
        added += [f"{name}={choice}" for choice in option["choices"] or [] if choice not in old]
    return added


def _option_entry(key: str, release: str, current: Surface) -> dict[str, Any]:
    name, _, choice = key.partition("=")
    option = current["options"].get(name)
    title = f"New value `{choice}` of `{name}`" if choice else f"New option `{name}`"
    if option and not choice and option["aliases"]:
        title += f" ({', '.join(f'`{alias}`' for alias in option['aliases'])})"
    summary = option["help"] if option and option["help"] and not choice else f"{title}."
    return {
        "release": release,
        "kind": "cli",
        "action": "none",
        "title": title,
        "summary": summary,
        "affects": {},
        "source": "surface",
        "note": f"{title}: {summary}" if summary != f"{title}." else title,
    }


def _code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"`` {text} ``"


def _anchor(entry_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", entry_id.lower()).strip("-")


def _read_toml(path: Path, problems: list[str]) -> dict[str, Any]:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        problems.append(f"{path.name}: {error.strerror}")
    except tomllib.TOMLDecodeError as error:
        problems.append(f"{path.name}: {error}")
    return {}


def _load_releases(layout: Layout, problems: list[str]) -> tuple[list[dict[str, str]], str]:
    """Return the release rows and `complete_from`, which defaults to the oldest release (every list complete)."""
    table = _read_toml(layout.releases, problems)
    releases = table.get("release", [])
    problems.extend(
        f"releases.toml: {release} is not a row of `version` and `date` (YYYY-MM-DD)"
        for release in releases
        if set(release) != {"version", "date"} or not DATE_PATTERN.fullmatch(str(release.get("date")))
    )
    versions = [str(release.get("version")) for release in releases]
    if not versions:
        problems.append("releases.toml lists no release")
    for older, newer in pairwise(versions):
        if version_key(older) >= version_key(newer):
            problems.append(f"releases.toml: {newer} does not come after {older}")
    complete_from = str(table.get("complete_from", versions[0] if versions else ""))
    if versions and complete_from not in versions:
        problems.append(f"releases.toml: complete_from {complete_from} is not a listed release")
    return releases, complete_from


def _registry_affects(kind: str, target: str) -> dict[str, list[str]]:
    match kind:
        case "cli-option":
            return {"options": [target]}
        case "python-api":
            return {"python_api": [target]}
    return {}


class _Releases:
    """Maps a version a registry or a data file names to the release the guide puts it in."""

    def __init__(self, releases: list[dict[str, str]], problems: list[str]) -> None:
        self.versions = [str(release.get("version")) for release in releases]
        self.problems = problems

    def place(self, version: str, where: str) -> str | None:
        """Return the release a version belongs to: itself, `unreleased` after the latest one, None before the floor."""
        if version in self.versions or version == UNRELEASED:
            return version
        if not self.versions or version_key(version) > version_key(self.versions[-1]):
            return UNRELEASED
        if version_key(version) < version_key(self.versions[0]):
            return None
        self.problems.append(f"{where}: {version} was never released")
        return None


def _derived_changes(
    registries: Registries, presets: dict[str, str], releases: _Releases, problems: list[str]
) -> dict[str, dict[str, Any]]:
    """Return the entries the registries give, by id."""
    changes: dict[str, dict[str, Any]] = {}
    for item in registries.deprecations:
        affects = _registry_affects(item.kind, item.target)
        if release := releases.place(item.warning_since, f"deprecation {item.id}"):
            scheduled = item.status == "scheduled"
            changes[f"{DEPRECATION_PREFIX}{item.id}"] = {
                "release": release,
                "kind": "warning",
                "action": "none" if scheduled else "warn",
                "title": f"{item.target} {'is scheduled to change' if scheduled else 'now emits'}"
                + ("" if scheduled else f" {item.warning_category}"),
                "summary": item.message,
                "migrate": item.replacement,
                "affects": affects,
                "source": "registry",
                "note": _release_note_line(item),
            }
        if item.removal_version and (release := releases.place(item.removal_version, f"deprecation {item.id}")):
            changes[f"removal:{item.id}"] = {
                "release": release,
                "kind": "removal",
                "action": "required",
                "title": f"{item.target} is removed",
                "summary": item.message,
                "migrate": item.replacement or item.message,
                "affects": affects,
                "source": "registry",
                "note": _removal_release_note_line(item),
            }
    for feature in registries.experimental:
        if release := releases.place(feature.since_version, f"experimental feature {feature.id}"):
            changes[f"experimental:{feature.id}"] = {
                "release": release,
                "kind": "experimental",
                "action": "none",
                "title": f"{feature.target} is experimental",
                "summary": feature.message,
                "affects": {"experimental": [feature.id]},
                "source": "registry",
                "note": _experimental_release_note_line(feature),
            }
    dates = {preset.date for preset in registries.preset_dates}
    problems.extend(
        f"derived.toml: preset date {date} is not in the source tree" for date in presets if date not in dates
    )
    for preset in registries.preset_dates:
        release = (
            releases.place(presets[preset.date], f"preset {preset.date}") if preset.date in presets else UNRELEASED
        )
        if not release:
            continue
        names = f"`standard-py3XX-{preset.date}` and `practical-py3XX-{preset.date}`"
        if preset.previous is None:
            summary = f"The first dated presets; the [presets page]({SITE_URL}/presets/) lists their options."
            note = summary
        else:
            summary = f"They keep the options of the {preset.previous} presets and add:\n\n" + "\n".join(
                preset.additions
            )
            added = "; ".join(item.removeprefix("- ").removesuffix(".") for item in preset.additions)
            note = f"they keep the {preset.previous} options and add {added}."
        changes[f"preset:{preset.date}"] = {
            "release": release,
            "kind": "preset",
            "action": "none",
            "title": f"New dated presets {names}",
            "summary": summary,
            "source": "registry",
            "note": f"{names}: {note}",
        }
    return changes


def _hand_files(layout: Layout, releases: _Releases, problems: list[str]) -> list[tuple[str, Path]]:
    files = []
    for path in sorted(layout.changes.glob("*.toml"), key=lambda path: version_key(path.stem)):
        if path.stem not in releases.versions:
            problems.append(f"changes/{path.name}: {path.stem} is not in releases.toml")
            continue
        files.append((path.stem, path))
    return files + [(UNRELEASED, path) for path in sorted(layout.unreleased.glob("*.toml"))]


def _hand_changes(
    layout: Layout, changes: dict[str, dict[str, Any]], releases: _Releases, facts: Facts, problems: list[str]
) -> None:
    """Add the guide entries of the hand-written records to `changes`; one with the id of a derived entry extends it.

    A new record's id is a lower-case slug; the id of a derived entry is taken as the build gives it, such as
    `option:--output-model-type=msgspec.Struct`. Records of a category without a guide entry, and records that extend
    another record, are checked and left out of the guide.
    """
    derived = set(changes)
    seen: dict[str, str] = {}
    fragments: dict[str, Record] = {}
    for release, path in _hand_files(layout, releases, problems):
        entries = _read_toml(path, problems).get("change", [])
        where = f"{path.parent.name}/{path.name}"
        fragment = release == UNRELEASED
        if fragment and [entry.get("id") for entry in entries] != [path.stem]:
            problems.append(f"{where}: a fragment holds exactly one [[change]] whose id is the file name")
        for entry in entries:
            record, found = parse_entry(entry, where)
            problems += found
            if record is None:
                continue
            if record.id in seen:
                problems.append(f"{where}: id {record.id} is also in {seen[record.id]}")
                continue
            seen[record.id] = where
            problems += rule_problems(record, fragment=fragment, facts=facts)
            if fragment:
                fragments[record.id] = record
                if not covers_written(text := path.read_text(encoding="utf-8"), record):
                    problems.append(f"{where}: covers are written by 'python scripts/declared_changes.py declare' only")
                if not cells_written(text):
                    problems.append(f"{where}: cells are written as [[change.cells]] tables only")
            if not record.guide:
                continue
            if record.derived:
                if record.id not in derived:
                    problems.append(f"{where}: {record.id} extends no derived entry")
                    continue
                if changes[record.id]["release"] != release:
                    problems.append(f"{where}: {record.id} belongs to {changes[record.id]['release']}")
            changes[record.id] = changes.get(record.id, {}) | record.guide_fields() | {"release": release}
    problems.extend(
        f"entry {record.id}: extends {record.extends}, which is not an unreleased record of its own"
        for record in fragments.values()
        if record.extends is not None
        and ((target := fragments.get(record.extends)) is None or target.extends is not None or target.derived)
    )
    unreleased = {entry_id for entry_id, entry in changes.items() if entry["release"] == UNRELEASED}
    for record in fragments.values():
        for entry_id in _note_entries(record, unreleased):
            entry = changes[entry_id]
            entry["records"] = [*entry.get("records", []), record.id]
            entry["record_refs"] = [*entry.get("record_refs", []), *record.refs]


def _note_entries(record: Record, unreleased: set[str]) -> list[str]:
    """Return the ids of the unreleased entries whose release-note item a fragment adds its pull request and refs to.

    A guide record adds them to its own entry and a `new-surface` record to the derived entries of the options, option
    values and preset dates it names. A record that extends another only covers more output of the same change, which
    a later pull request (a stack layer, a test move) may add, so it adds nothing.
    """
    if record.guide:
        return [record.id] if record.id in unreleased else []
    if record.category != Category.NEW_SURFACE:
        return []
    ids = [
        item if item.startswith(PRESET_SURFACE) else f"option:{item.replace(' ', '=', 1)}" for item in record.surface
    ]
    return [entry_id for entry_id in ids if entry_id in unreleased]


def _check_links(changes: dict[str, dict[str, Any]], order: dict[str, int], problems: list[str]) -> None:
    for entry in changes.values():
        supersedes = entry.get("supersedes", [])
        targets = [
            *(supersedes if isinstance(supersedes, list) else []),
            *([entry["reverts"]] if "reverts" in entry else []),
        ]
        for target in targets:
            if target not in changes:
                problems.append(f"entry {entry['id']}: {target} is not an entry")
            elif order[changes[target]["release"]] > order[entry["release"]]:
                problems.append(f"entry {entry['id']}: {target} comes after it")


def keep_config(flags: list[str]) -> dict[str, Any]:
    """Return the pyproject.toml values the command-line flags set, keyed as pyproject.toml spells them.

    Raises ValueError with the parser's message when the flags are not valid options of this source tree.
    """
    from datamodel_code_generator.__main__ import (  # ruff: ignore[import-outside-top-level]
        generate_pyproject_config,
    )
    from datamodel_code_generator.arguments import arg_parser  # ruff: ignore[import-outside-top-level]

