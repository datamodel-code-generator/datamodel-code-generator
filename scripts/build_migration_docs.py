"""Build the upgrade guide from the declarative change list.

Usage:
    python scripts/build_migration_docs.py
    python scripts/build_migration_docs.py --check
    python scripts/build_migration_docs.py --release-notes unreleased
    python scripts/build_migration_docs.py --has-breaking unreleased
    python scripts/build_migration_docs.py --stamp 0.97.0 --tag-tree DIR [--date 2026-12-01]
    python scripts/build_migration_docs.py --range-pages docs/migration
    python scripts/build_migration_docs.py --raw-site site

Data (docs/data/migration/): `releases.toml` (every published release since the oldest one the guide covers),
`changes/<version>.toml` (the hand-written `[[change]]` entries of a release), `unreleased/<id>.toml` (one entry per
file until the release stamps it) and `derived.toml` (the first release of each dated preset). The deprecation and
experimental registries and the dated presets of the source tree add entries nobody writes by hand; a hand entry
with the id of such an entry extends it.

The build writes the committed pages docs/migration/index.md (the hub), docs/migration/changes.md (every change by
release) and docs/data/migration.json. `--range-pages` writes the page of each range of releases that need the same
steps, `--raw-site` the Markdown of each release under `<site>/migration/from/<version>.md`; the docs deploy builds
both. `--release-notes` prints the release-note sections of a release from the same entries, `--has-breaking` exits 0
when the release has a breaking change and 1 otherwise, and `--stamp` moves the fragments a release tag contains into
the changes of that release.
"""

