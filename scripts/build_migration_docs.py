def _steps_after(changes: list[dict[str, Any]], index: int, *, unreleased: bool = False) -> list[dict[str, Any]]:
    """Return the entries a user of the release at `index` meets on the way to the latest release.

    An entry another entry on the path supersedes is left out, and so is a pair of an entry and the one that reverts it.
    Unreleased entries are on the path only with `unreleased`, the way to this checkout.
    """
    path = [entry for entry in changes if index < entry["index"] and (unreleased or entry["release"] != UNRELEASED)]
    ids = {entry["id"] for entry in path}
    dropped = {old for entry in path for old in entry.get("supersedes", []) if old in ids}
    dropped |= {
        entry_id for entry in path if (undone := entry.get("reverts")) in ids for entry_id in (undone, entry["id"])
    }
    return [entry for entry in path if entry["id"] not in dropped]


def _keep_configs(changes: list[dict[str, Any]], problems: list[str]) -> dict[str, dict[str, Any]]:
    """Return the `pyproject.toml` values of the keep flags of every entry that has them, by entry id.

    The flags of every entry are parsed, also those of an entry `affects.options` narrows and of an unreleased one,
    whose values no page writes.
    """
    configs: dict[str, dict[str, Any]] = {}
    for entry in changes:
        if not (flags := entry.get("keep", {}).get("flags")):
            continue
        try:
            configs[entry["id"]] = keep_config(flags)
        except ValueError as error:
            problems.append(f"entry {entry['id']}: keep.flags {' '.join(flags)!r}: {error}")
            configs[entry["id"]] = {}
    return configs


def _ranges(
    releases: list[dict[str, str]], changes: list[dict[str, Any]], complete_from: str, problems: list[str]
) -> list[Range]:
    """Group consecutive source releases whose steps that need an action are the same, and complete or not alike."""
    configs = _keep_configs(changes, problems)
    ranges: list[Range] = []
    for index, release in enumerate(releases[:-1]):
        path = _steps_after(changes, index)
        steps = tuple(entry["id"] for entry in path if entry["action"] != "none")
        complete = version_key(release["version"]) >= version_key(complete_from)
        if ranges and ranges[-1].steps == steps and ranges[-1].complete == complete:
            ranges[-1].sources.append(release["version"])
            continue
        ranges.append(Range([release["version"]], steps, path, complete=complete))
    for group in ranges:
        unconditional: dict[str, tuple[str, Any]] = {}
        for entry in group.path:
            if entry["id"] not in configs:
                continue
            flags = entry["keep"]["flags"]
            if (only := entry["affects"].get("options")) is not None:
                group.keep_conditional.setdefault(", ".join(only), []).extend(flags)
                continue
            group.keep_flags += flags
            for key, value in configs[entry["id"]].items():
                if key in unconditional and unconditional[key][1] != value:
                    problems.append(
                        f"range from {group.first}: {entry['id']} and {unconditional[key][0]} set {key} differently"
                    )
                unconditional.setdefault(key, (entry["id"], value))
                group.keep_pyproject[key] = unconditional[key][1]
    return ranges


def _read_surface_file(layout: Layout, problems: list[str]) -> Surface | None:
    try:
        surface = json.loads(layout.surface.read_text(encoding="utf-8"))
    except OSError as error:
        problems.append(f"{layout.surface.name}: {error.strerror}")
    except json.JSONDecodeError as error:
        problems.append(f"{layout.surface.name}: {error}")
    else:
        if not (missing := [key for key in Surface.__annotations__ if key not in surface]):
            return surface
        problems.append(f"{layout.surface.name}: no {', '.join(missing)}")
    return None


def _check_released(
    current: Surface,
    released: Surface,
    latest: str,
    experimental: tuple[ExperimentalFeature, ...],
    problems: list[str],
) -> None:
    """Report what changes the facts the latest release fixed.

    The presets of a date the release ships are frozen and none of them is removed or replaced; one date at most is
    unreleased. Rules that differ from the
    release's carry a new `rules_revision`. An experimental feature the release lacks names a later `since_version`,
    and one it has keeps the `since_version` it shipped with.
    """
    shipped = released["presets"]
    if len(unreleased := sorted(current["presets"].keys() - shipped.keys())) > 1:
        problems.append(
            f"presets: dates {', '.join(unreleased)} are unreleased; add the options of this release to one date; "
            "if the latest tag is not stamped yet, stamp it first"
        )
    problems.extend(
        f"preset {name}: {'its options differ from' if name in shipped[date] else 'is not one of'} the {date} presets "
        f"of {latest}; released presets are frozen, so change the unreleased date's"
        for date, names in current["presets"].items()
        if date in shipped
        for name, digest in names.items()
        if shipped[date].get(name) != digest
    )
    problems.extend(
        f"preset {name}: the {date} presets of {latest} include it, but this tree no longer does; released presets "
        "are frozen"
        for date, names in shipped.items()
        for name in names
        if name not in current["presets"].get(date, {})
    )
    rules, released_rules = current["recommender_rules"], released["recommender_rules"]
    if rules["digest"] != released_rules["digest"] and rules["revision"] == released_rules["revision"]:
        problems.append(
            f"recommender_rules.json: the rules differ from those of {latest} and rules_revision is still "
            f"{rules['revision']}; set it to the date of the change"
        )
    problems.extend(
        f"experimental feature {feature.id}: since_version {feature.since_version} differs from {since}, which "
        f"{latest} ships"
        for feature in experimental
        if (since := released["experimental"].get(feature.id, feature.since_version)) != feature.since_version
    )
    problems.extend(
        f"experimental feature {feature.id}: {latest} lacks it, so since_version {feature.since_version} must name a "
        "later release"
        for feature in experimental
        if feature.id not in released["experimental"]
        and feature.since_version != UNRELEASED
        and version_key(feature.since_version) <= version_key(latest)
    )


def _check_removals(
    current: Surface, released: Surface, changes: dict[str, dict[str, Any]], problems: list[str]
) -> None:
    """Report each item of the latest release's surface that is gone and that no unreleased entry names."""
    named = {
        (key, value)
        for entry in changes.values()
        if entry["release"] == UNRELEASED
        for key, values in entry["affects"].items()
        for value in values
    }
    present = surface_items(current)
    problems.extend(
        f"surface: {item} of the latest release is gone; an unreleased entry names it in affects.{key}, or the "
        "deprecation registry schedules its removal"
        for item, key in surface_items(released).items()
        if item not in present and (key, item) not in named
    )


def previous_release(versions: list[str], entry: dict[str, Any]) -> str:
    """Return the release before an entry's release, the latest one for an unreleased entry: its output is recorded."""
    return versions[entry["index"] - 1]


def fixture_key(entry: dict[str, Any]) -> str:
    """Return the key of an entry's fixture: a record is stale once the schema or the arguments change."""
    verify = entry["verify"]
    return hashlib.sha256(json.dumps([verify["schema"], verify["args"]]).encode()).hexdigest()[:16]


def _read_records(layout: Layout) -> dict[str, Any]:
    return json.loads(layout.recorded.read_text(encoding="utf-8")) if layout.recorded.exists() else {}


def _check_records(
    layout: Layout, versions: list[str], changes: dict[str, dict[str, Any]], problems: list[str]
) -> None:
    """Report each entry with a fixture whose previous release's output is not recorded for its current fixture.

    A record is of the fixture and of the release before the entry's: one taken before the entry moved to another
    release is stale too.
    """
    records = _read_records(layout)
    for entry_id, entry in changes.items():
        record = records.get(entry_id, {})
        if entry.get("source") == "run" and (
            record.get("fixture") != fixture_key(entry) or record.get("previous") != previous_release(versions, entry)
        ):
            problems.append(
                f"entry {entry_id}: no recorded output of its previous release for its fixture; run "
                f"'python scripts/build_migration_docs.py --record {entry_id}'"
            )


def _facts(registries: Registries, released_surface: Surface, changes: dict[str, dict[str, Any]]) -> Facts:
    """Return what the rules of the records read: the derived entries give the releases of features and presets."""
    unreleased = {entry_id for entry_id, entry in changes.items() if entry["release"] == UNRELEASED}
    features = {feature.id for feature in registries.experimental}
    presets = {f"{PRESET_SURFACE}{preset.date}" for preset in registries.preset_dates}
    surface = set(surface_items(registries.surface)) | presets
    return Facts(
        features=frozenset(feature for feature in features if f"experimental:{feature}" not in unreleased),
        unreleased_features=frozenset(feature for feature in features if f"experimental:{feature}" in unreleased),
        scheduled=frozenset(item.target for item in registries.deprecations if item.removal_version),
        new_surface=frozenset(
            item
            for item in surface - set(surface_items(released_surface))
            if not item.startswith(PRESET_SURFACE) or item in unreleased
        ),
        surface=frozenset(surface),
    )


def load(
    layout: Layout | None = None,
    registries: Registries | None = None,
    *,
    records: bool = True,
    released_check: bool = True,
) -> Guide:
    """Load, derive and check the change list; raise MigrationDataError with every problem found.

    Without `records`, an entry with a fixture may lack the recorded output `--record` is about to write. Without
    `released_check`, the tree is not held to the facts of surface.json, which `--stamp` is about to replace by the
    tag's and checks the tree against.
    """
    layout = layout or Layout()
    registries = registries or current_registries()
    problems: list[str] = []
    releases, complete_from = _load_releases(layout, problems)
    placed = _Releases(releases, problems)
    derived = _read_toml(layout.derived, problems)
    presets = {str(date): str(version) for date, version in derived.get("presets", {}).items()}
    changes = _derived_changes(registries, presets, placed, problems)
    released = _read_surface_file(layout, problems)
    released_surface = released or EMPTY_SURFACE
    option_releases = {str(key): str(version) for key, version in derived.get("options", {}).items()}
    option_releases |= dict.fromkeys(_option_additions(registries.surface, released_surface), UNRELEASED)
    for key, version in option_releases.items():
        if release := placed.place(version, f"option {key}"):
            changes[f"option:{key}"] = _option_entry(key, release, registries.surface)
    _hand_changes(layout, changes, placed, _facts(registries, released_surface, changes), problems)
    order = {version: index for index, version in enumerate(placed.versions)} | {UNRELEASED: len(placed.versions)}
    for entry_id, entry in changes.items():
        entry["id"] = entry_id
        entry["anchor"] = _anchor(entry_id)
        entry["index"] = order[entry["release"]]
        entry["affects"] = {key: values for key, values in entry_table(entry, "affects").items() if values}
        problems += guide_problems(entry)
    _check_links(changes, order, problems)
    _check_removals(registries.surface, released_surface, changes, problems)
    if released and released_check and placed.versions:
        _check_released(registries.surface, released, placed.versions[-1], registries.experimental, problems)
    if records and not problems:
        _check_records(layout, placed.versions, changes, problems)
    action_order = {action: index for index, action in enumerate(ACTIONS)}
    ordered = sorted(
        changes.values(),
        key=lambda entry: (entry["index"], action_order.get(entry.get("action"), len(ACTIONS)), entry["id"]),
    )
    ranges = _ranges(releases, ordered, complete_from, problems) if releases and not problems else []
    if problems:
        raise MigrationDataError(problems)
    return Guide(releases, ordered, ranges, complete_from)


def _affects_line(entry: dict[str, Any]) -> str | None:
    parts = [f"{AFFECTS[name]}: {', '.join(map(_code, values))}" for name, values in entry["affects"].items()]
    return "; ".join(parts) or None


def _refs(entry: dict[str, Any]) -> str:
    return ", ".join(f"[{ref}]({REPO_URL}/issues/{ref[1:]})" for ref in entry.get("refs", []))


def _details_link(entry: dict[str, Any], base: str) -> str:
    return f"[details]({base}#{entry['anchor']})"


def entry_markdown(entry: dict[str, Any], level: int = 3) -> list[str]:
    """Return one entry in full: heading with its release and anchor, summary, details and the before/after lines."""
    release = "unreleased" if entry["release"] == UNRELEASED else entry["release"]
    lines = [f"{'#' * level} {entry['title']} ({release}) {{ #{entry['anchor']} }}", "", entry["summary"], ""]
    if affects := _affects_line(entry):
        lines.append(f"- **Affects:** {affects}")
    keep = entry.get("keep", {})
    if keep.get("flags"):
        lines.append(f"- **Keep the old output:** {_code(' '.join(keep['flags']))}")
    if keep.get("note"):
        lines.append(f"- **Keep the old output:** {keep['note']}")
    if entry.get("migrate"):
        lines.append(f"- **What to change:** {entry['migrate']}")
    if refs := _refs(entry):
        lines.append(f"- **Pull requests and issues:** {refs}")
    lines += [f"- **Source:** {SOURCES[entry['source']]}", ""]
    if entry.get("before") or entry.get("after"):
        lines += ["```diff", *(f"-{line}" for line in entry.get("before", "").splitlines())]
        lines += [*(f"+{line}" for line in entry.get("after", "").splitlines()), "```", ""]
    return lines


def _toml_line(name: str, value: object) -> str:
    return f"{name} = {str(value).lower() if isinstance(value, bool) else json.dumps(value, ensure_ascii=False)}"


def _keep_block(group: Range, latest: str) -> list[str]:
    notes = [
        f"- {entry['title']}: {entry['keep']['note']}"
        for entry in group.path
        if entry["action"] == "keep" and not entry.get("keep", {}).get("flags") and entry.get("keep", {}).get("note")
    ]
    notes = ["Outside the command line:", "", *notes, ""] if notes else []
    if not group.keep_flags and not group.keep_conditional:
        return notes or ["No option is needed to keep your output; check the changes below.", ""]
    lines = []
    if group.keep_flags:
        lines += [
            (
                f"Add these options to keep the output of your release where {latest} can (every option exists in "
                f"{latest}):"
            ),
            "",
            "```bash",
            "datamodel-codegen ... " + " ".join(group.keep_flags),
            "```",
            "",
            "or in `pyproject.toml`:",
            "",
            "```toml",
            "[tool.datamodel-codegen]",
            *starmap(_toml_line, group.keep_pyproject.items()),
            "```",
            "",
        ]
    for only, flags in group.keep_conditional.items():
        lines += [f"Only if you pass {_code(only)}, also add {_code(' '.join(flags))}.", ""]
    return lines + notes


def _is_deprecation(entry: dict[str, Any]) -> bool:
    """Return whether an entry is a deprecation of the registry, or a hand entry that extends one by its id."""
    return entry["id"].startswith(DEPRECATION_PREFIX)


def _action_sections(action: str, entries: list[dict[str, Any]]) -> list[tuple[str, list[dict[str, Any]]]]:
    """Return the headings of one action's entries; the warnings that deprecate nothing get their own heading."""
    sections = [(ACTIONS[action], entries)]
    if action == "warn":
        sections = [
            (ACTIONS[action], [entry for entry in entries if _is_deprecation(entry)]),
            (NEW_WARNINGS, [entry for entry in entries if not _is_deprecation(entry)]),
        ]
    return [(heading, chosen) for heading, chosen in sections if chosen]


def _short_line(entry: dict[str, Any], base: str) -> str:
    release = "unreleased" if entry["release"] == UNRELEASED else entry["release"]
    line = f"- {entry['title']} ({release})"
    if entry["action"] == "warn":
        if entry.get("migrate"):
            line += f": {entry['migrate']}"
        if only := [value for values in entry["affects"].values() for value in values]:
            line += f" Only if you use {', '.join(map(_code, only))}."
    return f"{line} {_details_link(entry, base)}"


def _incomplete_note(group: Range, complete_from: str) -> list[str]:
    """Return the warning a range whose steps are incomplete starts with, pointing to the changelog."""
    if group.complete:
        return []
    return [
        (
            f"**Incomplete list:** the changes of the releases after yours through {complete_from} are not all listed "
            f"yet. Read the breaking changes of those releases in the [changelog]({CHANGELOG_URL}) too; every change "
            f"after {complete_from} is listed."
        ),
        "",
    ]


def guide_page(title: str, intro: str, group: Range, guide: Guide, base: str) -> str:
    """Return the steps of one range or release: the keep options, then the entries by action.

    `base` is where the entries' details are: the all-changes page, relative or as a URL.
    """
    path = group.path
    latest = guide.latest
    counts = {action: sum(entry["action"] == action for entry in path) for action in ACTIONS}
    lines = [
        f"# {title}",
        "",
        GENERATED,
        "",
        (
            f"{intro} On the way to {latest}: {counts['required']} required changes, {counts['keep']} output changes "
            f"an option keeps, {counts['review']} changes no option keeps, {counts['warn']} new warnings, "
            f"{counts['none']} changes that need nothing. Each item names the release that made it. "
            f"[All changes]({base}) · [Machine-readable list]({SITE_URL}/data/migration.json)"
        ),
        "",
        *_incomplete_note(group, guide.complete_from),
        "## Keep your current output",
        "",
        *_keep_block(group, latest),
    ]
    for action in ACTIONS:
        for heading, entries in _action_sections(action, [entry for entry in path if entry["action"] == action]):
            lines += [f"## {heading}", ""]
            if action in {"none", "warn"}:
                lines += [*(_short_line(entry, base) for entry in entries), ""]
                continue
            for entry in entries:
                lines += entry_markdown(entry)
    return "\n".join(lines).rstrip() + "\n"


def range_page(guide: Guide, group: Range) -> str:
    """Return the page of one range of source releases."""
    intro = f"For datamodel-code-generator {group.span} ({len(group.sources)} releases)."
    if len(group.sources) == 1:
        intro = f"For datamodel-code-generator {group.first}."
    title = f"Upgrading from {group.span} to {guide.latest}"
    return guide_page(title, intro, group, guide, CHANGES_PAGE)


def raw_page(guide: Guide, version: str) -> str:
    """Return the self-contained Markdown of the steps from one exact release, for coding agents."""
    versions = [release["version"] for release in guide.releases]
    if version == guide.latest:
        return f"# datamodel-code-generator {version}\n\n{version} is the latest release: nothing to change.\n"
    group = next(group for group in guide.ranges if version in group.sources)
    exact = replace(group, sources=[version], path=_steps_after(guide.changes, versions.index(version)))
    intro = (
        f"For datamodel-code-generator {version}; the [upgrade guide]({SITE_URL}/migration/) has the other releases."
    )
    title = f"Upgrading from {version} to {guide.latest}"
    return guide_page(title, intro, exact, guide, f"{SITE_URL}/migration/changes/")


def _incomplete_mark(group: Range) -> str:
    return "" if group.complete else " (incomplete list)"


