def _code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"`` {text} ``"


def _anchor(entry_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", entry_id.lower()).strip("-")


def _read_toml(path: Path, problems: list[str]) -> dict[str, Any]:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as error:
        problems.append(f"{path.name}: {error}")
        return {}


def _load_releases(layout: Layout, problems: list[str]) -> list[dict[str, str]]:
    releases = _read_toml(layout.releases, problems).get("release", [])
    problems.extend(
        f"releases.toml: {release} is not a row of `version` and `date` (YYYY-MM-DD)"
        for release in releases
        if set(release) != {"version", "date"} or not DATE_PATTERN.fullmatch(str(release.get("date")))
    )
    versions = [str(release.get("version")) for release in releases]
    if not versions:
        problems.append("releases.toml lists no release")
    for older, newer in pairwise(versions):
        if version_key(older) >= version_key(newer):
            problems.append(f"releases.toml: {newer} does not come after {older}")
    return releases


def _registry_affects(kind: str, target: str) -> dict[str, list[str]]:
    match kind:
        case "cli-option":
            return {"options": [target]}
        case "python-api":
            return {"python_api": [target]}
    return {}


class _Releases:
    """Maps a version a registry or a data file names to the release the guide puts it in."""

    def __init__(self, releases: list[dict[str, str]], problems: list[str]) -> None:
        self.versions = [str(release.get("version")) for release in releases]
        self.problems = problems

    def place(self, version: str, where: str) -> str | None:
        """Return the release a version belongs to: itself, `unreleased` after the latest one, None before the floor."""
        if version in self.versions:
            return version
        if not self.versions or version_key(version) > version_key(self.versions[-1]):
            return UNRELEASED
        if version_key(version) < version_key(self.versions[0]):
            return None
        self.problems.append(f"{where}: {version} was never released")
        return None


def _derived_changes(
    registries: Registries, presets: dict[str, str], releases: _Releases, problems: list[str]
) -> dict[str, dict[str, Any]]:
    """Return the entries the registries give, by id."""
    changes: dict[str, dict[str, Any]] = {}
    for item in registries.deprecations:
        affects = _registry_affects(item.kind, item.target)
        if release := releases.place(item.warning_since, f"deprecation {item.id}"):
            scheduled = item.status == "scheduled"
            changes[f"deprecation:{item.id}"] = {
                "release": release,
                "kind": "warning",
                "action": "none" if scheduled else "warn",
                "title": f"{item.target} {'is scheduled to change' if scheduled else 'now emits'}"
                + ("" if scheduled else f" {item.warning_category}"),
                "summary": item.message,
                "migrate": item.replacement,
                "affects": affects,
                "source": "registry",
                "note": _release_note_line(item),
            }
        if item.removal_version and (release := releases.place(item.removal_version, f"deprecation {item.id}")):
            changes[f"removal:{item.id}"] = {
                "release": release,
                "kind": "removal",
                "action": "required",
                "title": f"{item.target} is removed",
                "summary": item.message,
                "migrate": item.replacement or item.message,
                "affects": affects,
                "source": "registry",
                "note": _removal_release_note_line(item),
            }
    for feature in registries.experimental:
        if release := releases.place(feature.since_version, f"experimental feature {feature.id}"):
            changes[f"experimental:{feature.id}"] = {
                "release": release,
                "kind": "experimental",
                "action": "none",
                "title": f"{feature.target} is experimental",
                "summary": feature.message,
                "affects": {"experimental": [feature.id]},
                "source": "registry",
                "note": _experimental_release_note_line(feature),
            }
    dates = {preset.date for preset in registries.preset_dates}
    problems.extend(
        f"derived.toml: preset date {date} is not in the source tree" for date in presets if date not in dates
    )
    for preset in registries.preset_dates:
        release = (
            releases.place(presets[preset.date], f"preset {preset.date}") if preset.date in presets else UNRELEASED
        )
        if not release:
            continue
        names = f"`standard-py3XX-{preset.date}` and `practical-py3XX-{preset.date}`"
        if preset.previous is None:
            summary = f"The first dated presets; the [presets page]({SITE_URL}/presets/) lists their options."
            note = summary
        else:
            summary = f"They keep the options of the {preset.previous} presets and add:\n\n" + "\n".join(
                preset.additions
            )
            added = "; ".join(item.removeprefix("- ").removesuffix(".") for item in preset.additions)
            note = f"they keep the {preset.previous} options and add {added}."
        changes[f"preset:{preset.date}"] = {
            "release": release,
            "kind": "preset",
            "action": "none",
            "title": f"New dated presets {names}",
            "summary": summary,
            "source": "registry",
            "note": f"{names}: {note}",
        }
    return changes


def _hand_files(layout: Layout, releases: _Releases, problems: list[str]) -> list[tuple[str, Path]]:
    files = []
    for path in sorted(layout.changes.glob("*.toml"), key=lambda path: version_key(path.stem)):
        if path.stem not in releases.versions:
            problems.append(f"changes/{path.name}: {path.stem} is not in releases.toml")
            continue
        files.append((path.stem, path))
    return files + [(UNRELEASED, path) for path in sorted(layout.unreleased.glob("*.toml"))]


def _check_shape(entry_id: str, entry: dict[str, Any], problems: list[str]) -> None:
    where = f"entry {entry_id}"
    problems.extend(f"{where}: unknown key {key}" for key in sorted(set(entry) - ENTRY_KEYS))
    problems.extend(
        f"{where}: {key} is not a string" for key in TEXT_KEYS if key in entry and not isinstance(entry[key], str)
    )
    for key, allowed in (("kind", KINDS), ("action", ACTIONS), ("source", SOURCES)):
        if key in entry and entry[key] not in allowed:
            problems.append(f"{where}: {key} {entry[key]!r} is not one of {', '.join(allowed)}")
    affects = entry.get("affects", {})
    if not isinstance(affects, dict):
        problems.append(f"{where}: affects is not a table")
    else:
        problems.extend(f"{where}: unknown affects key {key}" for key in sorted(set(affects) - set(AFFECTS)))
        problems.extend(
            f"{where}: affects.{key} is not a list of strings"
            for key, values in affects.items()
            if not isinstance(values, list) or not all(isinstance(value, str) for value in values)
        )
    for key, allowed in (("keep", KEEP_KEYS), ("verify", VERIFY_KEYS)):
        if not isinstance(table := entry.get(key, {}), dict):
            problems.append(f"{where}: {key} is not a table")
            continue
        problems.extend(f"{where}: unknown {key} key {name}" for name in sorted(set(table) - allowed))
    if not isinstance(flags := _table(entry, "keep").get("flags", []), list) or not all(
        isinstance(flag, str) for flag in flags
    ):
        problems.append(f"{where}: keep.flags is not a list of strings")
    problems.extend(
        f"{where}: {key} is not a list of strings"
        for key in ("refs", "supersedes")
        if not isinstance(values := entry.get(key, []), list) or not all(isinstance(value, str) for value in values)
    )
    problems.extend(
        f"{where}: ref {ref!r} is not #<number>" for ref in entry.get("refs", []) if not REF_PATTERN.fullmatch(str(ref))
    )


def _hand_changes(layout: Layout, changes: dict[str, dict[str, Any]], releases: _Releases, problems: list[str]) -> None:
    """Add the hand-written entries to `changes`; one with the id of a derived entry extends it."""
    derived = set(changes)
    seen: dict[str, str] = {}
    for release, path in _hand_files(layout, releases, problems):
        entries = _read_toml(path, problems).get("change", [])
        where = f"{path.parent.name}/{path.name}"
        if release == UNRELEASED and [entry.get("id") for entry in entries] != [path.stem]:
            problems.append(f"{where}: a fragment holds exactly one [[change]] whose id is the file name")
        for entry in entries:
            if not isinstance(entry_id := entry.get("id"), str) or not ID_PATTERN.fullmatch(entry_id):
                problems.append(f"{where}: id {entry_id!r} is not a lower-case slug")
                continue
            if entry_id in seen:
                problems.append(f"{where}: id {entry_id} is also in {seen[entry_id]}")
                continue
            seen[entry_id] = where
            _check_shape(entry_id, entry, problems)
            if entry_id.startswith(DERIVED_PREFIXES):
                if entry_id not in derived:
                    problems.append(f"{where}: {entry_id} extends no derived entry")
                    continue
                if changes[entry_id]["release"] != release:
                    problems.append(f"{where}: {entry_id} belongs to {changes[entry_id]['release']}")
            elif not entry.get("refs"):
                problems.append(f"{where}: entry {entry_id} has no refs")
            fields = {key: value for key, value in entry.items() if key != "id"}
            changes[entry_id] = changes.get(entry_id, {}) | fields | {"release": release}


def _table(entry: dict[str, Any], key: str) -> dict[str, Any]:
    """Return a table of an entry, or an empty one where the entry holds something else (a reported problem)."""
    return value if isinstance(value := entry.get(key), dict) else {}


def _check_entry(entry: dict[str, Any], problems: list[str]) -> None:
    where = f"entry {entry['id']}"
    problems.extend(f"{where}: missing {key}" for key in REQUIRED_KEYS if not entry.get(key))
    keep = _table(entry, "keep")
    if entry.get("action") == "keep" and not (keep.get("flags") or keep.get("note")):
        problems.append(f"{where}: action keep needs keep.flags or keep.note")
    if keep.get("flags") and entry.get("action") != "keep":
        problems.append(f"{where}: keep.flags belong to an entry with action keep")
    if entry.get("action") == "required" and not entry.get("migrate"):
        problems.append(f"{where}: action required needs migrate")
    verify = _table(entry, "verify")
    if entry.get("source") == "run" and not (
        isinstance(verify.get("schema"), str) and isinstance(verify.get("args"), list)
    ):
        problems.append(f"{where}: source run needs verify.schema and verify.args")


def _check_links(changes: dict[str, dict[str, Any]], order: dict[str, int], problems: list[str]) -> None:
    for entry in changes.values():
        supersedes = entry.get("supersedes", [])
        targets = [
            *(supersedes if isinstance(supersedes, list) else []),
            *([entry["reverts"]] if "reverts" in entry else []),
        ]
        for target in targets:
            if target not in changes:
                problems.append(f"entry {entry['id']}: {target} is not an entry")
            elif order[changes[target]["release"]] > order[entry["release"]]:
                problems.append(f"entry {entry['id']}: {target} comes after it")


def keep_config(flags: list[str]) -> dict[str, Any]:
    """Return the pyproject.toml values the command-line flags set, keyed as pyproject.toml spells them.

    Raises ValueError with the parser's message when the flags are not valid options of this source tree.
    """
    from datamodel_code_generator.__main__ import (  # ruff: ignore[import-outside-top-level]
        generate_pyproject_config,
    )
    from datamodel_code_generator.arguments import arg_parser  # ruff: ignore[import-outside-top-level]

    stderr = io.StringIO()
    try:
        with contextlib.redirect_stderr(stderr):
            namespace = arg_parser.parse_args(flags)
    except SystemExit:
        raise ValueError(stderr.getvalue().strip().splitlines()[-1].partition("error: ")[2]) from None
    return tomllib.loads(generate_pyproject_config(namespace))["tool"]["datamodel-codegen"]


def _steps_after(changes: list[dict[str, Any]], index: int) -> list[dict[str, Any]]:
    """Return the entries a user of the release at `index` meets on the way to the latest release.

    An entry another entry on the path supersedes is left out, and so is a pair of an entry and the one that reverts it.
    Unreleased entries are not on the path.
    """
    path = [entry for entry in changes if index < entry["index"] and entry["release"] != UNRELEASED]
    ids = {entry["id"] for entry in path}
    dropped = {old for entry in path for old in entry.get("supersedes", []) if old in ids}
    dropped |= {
        entry_id for entry in path if (undone := entry.get("reverts")) in ids for entry_id in (undone, entry["id"])
    }
    return [entry for entry in path if entry["id"] not in dropped]


def _ranges(releases: list[dict[str, str]], changes: list[dict[str, Any]], problems: list[str]) -> list[Range]:
    """Group consecutive source releases whose steps that need an action are the same."""
    ranges: list[Range] = []
    for index, release in enumerate(releases[:-1]):
        path = _steps_after(changes, index)
        steps = tuple(entry["id"] for entry in path if entry["action"] != "none")
        if ranges and ranges[-1].steps == steps:
            ranges[-1].sources.append(release["version"])
            continue
        ranges.append(Range([release["version"]], steps, path))
    configs: dict[str, dict[str, Any]] = {}
    for group in ranges:
        unconditional: dict[str, tuple[str, Any]] = {}
        for entry in group.path:
            if entry["action"] != "keep" or not (flags := entry.get("keep", {}).get("flags")):
                continue
            if (only := entry.get("affects", {}).get("options")) is not None:
                group.keep_conditional.setdefault(", ".join(only), []).extend(flags)
                continue
            group.keep_flags += flags
            if entry["id"] not in configs:
                try:
                    configs[entry["id"]] = keep_config(flags)
                except ValueError as error:
                    problems.append(f"entry {entry['id']}: keep.flags {' '.join(flags)!r}: {error}")
                    configs[entry["id"]] = {}
            for key, value in configs[entry["id"]].items():
                if key in unconditional and unconditional[key][1] != value:
                    problems.append(
                        f"range from {group.first}: {entry['id']} and {unconditional[key][0]} set {key} differently"
                    )
                unconditional.setdefault(key, (entry["id"], value))
                group.keep_pyproject[key] = unconditional[key][1]
    return ranges


def load(layout: Layout | None = None, registries: Registries | None = None) -> Guide:
    """Load, derive and check the change list; raise MigrationDataError with every problem found."""
    layout = layout or Layout()
    registries = registries or current_registries()
    problems: list[str] = []
    releases = _load_releases(layout, problems)
    placed = _Releases(releases, problems)
    presets = {
        str(date): str(version) for date, version in _read_toml(layout.derived, problems).get("presets", {}).items()
    }
    changes = _derived_changes(registries, presets, placed, problems)
    _hand_changes(layout, changes, placed, problems)
    order = {version: index for index, version in enumerate(placed.versions)} | {UNRELEASED: len(placed.versions)}
    for entry_id, entry in changes.items():
        entry["id"] = entry_id
        entry["anchor"] = _anchor(entry_id)
        entry["index"] = order[entry["release"]]
        entry["affects"] = {key: values for key, values in _table(entry, "affects").items() if values}
        _check_entry(entry, problems)
    _check_links(changes, order, problems)
    action_order = {action: index for index, action in enumerate(ACTIONS)}
    ordered = sorted(
        changes.values(),
        key=lambda entry: (entry["index"], action_order.get(entry.get("action"), len(ACTIONS)), entry["id"]),
    )
    ranges = _ranges(releases, ordered, problems) if releases and not problems else []
    if problems:
        raise MigrationDataError(problems)
    return Guide(releases, ordered, ranges)


def _affects_line(entry: dict[str, Any]) -> str | None:
    parts = [f"{AFFECTS[name]}: {', '.join(map(_code, values))}" for name, values in entry["affects"].items()]
    return "; ".join(parts) or None


def _refs(entry: dict[str, Any]) -> str:
    return ", ".join(f"[{ref}]({REPO_URL}/issues/{ref[1:]})" for ref in entry.get("refs", []))


def _details_link(entry: dict[str, Any], base: str) -> str:
    return f"[details]({base}#{entry['anchor']})"


def entry_markdown(entry: dict[str, Any], level: int = 3) -> list[str]:
    """Return one entry in full: heading with its release and anchor, summary, details and the before/after lines."""
    release = "unreleased" if entry["release"] == UNRELEASED else entry["release"]
    lines = [f"{'#' * level} {entry['title']} ({release}) {{ #{entry['anchor']} }}", "", entry["summary"], ""]
    if affects := _affects_line(entry):
        lines.append(f"- **Affects:** {affects}")
    keep = entry.get("keep", {})
    if keep.get("flags"):
        lines.append(f"- **Keep the old output:** {_code(' '.join(keep['flags']))}")
    if keep.get("note"):
        lines.append(f"- **Keep the old output:** {keep['note']}")
    if entry.get("migrate"):
        lines.append(f"- **What to change:** {entry['migrate']}")
    if refs := _refs(entry):
        lines.append(f"- **Pull requests and issues:** {refs}")
    lines += [f"- **Source:** {SOURCES[entry['source']]}", ""]
    if entry.get("before") or entry.get("after"):
        lines += ["```diff", *(f"-{line}" for line in entry.get("before", "").splitlines())]
        lines += [*(f"+{line}" for line in entry.get("after", "").splitlines()), "```", ""]
    return lines


def _toml_line(name: str, value: object) -> str:
    return f"{name} = {str(value).lower() if isinstance(value, bool) else json.dumps(value, ensure_ascii=False)}"


def _keep_block(group: Range, latest: str) -> list[str]:
    notes = [
        f"- {entry['title']}: {entry['keep']['note']}"
        for entry in group.path
        if entry["action"] == "keep" and not entry.get("keep", {}).get("flags") and entry.get("keep", {}).get("note")
    ]
    notes = ["Outside the command line:", "", *notes, ""] if notes else []
    if not group.keep_flags and not group.keep_conditional:
        return notes or ["No option is needed to keep your output; check the changes below.", ""]
    lines = []
    if group.keep_flags:
        lines += [
            (
                f"Add these options to keep the output of your release where {latest} can (every option exists in "
                f"{latest}):"
            ),
            "",
            "```bash",
            "datamodel-codegen ... " + " ".join(group.keep_flags),
            "```",
            "",
            "or in `pyproject.toml`:",
            "",
            "```toml",
            "[tool.datamodel-codegen]",
            *starmap(_toml_line, group.keep_pyproject.items()),
            "```",
            "",
        ]
    for only, flags in group.keep_conditional.items():
        lines += [f"Only if you pass {_code(only)}, also add {_code(' '.join(flags))}.", ""]
    return lines + notes


def _short_line(entry: dict[str, Any], base: str) -> str:
    release = "unreleased" if entry["release"] == UNRELEASED else entry["release"]
    line = f"- {entry['title']} ({release})"
    if entry["action"] == "warn":
        if entry.get("migrate"):
            line += f": {entry['migrate']}"
        if only := [value for values in entry["affects"].values() for value in values]:
            line += f" Only if you use {', '.join(map(_code, only))}."
    return f"{line} {_details_link(entry, base)}"


def guide_page(title: str, intro: str, group: Range, latest: str, base: str) -> str:
    """Return the steps of one range or release: the keep options, then the entries by action.

    `base` is where the entries' details are: the all-changes page, relative or as a URL.
    """
    path = group.path
    counts = {action: sum(entry["action"] == action for entry in path) for action in ACTIONS}
    lines = [
        f"# {title}",
        "",
        GENERATED,
        "",
        (
            f"{intro} On the way to {latest}: {counts['required']} required changes, {counts['keep']} output changes "
            f"an option keeps, {counts['review']} changes no option keeps, {counts['warn']} new warnings, "
            f"{counts['none']} changes that need nothing. Each item names the release that made it. "
            f"[All changes]({base}) · [Machine-readable list]({SITE_URL}/data/migration.json)"
        ),
        "",
        "## Keep your current output",
        "",
        *_keep_block(group, latest),
    ]
    for action, heading in ACTIONS.items():
        if not (entries := [entry for entry in path if entry["action"] == action]):
            continue
        lines += [f"## {heading}", ""]
        if action in {"none", "warn"}:
            lines += [*(_short_line(entry, base) for entry in entries), ""]
            continue
        for entry in entries:
            lines += entry_markdown(entry)
    return "\n".join(lines).rstrip() + "\n"


def range_page(guide: Guide, group: Range) -> str:
    """Return the page of one range of source releases."""
    intro = f"For datamodel-code-generator {group.span} ({len(group.sources)} releases)."
    if len(group.sources) == 1:
        intro = f"For datamodel-code-generator {group.first}."
    title = f"Upgrading from {group.span} to {guide.latest}"
    return guide_page(title, intro, group, guide.latest, CHANGES_PAGE)


def raw_page(guide: Guide, version: str) -> str:
    """Return the self-contained Markdown of the steps from one exact release, for coding agents."""
    versions = [release["version"] for release in guide.releases]
    if version == guide.latest:
        return f"# datamodel-code-generator {version}\n\n{version} is the latest release: nothing to change.\n"
    group = next(group for group in guide.ranges if version in group.sources)
    exact = replace(group, sources=[version], path=_steps_after(guide.changes, versions.index(version)))
    intro = (
        f"For datamodel-code-generator {version}; the [upgrade guide]({SITE_URL}/migration/) has the other releases."
    )
    title = f"Upgrading from {version} to {guide.latest}"
    return guide_page(title, intro, exact, guide.latest, f"{SITE_URL}/migration/changes/")


def hub_page(guide: Guide) -> str:
    """Return the hub: how to read the guide, the release selector and the table of ranges."""
    floor = guide.releases[0]["version"]
    lines = [
        f"# Upgrading to {guide.latest}",
        "",
        GENERATED,
        "",
        (
            "Pick the release you use now. Its page lists, for that release only, the options that keep your current "
            f"output in {guide.latest}, the changes you must make and the changes no option keeps. Coding agents can "
            f"read the same steps as Markdown: `{SITE_URL}/migration/from/<release>.md`, for example "
            f"`{SITE_URL}/migration/from/{floor}.md`."
        ),
        "",
        '<div class="dcg-migration" data-migration-select hidden>',
        '<label for="dcg-migration-from">I use datamodel-code-generator</label>',
        '<select id="dcg-migration-from">',
        '<option value="">choose a release</option>',
        *(
            f'<option value="{group.page.removesuffix(".md")}/">{source}</option>'
            for group in reversed(guide.ranges)
            for source in reversed(group.sources)
        ),
        "</select>",
        "</div>",
        "",
        "| Your release | Required | Kept by an option | Not kept | New warnings | Page |",
        "|---|---|---|---|---|---|",
    ]
    for group in reversed(guide.ranges):
        counts = {action: sum(entry["action"] == action for entry in group.path) for action in ACTIONS}
        lines.append(
            f"| {group.span} | {counts['required']} | {counts['keep']} | {counts['review']} | {counts['warn']} "
            f"| [{group.page.removesuffix('.md')}]({group.page}) |"
        )
    lines += [
        "",
        (
            f"Releases before {floor}: start from the {floor} page and read the older entries of the "
            f"[changelog]({REPO_URL}/blob/main/CHANGELOG.md)."
        ),
        "",
        "## How to upgrade without surprises",
        "",
        "1. Add the options of your page; they keep the output where the new release can.",
        "2. Regenerate and compare: `datamodel-codegen ... --check` fails on any difference.",
        "3. Make the required changes and review the changes no option keeps.",
        "4. Later, drop one keep option at a time, or move to the newest dated preset.",
        "",
        f"[All changes by release]({CHANGES_PAGE}) lists every entry with its details, newest first.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def changes_page(guide: Guide, layout: Layout) -> str:
    """Return every entry by release, newest first."""
    dates = {release["version"]: release["date"] for release in guide.releases}
    lines = [
        "# All Changes by Release",
        "",
        GENERATED,
        "",
        (
            "Every change a user meets when upgrading, newest first. To upgrade from a release, apply every section "
            f"above it, or open [the page for your release]({HUB_PAGE})."
        ),
        "",
    ]
    for release in [UNRELEASED, *reversed(dates)]:
        entries = guide.entries_of(release)
        statistics = layout.output_changes / f"{release}.md"
        if not entries and not statistics.exists():
            continue
        lines += [f"## {'Unreleased' if release == UNRELEASED else f'{release} ({dates[release]})'}", ""]
        if statistics.exists():
            lines += [
                f"[Output changes in {release}](../output-changes/{release}.md) compares the generated models.",
                "",
            ]
        for entry in entries:
            lines += entry_markdown(entry)
    return "\n".join(lines).rstrip() + "\n"


def to_json(guide: Guide) -> str:
    """Return the releases, entries and ranges for tools."""
    data = {
        "schema_version": SCHEMA_VERSION,
        "latest": guide.latest,
        "raw_page": f"{SITE_URL}/migration/from/{{release}}.md",
        "releases": guide.releases,
        "changes": [
            {name: entry[name] for name in JSON_KEYS if entry.get(name) not in (None, {}, [])}
            for entry in guide.changes
        ],
        "ranges": [
            {
                "from": group.first,
                "through": group.last,
                "sources": group.sources,
                "page": f"{SITE_URL}/migration/{group.page.removesuffix('.md')}/",
                "changes": [entry["id"] for entry in group.path],
                "keep_flags": group.keep_flags,
                "keep_pyproject": group.keep_pyproject,
                "keep_conditional": group.keep_conditional,
            }
            for group in guide.ranges
        ],
    }
    return json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def _release_note_item(entry: dict[str, Any]) -> str:
    refs = f" ({', '.join(entry['refs'])})" if entry.get("refs") else ""
    if entry["action"] not in BREAKING_ACTIONS:
        return f"* {entry['note']}" if "note" in entry else f"* {entry['title']} - {entry['summary']}{refs}"
    keep = entry.get("keep", {})
    tail = f" Keep the old output with {_code(' '.join(keep['flags']))}." if keep.get("flags") else ""
    tail += "".join(f" {text}" for text in (keep.get("note"), entry.get("migrate")) if text)
    return f"* {entry['title']} - {entry['summary']}{tail}{refs}"


def _release_note_section(entry: dict[str, Any]) -> str:
    if entry["action"] in BREAKING_ACTIONS:
        return "Breaking Changes"
    if entry["action"] == "warn":
        return "Deprecations"
    match entry["kind"]:
        case "warning":
            return "Scheduled Breaking Changes"
        case "preset":
            return "New Dated Presets"
    return "Experimental Features" if entry["id"].startswith("experimental:") else "Changes That Need No Action"


def release_notes(guide: Guide, release: str) -> str:
    """Return the release-note sections of one release, each item from its entry."""
    sections: dict[str, list[str]] = {}
    categories: dict[str, list[str]] = {}
    for entry in guide.entries_of(release):
        section = _release_note_section(entry)
        sections.setdefault(section, []).append(_release_note_item(entry))
        if section == "Breaking Changes":
            categories.setdefault(KINDS[entry["kind"]], []).append(_release_note_item(entry))
    lines: list[str] = []
    if categories:
        lines += ["## Breaking Changes", ""]
        for category in CATEGORIES:
            if category in categories:
                lines += [f"### {category}", *categories[category], ""]
    for section in RELEASE_NOTE_SECTIONS:
        if section in sections:
            lines += [f"## {section}", "", *sections[section], ""]
    return "\n".join(lines).rstrip() + "\n" if lines else ""


def has_breaking(guide: Guide, release: str) -> bool:
    """Return whether a release has a change that needs an action or changes output."""
    return any(entry["action"] in BREAKING_ACTIONS for entry in guide.entries_of(release))


def committed_files(guide: Guide, layout: Layout) -> dict[Path, str]:
    """Return the committed generated files and their text."""
    return {
        layout.docs / HUB_PAGE: hub_page(guide),
        layout.docs / CHANGES_PAGE: changes_page(guide, layout),
        layout.json: to_json(guide),
    }


def _write(files: dict[Path, str]) -> None:
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def _preset_dates_of(tree: Path) -> set[str]:
    return set(PRESET_DATE_PATTERN.findall((tree / TAG_PRESET_NAMES).read_text(encoding="utf-8")))


def stamp(layout: Layout, version: str, tag_tree: Path, date: str, registries: Registries | None = None) -> list[str]:
    """Record a published release: move the fragments its tag contains, add its row and its new preset dates.

    Returns the ids of the moved fragments. Fragments the tag does not contain were merged after it and stay unreleased.
    """
    guide = load(layout, registries)
    if version_key(version) <= version_key(guide.latest):
        msg = f"{version} does not come after the latest release {guide.latest}"
        raise MigrationDataError([msg])
    tagged = tag_tree / TAG_FRAGMENTS
    moved = [path for path in sorted(layout.unreleased.glob("*.toml")) if (tagged / path.name).exists()]
    if moved:
        target = layout.changes / f"{version}.toml"
        layout.changes.mkdir(parents=True, exist_ok=True)
        texts = [path.read_text(encoding="utf-8").strip() + "\n" for path in moved]
        target.write_text(CHANGES_HEADER.format(version=version) + "\n" + "\n".join(texts), encoding="utf-8")
        for path in moved:
            path.unlink()
    with layout.releases.open("a", encoding="utf-8") as releases:
        releases.write(f'\n[[release]]\nversion = "{version}"\ndate = "{date}"\n')
    presets = tomllib.loads(layout.derived.read_text(encoding="utf-8")).get("presets", {})
    presets |= {preset_date: version for preset_date in _preset_dates_of(tag_tree) if preset_date not in presets}
    rows = "".join(f'"{preset_date}" = "{presets[preset_date]}"\n' for preset_date in sorted(presets))
    layout.derived.write_text(f"{DERIVED_HEADER}\n[presets]\n{rows}", encoding="utf-8")
    _write(committed_files(load(layout, registries), layout))
    return [path.stem for path in moved]


def check(guide: Guide, layout: Layout) -> list[str]:
    """Return the committed generated files that are missing or out of date."""
    return sorted(
        path.name
        for path, text in committed_files(guide, layout).items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    )


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="build_migration_docs.py", description="Build the upgrade guide from the declarative change list"
    )
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="fail when the data is invalid or a page is stale")
    action.add_argument("--release-notes", metavar="RELEASE", help="print the release-note sections of a release")
    action.add_argument("--has-breaking", metavar="RELEASE", help="exit 0 when a release has a breaking change")
    action.add_argument("--stamp", metavar="VERSION", help="record a published release (needs --tag-tree)")
    action.add_argument("--range-pages", type=Path, metavar="DIR", help="write the page of each range into DIR")
    action.add_argument("--raw-site", type=Path, metavar="SITE", help="write SITE/migration/from/<release>.md")
    parser.add_argument("--tag-tree", type=Path, help="a checkout of the release tag, for --stamp")
    parser.add_argument("--date", help="the release date for --stamp (default: today, UTC)")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    parser.add_argument("--docs-dir", type=Path, default=DOCS_DIR)
    parser.add_argument("--json", type=Path, default=JSON_PATH)
    ns = parser.parse_args(argv)
    if ns.stamp and ns.tag_tree is None:
        parser.error("--stamp needs --tag-tree")
    return ns


def run(ns: argparse.Namespace, registries: Registries | None = None) -> int:
    """Run the command the arguments name."""
    layout = Layout(ns.data_dir, ns.docs_dir, ns.json)
    if ns.stamp:
        date = ns.date or datetime.now(UTC).date().isoformat()
        moved = stamp(layout, ns.stamp, ns.tag_tree, date, registries)
        print(f"stamped {ns.stamp}: {', '.join(moved) or 'no fragments'}")
        return 0
    guide = load(layout, registries)
    if ns.has_breaking:
        return 0 if has_breaking(guide, ns.has_breaking) else 1
    if ns.check:
        if stale := check(guide, layout):
            print(f"Migration pages are out of date: {', '.join(stale)}", file=sys.stderr)
            print("Run 'python scripts/build_migration_docs.py' to update.", file=sys.stderr)
        return 1 if stale else 0
    if ns.release_notes:
        print(release_notes(guide, ns.release_notes), end="")
    elif ns.range_pages:
        _write({ns.range_pages / group.page: range_page(guide, group) for group in guide.ranges})
    elif ns.raw_site:
        pages = ns.raw_site / "migration" / "from"
        _write({pages / f"{release['version']}.md": raw_page(guide, release["version"]) for release in guide.releases})
    else:
        _write(committed_files(guide, layout))
    return 0


def main(argv: list[str] | None = None, registries: Registries | None = None) -> int:
    """Script entrypoint."""
    ns = _parse_args(argv)
    try:
        return run(ns, registries)
    except MigrationDataError as error:
        print("Invalid migration data:", file=sys.stderr)
        print("\n".join(f"- {problem}" for problem in error.problems), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
