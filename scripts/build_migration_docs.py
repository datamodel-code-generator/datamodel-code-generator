@dataclass
class Range:
    """Consecutive source releases whose users meet the same steps on the way to the latest release."""

    sources: list[str]
    steps: tuple[str, ...]
    path: list[dict[str, Any]]
    keep_flags: list[str] = field(default_factory=list)
    keep_pyproject: dict[str, Any] = field(default_factory=dict)
    keep_conditional: dict[str, list[str]] = field(default_factory=dict)

    @property
    def first(self) -> str:
        """Return the oldest source release."""
        return self.sources[0]

    @property
    def last(self) -> str:
        """Return the newest source release."""
        return self.sources[-1]

    @property
    def span(self) -> str:
        """Return the releases as a heading names them."""
        return self.first if self.first == self.last else f"{self.first} through {self.last}"

    @property
    def page(self) -> str:
        """Return the file name of the range page."""
        return f"from-{self.first}.md"


@dataclass
class Guide:
    """The loaded change list: releases oldest first, entries in release order, and the ranges."""

    releases: list[dict[str, str]]
    changes: list[dict[str, Any]]
    ranges: list[Range]

    @property
    def latest(self) -> str:
        """Return the latest published release."""
        return self.releases[-1]["version"]

    def entries_of(self, release: str) -> list[dict[str, Any]]:
        """Return the entries of one release (`unreleased` for the next one)."""
        return [entry for entry in self.changes if entry["release"] == release]


