"""Draw compositions of the shape families and hold their models to the validator and to the last release.

Usage (from the repository root):
  python -m scripts.shape_families_random [BASE] [--budget SECONDS] [--seed N] [--database DIR] [--json OUT]
      [--base-python PYTHON] [--cache-dir DIR] [--examples N] [--out DIR]

BASE is a released version (default: the latest tag, as `git describe --tags --abbrev=0` names it) or a git revision of
this repository; `compare_release.resolve_base` installs or extracts it (`--base-python`: an interpreter that has the
base installed). The candidate is this checkout.

An example is a composition of the shape families (`tests/main/shape_families/compose.py`: a family's shape placed
inside another's, two or three levels deep), one backend every level's family is generated for, and one contract of
the family verdict (`verdict.CONTRACTS`: the default output and the newest dated preset). A composition for which the
payload suite finds no seed (a payload the validator accepts, `value_neighbours`) is left out: it is a contradiction
no author writes, or too intricate for the seed, and the run counts it. An example is
a finding of one of these kinds:

- `generation-fails`: the candidate does not generate it;
- a kind of `verdict.KINDS`: its model differs from the validator (`verdict.judge`, the families' verdict);
- `base-fails`: BASE does not generate it and the candidate does (a crash fixed since BASE);
- `moved`: the candidate and BASE both generate it and their models decide a payload of the pool differently (the
  model's verdict in lax mode and in strict mode over the payload's JSON text), or one module imports and the other
  does not. Both are generated by `compare_release`'s warm workers with the same arguments; equal trees (paths and
  version lines normalised) decide alike without being judged.

BASE generates only the contracts whose options it has (`behaviour_diff.opt_in_reason`): a dated preset newer than
BASE is judged against the validator only. A finding is known when a rule covers it (`compose.covering`): a rule of
`shape_families/kept.py` that covers one level's own part, or a rule over the composition's parameters
(`compose.COMPOSED`); the default output's differences are frozen and the newest preset's are its to-do list, as for
the families themselves. Every other finding fails the run.

Hypothesis draws `ROUND` examples per round, round `n` with the seed `SEED + n`, until the budget is spent or
`--examples` examples were judged. A round that meets a new finding shrinks it (towards fewer levels and the first
value of each dimension) and prints the smallest composition with its witness, schema and command; the round's later
examples and its shrinking only count findings of that kind and family chain, and each kind and family chain is
reported once a run. `--database` keeps the failing examples, so the next run replays them first. Exit 1 on a finding.
"""

