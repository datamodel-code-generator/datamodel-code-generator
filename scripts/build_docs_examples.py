PYTHON_GENERATED_HEADER_PATTERN = re.compile(
    r"\A# generated by datamodel-codegen:\n"
    r"#   filename:  .+\n"
    r"(?:#   timestamp:\s+.+(?:\n|$))?"
    r"\n?",
)


@dataclass(frozen=True, slots=True)
class DocsExample:
    """One generated docs example section."""

    example_id: str
    path: Path
    render: Callable[[], str]


@dataclass(frozen=True, slots=True)
class MarkdownCodeBlock:
    """One labeled code block in a generated Markdown example."""

    label: str
    language: str
    path: Path | None = None
    content: str | None = None
    strip_python_header: bool = False


def read_text(path: Path) -> str:
    """Read a UTF-8 fixture file."""
    return path.read_text(encoding="utf-8").rstrip()


def read_python_output(path: Path) -> str:
    """Read generated Python output without volatile generated-file headers."""
    return PYTHON_GENERATED_HEADER_PATTERN.sub("", read_text(path), count=1)


def fenced(language: str, content: str) -> str:
    """Render a fixture verbatim, including its original formatting."""
    return f"\n<!-- fmt: off -->\n\n```{language}\n{content.rstrip()}\n```\n\n<!-- fmt: on -->\n"


def details(summary: str, language: str, content: str) -> str:
    """Render a collapsible Markdown details block containing a code fence."""
    return f"\n<details>\n<summary>{summary}</summary>\n{fenced(language, content)}</details>\n"


def render_file_example(*, language: str, path: Path, strip_python_header: bool = False) -> str:
    """Render one fixture file as a Markdown code block."""
    content = read_python_output(path) if strip_python_header else read_text(path)
    return fenced(language, content)


def read_code_block(block: MarkdownCodeBlock) -> str:
    """Read content for a Markdown code block."""
    if block.content is not None:
        return block.content.rstrip()
    if block.path is None:  # pragma: no cover - registry construction should prevent this
        msg = f"{block.label} requires either content or path"
        raise ValueError(msg)
    if block.strip_python_header:
        return read_python_output(block.path)
    return read_text(block.path)


def render_labeled_code_block(block: MarkdownCodeBlock) -> str:
    """Render one labeled Markdown code block."""
    return f"**{block.label}:**{fenced(block.language, read_code_block(block))}"


def indent_markdown(content: str, *, prefix: str = "    ") -> str:
    """Indent Markdown content for an admonition body."""
    return "\n".join(f"{prefix}{line}" if line else "" for line in content.splitlines())


def render_cli_example(*blocks: MarkdownCodeBlock) -> str:
    """Render a MkDocs example block from labeled code examples."""
    if not blocks:
        return ""
    body = "\n\n".join(render_labeled_code_block(block).strip() for block in blocks)
    return f'\n??? example "Examples"\n\n{indent_markdown(body)}\n'


def blocks(path: Path, *needles: str, limit: int | None = None, separator: str = "\n\n") -> str:
    """Return the separated blocks of a generated module that contain any of the needles, in file order.

    Methods of a class are separated by one blank line, and top-level definitions by two.
    """
    found = [block for block in read_python_output(path).split(separator) if any(needle in block for needle in needles)]
    return separator.join(found[:limit])


def report_lines(path: Path, *prefixes: str) -> str:
    """Return the lines of a test report's first section that start with any of the prefixes, with their details."""
    selected: list[str] = []
    depth: int | None = None
    for line in read_text(path).split("\n# ", 1)[0].splitlines():
        indent = len(line) - len(line.lstrip())
        if line.lstrip().startswith(prefixes):
            depth = indent
        elif depth is None or indent <= depth:
            depth = None
            continue
        selected.append(line[2:])
    return "\n".join(selected)


def yaml_helpers(path: Path, *names: str) -> str:
    """Return a helper file's lines before its helpers, then the definitions of the named helpers in file order."""
    head, _, body = read_text(path).partition("helpers:\n")
    definitions = re.split(r"\n(?=  \S)", body)
    kept = [block for block in definitions if block.split(":", 1)[0].strip() in names]
    return f"{head}helpers:\n" + "\n".join(kept)


def directory_files(path: Path) -> list[Path]:
    """Return stable file entries for generated directory examples."""
    return sorted(file for file in path.iterdir() if file.is_file())


def directory_tree(path: Path, *, root_name: str) -> str:
    """Render a stable text tree for generated directory examples."""
    lines = [f"{root_name}/"]
    files = directory_files(path)
    for index, file in enumerate(files):
        branch = "`--" if index == len(files) - 1 else "|--"
        lines.append(f"{branch} {file.name}")
    return "\n".join(lines)


def render_reuse_scope_tree_example() -> str:
    """Render tested reuse-scope tree output with representative files."""
    output_path = EXPECTED_MAIN / "jsonschema" / "reuse_scope_tree"
    lines = [
        "",
        "**Output with `--reuse-scope tree`:**",
        fenced("text", directory_tree(output_path, root_name="models")),
    ]
    for file in directory_files(output_path):
        content = read_python_output(file)
        lines.extend((
            f"**models/{file.name}:**",
            fenced("python", content) if content.strip() else "_No code beyond the generated header._\n",
        ))
    return "\n".join(lines)


def _file_example(
    example_id: str,
    doc: str,
    *,
    language: str,
    path: Path,
    strip_python_header: bool = False,
) -> DocsExample:
    """Build a docs example from one fixture file."""
    return DocsExample(
        example_id=example_id,
        path=DOCS / doc,
        render=lambda: render_file_example(
            language=language,
            path=path,
            strip_python_header=strip_python_header,
        ),
    )


