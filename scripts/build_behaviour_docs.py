"""Build the output-change pages from the committed behaviour summaries.

Usage:
    python scripts/build_behaviour_docs.py
    python scripts/build_behaviour_docs.py --check

docs/data/output-changes/<version>.json (written by `scripts/behaviour_diff.py guide`) becomes
docs/output-changes/<version>.md, and docs/data/output-changes/upgrading.json (written by
`scripts/behaviour_diff.py query all <version> --json ...`) becomes docs/output-changes/upgrading.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "docs" / "data" / "output-changes"
DOCS_DIR = ROOT / "docs" / "output-changes"
UPGRADING = "upgrading"
GATE_CLASSES = {
    "same": "identical output",
    "no-behaviour": "the output differs, the models behave the same (formatting, import order, redundant lines)",
    "crash-fix": "the previous release failed to generate, import or validate; the new one works",
    "accepted": "a behaviour change in default output that was decided and announced",
    "violation": "an unannounced behaviour change (a release is not published with one)",
    "both-fail": "both releases fail on the input",
    "opt-in": "the generation uses an option or option value the previous release does not have",
}
QUERY_CLASSES = {
    "same": "identical output",
    "no-behaviour": "the output differs, the models behave the same",
    "crash-fix": "the older release failed to generate, import or validate; the newer one works",
    "behaviour-change": "the models behave differently (types, constraints, names, defaults, validation results)",
    "now-fails": "the older release worked; the newer one fails on the input",
    "both-fail": "both releases fail on the input",
    "unsupported": "one of the releases does not have the output model type or an option the generation uses",
}
KIND_LABELS = {
    "default": "default options",
    "preset": "released presets",
    "cli-doc": "documented CLI examples",
    "payload": "payload validation cases",
}
GENERATED = "<!-- Generated by scripts/build_behaviour_docs.py. Do not edit manually. -->"


def _code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"`` {text} ``"


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    return [
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---" for _ in header) + "|",
        *("| " + " | ".join(_cell(value) for value in row) + " |" for row in rows),
        "",
    ]


def _class_list(classes: dict[str, str], used: list[str]) -> list[str]:
    return [*(f"- **{name}**: {classes[name]}" for name in used if name in classes), ""]


def _example_line(example: dict[str, Any]) -> str:
    options = "" if example["options"] == "default" else f", {_code(example['options'])}"
    return f"- {_code(example['input'])} ({example['type']}{options}): {_code(example['detail'])}"


def _diff_block(diff: str) -> list[str]:
    return ["```diff", *diff.splitlines(), "```", ""]


def render_release(data: dict[str, Any]) -> str:
    """Return the page of one release from its summary."""
    version, previous = data["version"], data["previous"]
    classes = data["classes"]
    rows = [[backend, *(data["counts"][backend].get(cls, 0) for cls in classes)] for backend in data["types"]]
    totals = [sum(row[index + 1] for row in rows) for index in range(len(classes))]
    tier = data.get("tier", "release")
    coverage = (
        "every test fixture and payload validation case of the repository with each output model type, with default "
        f"options, with the released presets and with the documented CLI examples (tier `{tier}`)."
        if tier != "pr"
        else "the test fixtures the change touches and a fixed sample of the others with the output model types of "
        "the pull request tier, with default options (tier `pr`)."
    )
    lines = [
        f"# Output changes in {version}",
        "",
        GENERATED,
        "",
        (
            f"How the models {version} generates differ in behaviour from the models {previous} generates. Both "
            f"releases generated {coverage} Each "
            "generation (one input, output model type and option set) whose output differs was imported and compared "
            "by behaviour: public names, model kinds and bases, configuration, field types, constraints, aliases, "
            "defaults, required flags, enum members, constructor order, and the validation result of sample payloads."
        ),
        "",
        "## Summary",
        "",
        *_table(["Output model type", *classes], [*rows, ["Total", *totals]]),
        "Generations per kind: "
        + ", ".join(f"{KIND_LABELS.get(kind, kind)} {count}" for kind, count in data["kinds"].items())
        + ".",
        "",
        *_class_list(GATE_CLASSES, classes),
    ]
    if data["crash_fixes"]:
        lines += [
            "## Fixed crashes",
            "",
            f"Generations that failed with {previous} and work with {version}, by the error {previous} raised.",
            "",
            *_table(
                ["Stage", "Error", "Generations", "Inputs", "Output model types"],
                [
                    [group["stage"], group["error"], group["cells"], group["inputs"], ", ".join(group["types"])]
                    for group in data["crash_fixes"]
                ],
            ),
        ]
        for group in data["crash_fixes"]:
            lines += [f"{group['stage'].capitalize()}, {group['error']}:", ""]
            lines += [*map(_example_line, group["examples"]), ""]
    if data["accepted"]:
        lines += ["## Behaviour changes in default output", ""]
        for group in data["accepted"]:
            keep = ", ".join(map(_code, group.get("restored_by", [])))
            lines += [
                f"### {group['release_note'] or group['reason']}",
                "",
                f"- Decision: {group['decision']}",
                f"- Why: {group['reason']}",
                (
                    f"- Affected: {group['cells']} generations of {len(group['inputs'])} inputs; "
                    f"{', '.join(group['types'])}; option sets: {', '.join(map(_code, group['option_sets']))}"
                ),
                f"- Changed aspects: {', '.join(group['aspects'])}",
                f"- How to keep the old output: {keep or 'no option restores it'}",
                "",
            ]
            if example := group.get("example"):
                options = "" if example["options"] == "default" else f", {_code(example['options'])}"
                lines += [f"{_code(example['input'])} ({example['type']}{options}):", ""]
                lines += _diff_block(example["diff"])
    if data["opt_in"]:
        lines += [
            "## New opt-in options",
            "",
            (
                f"Options and option values {previous} does not have. Default output does not change; each row "
                "shows where the option changes the output."
            ),
            "",
            *_table(
                ["Option", "Generations", "Inputs", "Output model types"],
                [
                    [_code(group["option"]), group["cells"], group["inputs"], ", ".join(group["types"])]
                    for group in data["opt_in"]
                ],
            ),
        ]
        for group in data["opt_in"]:
            if example := group.get("example"):
                lines += [
                    f"### {_code(group['option'])}",
                    "",
                    f"{_code(example['input'])} ({example['type']}), without and with {_code(example['options'])}:",
                    "",
                    *_diff_block(example["diff"]),
                ]
    if data["numbered_names"]:
        lines += ["## Numbered names that changed", "", *map(_example_line, data["numbered_names"]), ""]
    if data["violations"]:
        lines += ["## Unannounced behaviour changes", "", *map(_example_line, data["violations"]), ""]
    lines += [
        "## Upgrading across several releases",
        "",
        "[Upgrading from an older release](upgrading.md) compares the recorded older releases with the latest one.",
    ]
    return "\n".join(lines).rstrip() + "\n"


def render_comparison(comparison: dict[str, Any], level: int = 2) -> str:
    """Return one older-release comparison (`behaviour_diff.py query`) as markdown."""
    old, new = comparison["from"], comparison["to"]
    classes = [cls for cls in QUERY_CLASSES if cls in comparison["counts"]]
    by_type = comparison["by_type"]
    lines = [
        f"{'#' * level} From {old} to {new}",
        "",
        *_table(
            ["Output model type", *classes],
            [[backend, *(by_type[backend].get(cls, 0) for cls in classes)] for backend in comparison["types"]],
        ),
    ]
    changed = [cls for cls in classes if cls in {"crash-fix", "behaviour-change", "now-fails"}]
    if comparison["changed_in"]:
        lines += [
            (
                "Changed in (each recorded release counts the generations it changed since the recorded release "
                "before it, classified on that pair of releases alone, so a change that was made and later undone "
                "counts under both releases although the counts above compare only the two ends):"
            ),
            "",
            *_table(
                ["Release", *changed],
                [
                    [release, *(counts.get(cls, 0) for cls in changed)]
                    for release, counts in comparison["changed_in"].items()
                ],
            ),
        ]
    if comparison["aspects"]:
        ranked = sorted(comparison["aspects"].items(), key=lambda item: (-item[1], item[0]))
        aspects = ", ".join(f"{aspect} {count}" for aspect, count in ranked)
        lines += [f"Changed aspects: {aspects}.", ""]
    for cls, examples in comparison["examples"].items():
        lines += [f"Examples, {cls}:", ""]
        for example in examples:
            releases = ", ".join(example["changed_in"]) or "between the recorded releases"
            lines.append(f"- {_code(example['input'])} ({example['type']}), changed in {releases}")
            lines += [f"    - {_code(change)}" for change in example["changes"]]
        lines.append("")
    return "\n".join(lines).rstrip()


def render_upgrading(data: dict[str, Any]) -> str:
    """Return the page that compares every recorded older release with the latest one."""
    new = data["to"]
    rows = data["rows"]
    classes = [cls for cls in QUERY_CLASSES if any(cls in row["counts"] for row in rows)]
    lines = [
        "# Upgrading from an older release",
        "",
        GENERATED,
        "",
        f"How the models {new} generates differ in behaviour from the models each recorded older release "
        "generates, with default options, for every test fixture and payload validation case of the repository. "
        "Each older release ran in an environment with the package versions of its release day; the models were "
        "compared by behaviour as on the [release pages](" + f"{new}.md). Each change is attributed to the "
        "recorded releases that made it.",
        "",
        *_table(
            ["From", *classes],
            [[row["from"], *(row["counts"].get(cls, 0) for cls in classes)] for row in reversed(rows)],
        ),
        *_class_list(QUERY_CLASSES, classes),
    ]
    lines += [render_comparison(row) + "\n" for row in reversed(rows)]
    return "\n".join(lines).rstrip() + "\n"


def expected_pages(data_dir: Path = DATA_DIR) -> dict[str, str]:
    """Return every page the committed summaries produce, by file name."""
    pages = {}
    for path in sorted(data_dir.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        pages[f"{path.stem}.md"] = render_upgrading(data) if path.stem == UPGRADING else render_release(data)
    return pages


def build_docs(*, check: bool, data_dir: Path = DATA_DIR, docs_dir: Path = DOCS_DIR) -> int:
    """Write the pages, or report the ones that are out of date or have no summary."""
    pages = expected_pages(data_dir)
    existing = {path.name for path in docs_dir.glob("*.md")} if docs_dir.is_dir() else set()
    if check:
        stale = sorted(
            name
            for name in set(pages) | existing
            if name not in pages or name not in existing or (docs_dir / name).read_text(encoding="utf-8") != pages[name]
        )
        if stale:
            print(f"Output-change pages are out of date: {', '.join(stale)}", file=sys.stderr)
            print("Run 'python scripts/build_behaviour_docs.py' to update.", file=sys.stderr)
            return 1
        return 0
    docs_dir.mkdir(parents=True, exist_ok=True)
    for name in existing - set(pages):
        (docs_dir / name).unlink()
    for name, text in pages.items():
        (docs_dir / name).write_text(text, encoding="utf-8")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Script entrypoint."""
    parser = argparse.ArgumentParser(description="Build the output-change pages")
    parser.add_argument("--check", action="store_true", help="Check whether docs/output-changes is up to date")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR)
    parser.add_argument("--docs-dir", type=Path, default=DOCS_DIR)
    args = parser.parse_args(argv)
    return build_docs(check=args.check, data_dir=args.data_dir, docs_dir=args.docs_dir)


if __name__ == "__main__":
    raise SystemExit(main())
