"""Compile checked-in built-in Jinja templates into standalone renderers.

Jinja is used here as a lexer/parser only.  The resulting package has no Jinja
or MarkupSafe imports and is safe to use before the lazy Jinja import path.
"""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable

ROOT = Path(__file__).resolve().parents[1]
for import_path in (ROOT, ROOT / "src"):
    if str(import_path) not in sys.path:
        sys.path.insert(0, str(import_path))

from scripts._template_compiler import (  # noqa: E402
    build_environment,
    compile_template,
    inventory_templates,
    iter_template_paths,
)
from scripts._template_compiler.compiler import module_name_for_path  # noqa: E402

TEMPLATE_DIR = ROOT / "src/datamodel_code_generator/model/template"
OUTPUT_DIR = ROOT / "src/datamodel_code_generator/model/_compiled_templates"
FASTAPI_TEMPLATE_DIR = ROOT / "src/datamodel_code_generator/_fastapi/templates"
FASTAPI_OUTPUT_DIR = ROOT / "src/datamodel_code_generator/_fastapi/_compiled_templates"
_RESERVED_MODULE_NAMES = frozenset({"__init__", "registry"})
_PACKAGE_FILES = frozenset({"__init__.py", "registry.py"})


def _render_registry(template_paths: Iterable[Path]) -> str:
    entries = tuple(sorted(template_paths, key=lambda path: path.as_posix()))
    mapping = [f"    {path.as_posix()!r}: '.{module_name_for_path(path)}'," for path in entries]
    return (
        "\n".join([
            "# Generated by scripts/compile_builtin_templates.py; do not edit directly.",
            "from __future__ import annotations",
            "",
            "from collections.abc import Callable",
            "from functools import lru_cache",
            "from importlib import import_module",
            "from os import PathLike",
            "",
            "_RENDERER_MODULES: dict[str, str] = {",
            *mapping,
            "}",
            "",
            "",
            "@lru_cache",
            "def _load_renderer(module_name: str) -> Callable[..., str]:",
            "    return import_module(module_name, __package__).render",
            "",
            "",
            "def get_builtin_renderer(template_path: str | PathLike[str]) -> Callable[..., str] | None:",
            '    """Return a generated renderer for an exact built-in relative path."""',
            "    if (module_name := _RENDERER_MODULES.get(str(template_path).replace('\\\\', '/'))) is None:",
            "        return None",
            "    return _load_renderer(module_name)",
        ])
        + "\n"
    )


def _render_init(docstring: str, *, registry: bool) -> str:
    if not registry:
        return f'"""{docstring}"""\n'
    return "\n".join([
        f'"""{docstring}"""',
        "",
        "from .registry import get_builtin_renderer",
        "",
        '__all__ = ["get_builtin_renderer"]',
        "",
    ])


def template_sets() -> tuple[tuple[Path, Path, str, bool], ...]:
    """Return each template directory, its renderer directory, package docstring, and whether paths look up renderers.

    Model templates resolve by path because custom template directories overlay them; the FastAPI target imports its
    renderers directly until custom server templates exist.
    """
    return (
        (TEMPLATE_DIR, OUTPUT_DIR, "Generated standalone renderers for built-in model templates.", True),
        (
            FASTAPI_TEMPLATE_DIR,
            FASTAPI_OUTPUT_DIR,
            "Generated standalone renderers for built-in FastAPI templates.",
            False,
        ),
    )


def generated_sources() -> dict[Path, str]:
    """Generate and validate all standalone renderer source files of every template set in memory."""
    environment = build_environment()
    sources: dict[Path, str] = {}
    for template_dir, output_dir, docstring, registry in template_sets():
        inventory_templates(template_dir, environment)
        template_paths = tuple(path.relative_to(template_dir) for path in iter_template_paths(template_dir))
        _validate_module_names(template_paths)
        for path in template_paths:
            output_path = output_dir / f"{module_name_for_path(path)}.py"
            sources[output_path] = _format_python(compile_template(template_dir, path, environment), output_path)
        if registry:
            registry_path = output_dir / "registry.py"
            sources[registry_path] = _format_python(_render_registry(template_paths), registry_path)
        init = output_dir / "__init__.py"
        sources[init] = _format_python(_render_init(docstring, registry=registry), init)
    for path, source in sources.items():
        _validate_source(source, path)
    return sources


def _validate_module_names(template_paths: Iterable[Path]) -> None:
    """Reject template paths that would overwrite one generated module."""
    modules: dict[str, Path] = {}
    for path in template_paths:
        module_name = module_name_for_path(path)
        if module_name in _RESERVED_MODULE_NAMES:
            error_message = (
                f"template module name {module_name!r} for {path.as_posix()!r} is reserved for generated package "
                "code; rename the template and update the standalone template compiler before compiling"
            )
            raise ValueError(error_message)
        if (existing := modules.get(module_name)) is not None:
            error_message = (
                f"template module name collision: {existing.as_posix()!r} and {path.as_posix()!r} both map to "
                f"{module_name!r}; rename one template and update the standalone template compiler before compiling"
            )
            raise ValueError(error_message)
        modules[module_name] = path


def _validate_source(source: str, path: Path) -> None:
    """Validate generated Python before writing it to the repository."""
    try:
        ast.parse(source, filename=str(path), feature_version=(3, 10))
    except SyntaxError as error:  # pragma: no cover - protects generated output
        error_message = f"generated invalid Python for {path}: {error}"
        raise RuntimeError(error_message) from error


def _format_python(source: str, path: Path) -> str:
    """Apply the repository formatter while source is still in memory."""
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(path), "-"],
        check=True,
        capture_output=True,
        input=source,
        text=True,
    )
    return result.stdout


def _stale_paths(sources: dict[Path, str]) -> list[Path]:
    stale = [
        path for path, source in sources.items() if not path.is_file() or path.read_text(encoding="utf-8") != source
    ]
    stale.extend(_orphan_paths(sources))
    return sorted(set(stale), key=lambda path: path.relative_to(ROOT).as_posix())


def _orphan_paths(sources: dict[Path, str]) -> list[Path]:
    return sorted(
        (path for _, output_dir, _, _ in template_sets() for path in output_dir.glob("*.py") if path not in sources),
        key=lambda path: path.relative_to(ROOT).as_posix(),
    )


def main(argv: list[str] | None = None) -> int:
    """Generate renderers or report files that differ from generated output."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated template renderers are stale")
    parser.add_argument("--inventory", action="store_true", help="validate the current template feature subset")
    args = parser.parse_args(argv)
    sources = generated_sources()
    if args.inventory:
        print(f"validated {sum(path.name not in _PACKAGE_FILES for path in sources)} built-in templates")
    if (stale := _stale_paths(sources)) and args.check:
        for path in stale:
            print(path.relative_to(ROOT).as_posix(), file=sys.stderr)
        return 1
    if args.check:
        return 0
    for _, output_dir, _, _ in template_sets():
        output_dir.mkdir(parents=True, exist_ok=True)
    for path in _orphan_paths(sources):
        path.unlink()
    for path, source in sources.items():
        path.write_text(source, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
