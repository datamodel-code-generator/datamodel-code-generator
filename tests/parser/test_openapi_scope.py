@pytest.mark.parametrize("dot", [False, True])
@pytest.mark.parametrize("exports", [None, *AllExportsScope])
@pytest.mark.parametrize("existing", [False, True])
def test_api_empty_inventory(dot: bool, exports: AllExportsScope | None, existing: bool, tmp_path: Path) -> None:
    """Emit empty metadata while leaving an absent or existing output untouched."""
    output = tmp_path / "models.py"
    metadata = tmp_path / "metadata.json"
    if existing:
        output.write_bytes((EXPECTED / "existing-output.txt").read_bytes())
    result = generate(
        SOURCE / "contentless.json",
        input_file_type=InputFileType.OpenAPI,
        openapi_scopes=[OpenAPIScope.Api],
        output=output,
        emit_model_metadata=metadata,
        treat_dot_as_module=dot,
        all_exports_scope=exports,
        formatters=[],
        disable_timestamp=True,
    )
    assert_output(metadata.read_text(), EXPECTED / "empty-metadata.txt")
    assert_output(
        json.dumps({"result": result, "output_exists": output.exists()}, indent=2) + "\n",
        EXPECTED / f"empty-state-{existing}.txt",
    )
    if existing:
        assert_output(output.read_text(), EXPECTED / "existing-output.txt")


