def inventory(path: Path, *, logical_text: bool = False) -> dict[str, str]:
    """Hash raw bytes for transaction equality; serialize text inventories with LF."""
    files = sorted(path.rglob("*")) if path.is_dir() else [path] if path.exists() else []
    return {
        str(file.relative_to(path)) if path.is_dir() else file.name: hashlib.sha256(
            file.read_text(encoding="utf-8").encode("utf-8") if logical_text else file.read_bytes()
        ).hexdigest()
        for file in files
        if file.is_file()
    }


def cli_arguments(row: dict[str, Any], fixture: Path, output: Path, options: dict[str, Any]) -> list[str]:
    """Express the recorded public options as CLI arguments."""
    args = [
        "--input",
        str(fixture),
        "--input-file-type",
        row["input"],
        "--output-model-type",
        row["backend"],
        "--output",
        str(output),
        "--disable-timestamp",
        "--formatters",
        "builtin",
    ]
    for key, value in options.items():
        flag = "--" + key.replace("_", "-")
        if isinstance(value, bool):
            if value:
                args.append(flag)
        elif isinstance(value, list):
            args.extend([flag, *value])
        else:
            args.extend([flag, json.dumps(value) if isinstance(value, dict) else str(value)])
    return args


def public_generation(
    row: dict[str, Any], fixture: Path, output: Path, options: dict[str, Any], run_cli: Any
) -> dict[str, Any]:
    """Invoke the public generator or the existing CLI harness."""
    if row["entry"] == "api":
        generate(
            fixture,
            input_file_type=InputFileType(row["input"]),
            output_model_type=DataModelType(row["backend"]),
            output=output,
            disable_timestamp=True,
            formatters=[Formatter.BUILTIN],
            **options,
        )
        return {"success": True}
    args = cli_arguments(row, fixture, output, options)
    expected = Exit.ERROR if "Error" in row["candidate_expectation"] else Exit.OK
    returned = run_cli(args, expected_exit=expected)
    return {"success": returned == Exit.OK, "exit": int(returned)}


def generation_row(row: dict[str, Any], fixture: Path, output: Path, run_cli: Any) -> dict[str, Any]:
    """Run one recorded invocation, retaining errors and output state."""
    options = dict(row.get("options", {}))
    if "custom_template_dir" in options:
        options["custom_template_dir"] = Path(options["custom_template_dir"])
    stdout, stderr = io.StringIO(), io.StringIO()
    record: dict[str, Any] = {}
    with redirect_stdout(stdout), redirect_stderr(stderr):
        try:
            record.update(public_generation(row, fixture, output, options, run_cli))
        except Exception as exc:  # ruff: ignore[blind-except]
            record.update(success=False, error={"type": type(exc).__name__, "message": str(exc)})
    record.update(stdout=stdout.getvalue(), stderr=stderr.getvalue(), output_exists=output.exists())
    return record


def module_from_output(output: Path) -> Any:
    """Import actual generated bytes using the recorded standard import procedure."""
    spec = importlib.util.spec_from_file_location("allof_models", output)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def native_value(row: dict[str, Any], module: Any, cls: Any) -> tuple[Any, Any]:
    """Construct and serialize using only the selected backend native APIs."""
    payload = row["payload"]
    match row["backend"]:
        case "pydantic_v2.BaseModel" | "pydantic_v2.dataclass":
            from pydantic import TypeAdapter

            adapter = TypeAdapter(cls)
            instance = adapter.validate_python(payload)
            value = adapter.dump_python(instance, mode="json")
        case "msgspec.Struct":
            import msgspec

            instance = msgspec.convert(payload, type=cls)
            value = msgspec.to_builtins(instance)
        case "dataclasses.dataclass":
            match row["case"]:
                case "field_recursion":
                    instance = cls(a=payload["a"], child=module.B(b=payload["child"]["b"], parent=None))
                case "reuse":
                    instance = cls(left=module.A(**payload["left"]), right=module.B(**payload["right"]))
                case _:
                    instance = cls(**payload)
            value = dataclasses.asdict(instance)
        case "typing.TypedDict":
            instance = cls(**payload)
            value = dict(instance)
    return instance, value


def annotation_fact(value: Any) -> str:
    """Record forward expressions/modules; resolved hints separately retain owner semantics."""
    if isinstance(value, typing.ForwardRef):
        return f"ForwardRef({value.__forward_arg__!r}, module={value.__forward_module__!r})"
    return str(value)


def native_row(row: dict[str, Any], output: Path, target: str) -> dict[str, Any]:
    """Observe hints, field order, construction and serialization without another validator."""
    module = module_from_output(output)
    cls = getattr(module, target)
    fields = (
        list(cls.model_fields)
        if hasattr(cls, "model_fields")
        else [field.name for field in dataclasses.fields(cls)]
        if dataclasses.is_dataclass(cls)
        else list(cls.__struct_fields__)
        if hasattr(cls, "__struct_fields__")
        else list(cls.__annotations__)
    )
    facts = {
        "annotations": {key: annotation_fact(value) for key, value in cls.__annotations__.items()},
        "resolved_type_hints": {key: str(value) for key, value in typing.get_type_hints(cls).items()},
        "bases": [base.__module__ + "." + base.__qualname__ for base in cls.__bases__],
        "fields": fields,
    }
    record: dict[str, Any] = {"facts": facts, "baseline_facts_equal": facts == row["baseline_facts"]}
    try:
        instance, value = native_value(row, module, cls)
        record.update(
            success=True,
            serialized=value,
            serialized_order=list(value),
            constructed_type=type(instance).__module__ + "." + type(instance).__name__,
            baseline_value_equal=value == row.get("baseline_serialized"),
            baseline_order_equal=list(value) == row.get("baseline_serialized_order"),
        )
    except Exception as exc:  # ruff: ignore[blind-except]
        error = {"type": type(exc).__name__, "message": str(exc)}
        record.update(success=False, error=error, baseline_error_equal=error == row.get("baseline_error"))
    record["baseline_outcome_equal"] = record["success"] == row["baseline_success"]
    return record


def output_observation(record: dict[str, Any], row: dict[str, Any], output: Path) -> None:
    """Record final declarations, import behavior and byte equality to the preserved witness."""
    raw_digest = hashlib.sha256(output.read_bytes()).hexdigest()
    source = output.read_text(encoding="utf-8")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    baseline_digest = row["baseline_output_sha256_crlf" if os.linesep == "\r\n" else "baseline_output_sha256"]
    tree = ast.parse(source)
    declarations = [
        {"kind": "class", "name": node.name, "bases": [ast.unparse(base) for base in node.bases]}
        for node in tree.body
        if isinstance(node, ast.ClassDef)
    ]
    record.update(
        output_text_sha256=digest,
        baseline_bytes_equal=raw_digest == baseline_digest,
        declarations=declarations,
        baseline_declarations_equal=declarations == row["baseline_declarations"],
    )
    try:
        module_from_output(output)
        record["import"] = {"success": True}
    except Exception as exc:  # ruff: ignore[blind-except]
        record["import"] = {"success": False, "error": {"type": type(exc).__name__, "message": str(exc)}}
    record["baseline_import_equal"] = record["import"]["success"] == row["baseline_import_success"]


def inheritance_report(tmp_path: Path, run_cli: Any) -> str:
    """Produce the selected recorded generation/native report and six transaction records."""
    data = Path("tests/data/allof_model_inheritance")
    cases = json.loads((data / "cases.json").read_text())
    report: dict[str, Any] = {"generations": [], "native": [], "transactions": []}
    outputs = []
    for index, row in enumerate(cases["generations"]):
        folder = tmp_path / str(index)
        folder.mkdir()
        fixture = folder / row["staged_input_basename"]
        fixture.write_bytes((data / "fixtures" / row["fixture"]).read_bytes())
        output = folder / "models.py"
        outputs.append(output)
        record = generation_row(row, fixture, output, run_cli)
        record.update(case=row["case"], backend=row["backend"], entry=row["entry"], input=row["input"])
        if output.exists():
            output_observation(record, row, output)
        report["generations"].append(record)
    for row in cases["native"]:
        index = row["generation"]
        record = native_row(row, outputs[index], cases["generations"][index]["target"])
        record.update(case=row["case"], backend=row["backend"])
        report["native"].append(record)
    preexisting = Path("tests/data/expected/main/jsonschema/allof_mro.py")
    for split, exists in ((False, True), (True, False), (True, True)):
        for entry in ("cli", "api"):
            folder = tmp_path / f"transaction-{split}-{exists}-{entry}"
            folder.mkdir()
            output = folder / ("package" if split else "models.py")
            if exists:
                if split:
                    output.mkdir()
                (output / "models.py" if split else output).write_bytes(preexisting.read_bytes())
            before = inventory(output)
            before_text = inventory(output, logical_text=True)
            row = {
                "entry": entry,
                "input": "openapi",
                "backend": "pydantic_v2.BaseModel",
                "candidate_expectation": "new generation Error before output",
                "options": {"module_split_mode": "single"} if split else {},
            }
            record = generation_row(row, data / "fixtures/conflict.openapi.json", output, run_cli)
            record.update(
                split=split,
                preexisting=exists,
                entry=entry,
                before=before_text,
                after=inventory(output, logical_text=True),
                preexisting_bytes_equal=before == inventory(output),
            )
            report["transactions"].append(record)
    sys.modules.pop("allof_models", None)
    text = json.dumps(report, indent=2) + "\n"
    return text.replace(str(tmp_path), "$WORK")


def late_local_base_report(entry: str, tmp_path: Path, run_cli: Any) -> str:
    """Record tree reuse rejecting a child moved to shared.py before its base."""
    output = tmp_path / "package"
    output.mkdir()
    (output / "existing.py").write_text("existing = True\n")
    row = {
        "entry": entry,
        "input": "jsonschema",
        "backend": "pydantic_v2.BaseModel",
        "candidate_expectation": "new generation Error before output",
        "options": {"reuse_model": True, "reuse_scope": "tree"},
    }
    record = generation_row(
        row,
        Path("tests/data/allof_model_inheritance/fixtures/late_local_base"),
        output,
        run_cli,
    )
    record["files"] = {path.name: path.read_text() for path in output.iterdir()}
    return json.dumps(record, indent=2) + "\n"
