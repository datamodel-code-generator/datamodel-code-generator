REFS_SUFFIX = ".refs"
REFS_HEADER = (
    "# Generated by pytest. Do not edit by hand: run the tests instead (pytest <test>), then git add -A tests.\n"
    "# Each line records the expected output a test compares; to accept changed output add --inline-snapshot=fix "
    "(see AGENTS.md).\n"
)
"""The first lines of every sidecar pytest writes; the parser skips the ``#`` lines a sidecar starts with."""
FACTS = ("python", "formatter", "black", "isort", "platform")
_TOOL_VERSION = re.compile(r"(?:\d[0-9A-Za-z.+-]*)?")
_FACT_SHAPES = {
    "python": re.compile(r"\d+\.\d+"),
    "formatter": re.compile(r"builtin|external"),
    "black": _TOOL_VERSION,
    "isort": _TOOL_VERSION,
    "platform": re.compile(r"linux|darwin|win32"),
}
_NAME_BYTES = 255
PAYLOAD_DECODED_LIMIT = 4 * 1024 * 1024
"""The largest decoded payload, in bytes of JSON, that CI prints and ``--apply`` accepts."""
BROKEN = "broken"
"""A sidecar line pytest cannot parse: a hand edit that only restoring or repairing the file undoes."""
CONFLICT = "conflict"
"""Two lines for one item and label with different storage or flags, as a merge keeping both sides leaves them."""
ORDER = "order"
"""A sidecar whose lines parse but are not sorted, or repeat: a local run rewrites it in the form pytest writes."""
_WINDOWS_INVALID = re.compile(r'[<>:"/\\|?*\x00-\x1f]')
_CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f\u2028\u2029]")
"""Control characters, including every line separator ``str.splitlines`` knows; no label, item or test holds one."""
_DRIVE = re.compile(r"[A-Za-z]:")
_BAD_PARTS = frozenset({"", ".", ".."})
_MAX_NAME = 120


KEEP = object()
