"""Stored expected units, the ``.refs`` reference index, and how create and fix runs update them.

Every comparison of a test item against stored expected output is a reference: the item and a label, a name relative
to ``tests/data/expected``. A label names a file (``main/x.py``), a whole tree (``main/pkg/``), or the files of a tree
that match a pattern (``main/pkg//*.py``). Each test module keeps its references in a sidecar next to it
(``tests/main/test_x.refs``), written only by pytest. A reference stores its unit at its label unless the line names
other storage (``= main/y.py``), so tests with identical output can share one stored unit.

The resolver turns what a run observed into new sidecar lines and file operations. It changes a stored unit in place
only when every reference to it changed the same way; otherwise the changed references get their own unit (copy on
write), equal contents are merged, and units that lose their last reference are deleted. It never changes what an
unobserved reference compares against, and every write and delete goes through ``write_files``, which refuses
anything outside ``tests/data/expected`` and the sidecars. This module uses the standard library only, so scripts can
read the index.
"""

